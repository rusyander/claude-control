/**
 * Чужой текст, пригодный для показа: сначала БЕЗ СЕКРЕТОВ, потом обрезка.
 *
 * Общий модуль, потому что чужой текст приходит с трёх сторон — проба, вызов
 * агента, эмбеддинги, — а правило у него одно. Второй копией это правило
 * расходилось бы молча: сервер контура вполне может отразить присланный ключ в
 * теле ошибки («unknown api key sk-…»), а такой текст оседает в `state.json` и
 * уезжает экспортом настроек на другую машину.
 *
 * ПОРЯДОК ВАЖЕН: обрезать первым значило бы резать уже отражённый ключ, а
 * половина ключа наружу — это тот же ключ наружу.
 */

/** Сколько символов чужого текста показываем. */
export const FOREIGN_TEXT_LIMIT = 300;

/**
 * Убрать секреты: свой ключ — по значению, всё похожее на чужой — по форме.
 *
 * Короткий ключ по значению не ищется: подстрока в шесть символов вырезала бы
 * куски осмысленного текста. Дыры здесь нет, и держится это НЕ на удаче:
 * `assertToken` (`store.ts`) короче `MIN_KEY_LENGTH` ключ не сохраняет вовсе —
 * значит, отражённого контуром ключа короче порога не бывает. Тронув один из
 * двух порогов, трогайте второй.
 */
export function redactSecrets(text: string, token: string | undefined): string {
  const hidden = '«ключ»';
  let safe = text;
  if (token && token.length >= 8) safe = safe.split(token).join(hidden);
  return safe
    .replace(/\bBearer\s+[\w.-]{8,}/gi, `Bearer ${hidden}`)
    .replace(/\b(?:sk|pk|api|key|token)[-_][\w.-]{8,}/gi, hidden);
}

/** Кусок чужого текста для показа: сначала чистка, потом обрезка. */
export function foreignTail(
  text: string,
  token: string | undefined,
  limit = FOREIGN_TEXT_LIMIT,
): string {
  return redactSecrets(text.trim(), token).slice(0, limit);
}

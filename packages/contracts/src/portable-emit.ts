import type { FidelityVerdict } from './portable-fidelity.ts';

/**
 * Словарь ИСХОДОВ записи: что эмиттер сделал с одной записью канона у цели.
 *
 * Уровень верности (`portable-fidelity.ts`) — это ПРОГНОЗ: как запись доедет.
 * Исход — то, что с ней произошло на самом деле. Разводить их обязательно:
 * прогноз «нативно» и пустой каталог у цели — разные утверждения, и П2.4
 * сравнивает как раз эти два столбца («обещано» против «проверено»).
 *
 * Второй таблицы «уровень → исход» здесь нет: исход вычисляется из приговора
 * ОДНИМ местом (`domains/portability/emit/sections.ts`), а приговор — из фактов
 * цели. Ветка по идентификатору CLI не появляется ни там, ни тут.
 *
 * - `written` — запись легла в файл цели её собственным адаптером формата;
 * - `already_available` — цель ЧИТАЕТ тот же каталог, в котором запись уже
 *   лежит: копия создала бы второй экземпляр, который дальше разойдётся с
 *   первым правками. Уровень при этом нативный, а записей на диск ноль;
 * - `runtime_only` — на диск не ложится ничем: уровень держится запуском через
 *   панель (`emulated`) или проводом (`wired`), и владеют этим волны П3 и П4;
 * - `not_transferable` — перенести нечем, причина в приговоре;
 * - `disabled_at_source` — запись у источника ВЫКЛЮЧЕНА, а формат цели
 *   выключателя не имеет: записать её значило бы включить то, что человек
 *   выключил сам. Не переносим и говорим об этом (инвариант 6 в другую сторону);
 * - `refused_by_target` — формат цели эту запись не принимает (описание длиннее
 *   его потолка, файл с неразобранной шапкой). Подрезать или переписать чужой
 *   файл панель не станет: это догадка о чужом формате;
 * - `script_missing` — команда записи зовёт скрипт, которого на диске нет. У
 *   цели она не регистрируется: механизм у цели есть и запись бы легла, но
 *   легла бы заведомо неисполнимой — хук с несуществующим скриптом падает на
 *   каждом событии. Отличается от `not_transferable` тем, что причина НЕ в
 *   приговоре: уровень верности здесь нативный, и в отчёте это видно;
 * - `collision_needs_choice` — у цели УЖЕ лежит запись с этим именем и другим
 *   содержимым. Выбор между ними — человеческий: эмиттер не решает, чья версия
 *   важнее, и ничего не перезаписывает (инвариант 10 разрешает лишь повтор
 *   того же самого).
 */
export const emitOutcomes = [
  'written',
  'already_available',
  'runtime_only',
  'not_transferable',
  'disabled_at_source',
  'script_missing',
  'refused_by_target',
  'collision_needs_choice',
] as const;

export type EmitOutcome = (typeof emitOutcomes)[number];

export function isEmitOutcome(value: string): value is EmitOutcome {
  return (emitOutcomes as readonly string[]).includes(value);
}

/**
 * Что эмиттер собирается сделать с одной записью.
 *
 * Строка есть у КАЖДОЙ записи паспорта, включая непереносимые: отсутствие
 * строки человек читает как «эта запись доехала», и ровно так отчёт начинает
 * врать молчанием (то же правило, что у строк отчёта верности).
 *
 * `file` — путь файла цели, в который запись легла или ляжет; у исходов без
 * записи на диск он `null`, и подставлять туда «ближайший» файл нельзя: это
 * утверждение о чужом конфиге, которого никто не делал.
 */
export interface EmitEntry {
  readonly itemId: string;
  /** Вид записи канона — строкой, как и в отчёте верности: словарь видов живёт в `portable-env.ts`. */
  readonly kind: string;
  /** Одна фраза человеку: та же, что у записи канона. */
  readonly intent: string;
  readonly outcome: EmitOutcome;
  /** Прогноз П1: уровень, причина, условие. Эмиттер его ИСПОЛНЯЕТ, а не пересчитывает. */
  readonly verdict: FidelityVerdict;
  readonly file: string | null;
}

/**
 * Исход, при котором запись доедет до цели без панели. Считается отсюда, а не
 * пишется рукой на экране: «перенесено» — это `written` плюс `already_available`,
 * и второе легко потерять, потому что файлов оно не создаёт.
 */
export function landsAtTarget(outcome: EmitOutcome): boolean {
  return outcome === 'written' || outcome === 'already_available';
}

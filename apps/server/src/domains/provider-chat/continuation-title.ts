/**
 * Название продолжения, которое сервер заводит задачей ядра (перенос незакрытой работы в другой
 * CLI). Суффикс не копится: «Группа · работа · продолжение 3» читается,
 * «… · продолжение · продолжение · продолжение» — нет.
 */
export function continuationTitle(title: string, depth: number): string {
  const base = title.replace(/\s*·\s*продолжение(\s+\d+)?\s*$/u, '').trim() || 'Разговор';
  return `${base} · продолжение${depth > 1 ? ` ${depth}` : ''}`;
}

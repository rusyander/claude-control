import type { ReactNode } from 'react';

export interface InstructionsDocumentProps {
  /** Имя файла: в подписи поля, в пустом состоянии и для подсветки Markdown. */
  fileName: string;
  /** Абсолютный путь — строка источника называет, какой файл правится. */
  filePath: string;
  /** Есть ли файл на диске: нет — вместо пустого просмотра приглашение написать. */
  exists: boolean;
  /** Текст в поле — черновик, если он есть, иначе то, что на диске. */
  value: string;
  onChange: (value: string) => void;
  isDirty: boolean;
  /**
   * Файл на диске ушёл от текста, с которого начата правка (его записал агент,
   * редактор): «Сохранить» заменит ту запись — документ говорит это словами.
   */
  changedElsewhere?: boolean;
  isSaving: boolean;
  onSave: () => void;
  onRevert: () => void;
  /**
   * Растёт на каждой замене текста не руками — загрузка с диска, отмена правок:
   * редактор по нему берёт текст заново, а набранное не перетирает.
   */
  version: number;
  /** Какой CLI перечитает файл и когда — строкой под документом. */
  restartHint: string;
  /** Раскладка файлов инструкций (у Claude): широкий экран — сбоку, узкий — над текстом. */
  aside?: ReactNode;
}

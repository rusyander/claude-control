import type { SplitPlanView } from '@agentdeck/contracts/chat-handoff';

/**
 * Итог разбора одним словом — подпись фишки в хабе.
 *
 * Отдельной функцией, потому что состояний стало пять и одно из них
 * противоположно соседнему по последствиям: «не получен» значит, что группы
 * ПОШЛИ как предложено, а «оборван перезапуском» — что не пошли вовсе и стоят
 * на вопросе человеку. Пока это решалось тернарником в разметке, второй случай
 * показывался подписью первого и врал ровно там, где человеку надо действовать.
 */
export type TriageChipState = 'running' | 'stopped' | 'applied' | 'missing' | 'interrupted';

/**
 * `live` — прогон разбора идёт прямо сейчас (строка разбора или узел дерева).
 * Итога ещё нет, а прогон стоит (пауза дерева, остановка, перезапуск
 * разделения) — это «разбор не идёт», а не «идёт разбор»: иначе фишка говорила
 * «идёт» часами над деревом без единого прогона (wp9a, открытый пункт 1).
 */
export function triageChipState(triage: SplitPlanView['triage'], live: boolean): TriageChipState {
  // Поле `triage` появляется только когда прогон кончился, чем бы ни кончился;
  // до того запись конвейера уже есть, и чем он занят — знает только прогон.
  if (!triage) return live ? 'running' : 'stopped';
  if (triage.received) return 'applied';
  return triage.interrupted ? 'interrupted' : 'missing';
}

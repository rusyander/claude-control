/**
 * Владелец прерывателя текущего прогона песочницы.
 *
 * Вынесено из хука по двум причинам, и обе — ошибки, которые здесь заперты.
 *
 * Первая: прогон не прерывался при уходе со страницы. Хук снимал прогон только
 * по кнопке «Остановить», а вкладка модалки размонтируется молча — соединение
 * оставалось открытым, поэтому сервер не видел `close`, не звал `run.stop()`,
 * и временный Claude дорабатывал прогон до конца, тратя токены впустую.
 *
 * Вторая: завершение СТАРОГО прогона снимало учёт нового. Новый запуск
 * прерывает предыдущий, но `finally` прерванного выполняется уже после того,
 * как новый записал свой контроллер, — и обнулял его. После этого ни
 * «Остановить», ни уход со страницы живой прогон не прерывали. Поэтому
 * `finish` требует свой контроллер и сбрасывает запись, только если она ещё
 * его: чужой прогон не трогаем.
 */
export interface RunAbort {
  /** Начать прогон: прежний прерываем, новый становится текущим. */
  start: () => AbortController;
  /** Завершить свой прогон — запись снимается, только если она ещё его. */
  finish: (controller: AbortController) => void;
  /** Прервать текущий прогон (кнопка «Остановить», уход со страницы). */
  abort: () => void;
}

export function createRunAbort(): RunAbort {
  let current: AbortController | undefined;

  return {
    start() {
      current?.abort();
      current = new AbortController();
      return current;
    },
    finish(controller) {
      if (current === controller) current = undefined;
    },
    abort() {
      current?.abort();
      current = undefined;
    },
  };
}

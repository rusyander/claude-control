/**
 * Dev-сервер проекта, запущенный панелью прямо из ряда вкладки-проекта в чате.
 *
 * Реестр запущенных серверов живёт в памяти серверного процесса (см.
 * `domains/project-runner.ts`): у каждого проекта свой порт и URL, а браузер
 * открывается автоматически, как только порт начал слушать. Здесь — только
 * форма данных, которой сервер описывает состояние клиенту.
 */

/** Стадия жизни запущенного dev-сервера. */
export type ProjectRunnerStatus = 'starting' | 'running' | 'stopped' | 'error';

/** Состояние одного dev-сервера проекта — как его видит клиент. */
export interface ProjectRunnerView {
  /** Абсолютный путь каталога проекта (нормализованный) — ключ реестра. */
  path: string;
  /** Порт, на котором поднимается сервер (выбран из свободных). */
  port: number;
  /** Адрес, по которому открылся браузер и работает ссылка «Перейти». */
  url: string;
  /** Стадия: поднимается / работает / остановлен / ошибка. */
  status: ProjectRunnerStatus;
  /** Команда запуска, как она показана пользователю (`pnpm run dev` и т.п.). */
  command: string;
  /** Момент старта, ISO. */
  startedAt: string;
  /** Текст ошибки, если запуск не удался. */
  error?: string;
}

/** Ответ на запрос «а можно ли вообще запустить этот проект». */
export interface ProjectRunnerInfo {
  /** Есть ли команда запуска (скрипт dev/start или оверрайд). */
  runnable: boolean;
  /** Команда, которая будет запущена, — для подсказки на кнопке. */
  command?: string;
  /** Почему запустить нельзя (нет dev/start и нет оверрайда). */
  reason?: string;
}

/**
 * Черновик поля вне состояния React: читать и писать его может кто угодно, а
 * перерисовывается только тот, кто подписан (`useDraftValue`).
 */
export interface DraftBox {
  /** Текущий текст — без подписки, для отправки и прочих разовых чтений. */
  get: () => string;
  /** Новый текст: сохраняется под текущим ключом и будит подписчиков. */
  set: (value: string) => void;
  subscribe: (listener: () => void) => () => void;
}

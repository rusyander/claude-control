import type { EnvItemKind, EnvScope } from './portable-env.ts';
import type { TransferPlan } from './portable-transfer.ts';

/**
 * Подписка: канон — источник, чужой CLI — его проекция (П5.1).
 *
 * Отличие от разового переноса ровно одно и оно в направлении времени. Перенос
 * отвечает на вопрос «перенеси сейчас то, что есть»; подписка — на вопрос
 * «держи эту цель согласованной с каноном и дальше». Поэтому здесь появляется
 * то, чего у переноса нет: ПАМЯТЬ о том, что панель спроецировала в прошлый
 * раз, запись за записью.
 *
 * Память пофайловая не годится: у цели записи сливаются в один файл
 * (`settings.json` собирает хуки и переменные), и хеш файла отвечает «в файле
 * что-то не то», а не «разошлась вот эта запись». Пересборка по хешу файла
 * переписывала бы весь файл из-за одной правки — то самое, чего критерий
 * приёмки требует не делать.
 *
 * Подписка включается ПО СЛОЮ: «скиллы во все CLI, права никуда» — законный
 * набор, и он же самый частый. Слой здесь — вид записи канона (`EnvItemKind`),
 * а не строка матрицы верности: проецируется запись, уровень — её свойство.
 *
 * Модуль без zod, как и остальные `portable-*`: точка экспорта
 * `@agentdeck/contracts/portable-subscribe`, бочка не используется.
 */

/**
 * Чей дом панель считает каноном.
 *
 * Лежит в контракте, а не в маршруте, потому что от этого значения зависит
 * ЭКРАН: после исхода `canon` устаревает паспорт канона, а не цели, и веб,
 * знающий владельца истины по своей копии строки, разошёлся бы с сервером
 * молча — показав свежим тот паспорт, который только что переписали.
 *
 * Параметром запроса не становится ни при каких условиях: владелец истины один
 * и человеком не выбирается — иначе подписка была бы вторым переносом.
 */
export const PANEL_CANON_PROVIDER = 'claude';

/**
 * Чем запись была в момент, когда панель её спроецировала.
 *
 * Вид хранится рядом с отпечатком, а не выводится из `id`. Выводить его из
 * строки идентификатора значило бы поставить на разбор имени решение, от
 * которого зависит отписка: запись, чей вид не назван, невозможно отличить от
 * записи ИСЧЕЗНУВШЕЙ, и отписка от слоя «скиллы» прочиталась бы как удаление
 * каждого скилла из канона.
 */
export interface SubscriptionMark {
  readonly kind: EnvItemKind;
  /** Отпечаток записи — `envItemFingerprintInput`, захешированный сервером. */
  readonly fingerprint: string;
  /**
   * Файл цели, в который запись легла. По нему расхождение файла переводится в
   * расхождение ЗАПИСЕЙ: хеш отвечает «в этом файле что-то не то», а удерживать
   * надо то, что панель собралась в него написать.
   *
   * `null` у записи, доехавшей без записи на диск (`already_available`), и у
   * отметок, поставленных до П5.2. Второе — не то же самое, что первое, и
   * трактуется fail-closed: при любом расхождении отметка без файла считается
   * удержанной, потому что «не знаю, где она лежит» — не повод переписать.
   */
  readonly file: string | null;
}

/**
 * Подписка одной цели на одном уровне.
 *
 * Источник в ней не назван НАМЕРЕННО. Канон подписки — собственная среда
 * панели, и пара «источник → цель» превратила бы подписку во второй перенос,
 * у которого истин столько же, сколько источников. Владелец истины один, и он
 * не выбирается.
 */
export interface EnvSubscription {
  /** Целевой CLI. */
  readonly target: string;
  readonly scope: EnvScope;
  /** Каталог проекта на уровне проекта; у глобальной подписки не задан. */
  readonly project?: string;
  /**
   * Слои, на которые цель подписана. Пустой список — законное состояние
   * «подписки больше нет ни на что»; запись при этом хранится дальше, потому
   * что в ней лежит память о том, что уже спроецировано, и выбросить её
   * значило бы предложить человеку переписать цель заново с нуля.
   */
  readonly layers: readonly EnvItemKind[];
  /**
   * Версия канона, которой построена ПРОЕКЦИЯ. Не текущая версия словаря:
   * разойтись они могут только после обновления панели, и тогда проекция
   * помечается устаревшей, а не пересобирается молча (инвариант плана).
   */
  readonly canonVersion: number;
  /**
   * Память подписки: `id записи` → чем она была, когда её спроецировали. По ней
   * и считается, что разошлось.
   */
  readonly marks: Readonly<Record<string, SubscriptionMark>>;
  /**
   * Хеш каждого файла цели, каким панель его ОСТАВИЛА. Расхождение с диском —
   * предмет П5.2. Лежит в подписке, а не в следе переноса, потому что
   * переживает любое число пересборок.
   */
  readonly files: Readonly<Record<string, string>>;
  /**
   * Корень цели, в который писала проекция: дом CLI или каталог проекта.
   *
   * Хранится, потому что имя резервной копии переноса — это `<id цели>-<путь от
   * корня>`, и без корня лента изменений не умеет назвать копии подписки. Взять
   * корень заново у каталога нельзя: он ответит сегодняшним, а копии лежат под
   * тем, что был в момент записи. Ни разу не синхронизированная подписка — `null`.
   */
  readonly root: string | null;
  /** Когда проекция собиралась в последний раз (ISO); ни разу — `null`. */
  readonly syncedAt: string | null;
}

/**
 * Что стало с одной записью канона с прошлой пересборки.
 *
 * `gone` — запись исчезла из канона (человек удалил хук в панели). Строка о ней
 * есть, а удаления у цели нет: снять запись у чужого CLI — действие, обратного
 * которому у подписки не предусмотрено, и оно требует разговора (П5.2), а не
 * побочного эффекта пересборки. Молчания здесь быть не должно: без строки
 * человек прочитал бы пересборку как «цель совпадает с каноном».
 */
export type SubscriptionRowState = 'new' | 'changed' | 'unchanged' | 'gone';

export interface SubscriptionRow {
  readonly itemId: string;
  /** Вид записи; у `gone` — вид, которым её спроецировали в прошлый раз. */
  readonly kind: EnvItemKind | null;
  readonly state: SubscriptionRowState;
  /**
   * Файл цели, правка человека в котором держит эту запись; `null` — не
   * удержана. Отдельное поле, а не значение `state`: состояние отвечает, что
   * стало с записью В КАНОНЕ, и сложи мы туда же ответ про диск, «изменилась» и
   * «изменилась, но не поедет» стали бы одним словом (П5.2).
   */
  readonly heldBy: string | null;
}

/**
 * Что стало с файлом цели, который панель писала (П5.2).
 *
 * `edited` — содержимое отличается от того, каким панель файл оставила.
 * `missing` — файла нет вовсе: человек удалил его или каталог. Разводятся
 * потому, что исходы у них разные — правку можно взять в канон, а удаление
 * нечего брать, и предложить «взять в канон» пустоту значило бы предложить
 * стереть записи, которых человек не трогал.
 */
export type SubscriptionDriftState = 'edited' | 'missing';

/**
 * Файл цели, разошедшийся с тем, каким панель его оставила.
 *
 * Отпечаток файла — ЕДИНСТВЕННЫЙ надёжный сторож руки человека: импортёр видит
 * только то, что умеет разобрать, и правка в том, чего он не моделирует
 * (комментарий, чужой ключ, порядок), прошла бы мимо него незамеченной. Поэтому
 * сторожит хеш, а импортёр отвечает на следующий вопрос — что именно взять в
 * канон, если человек так решит.
 */
export interface SubscriptionDrift {
  readonly filePath: string;
  readonly state: SubscriptionDriftState;
  /** Записи, которые панель в этот файл спроецировала, — их и держит. */
  readonly itemIds: readonly string[];
  /** Слои этого файла: их снимет исход `unsubscribe`, и человек видит, чего лишается. */
  readonly layers: readonly EnvItemKind[];
}

/**
 * Три исхода расхождения. Четвёртого — «перезаписать молча» — нет намеренно:
 * ровно его отсутствие и есть предмет П5.2.
 *
 * - `canon` — правка человека уезжает В КАНОН импортёром: панель читает файл
 *   цели её собственным импортёром и пишет записи в свои файлы тем же
 *   переносом. Текстовой склейки здесь нет и быть не может — склейка означала
 *   бы, что канон пополняется тем, чего панель не разобрала;
 * - `projection` — у цели остаётся проекция: файл пересобирается из канона,
 *   правка человека теряется. Решение его, и до него молчаливым оно не бывает;
 * - `unsubscribe` — панель перестаёт писать в этот файл: снимаются ВСЕ его слои.
 *   Оставить один подписанным значило бы открыть то же расхождение на следующей
 *   пересборке.
 */
export type SubscriptionDriftResolution = 'canon' | 'projection' | 'unsubscribe';

export function isSubscriptionDriftResolution(value: string): value is SubscriptionDriftResolution {
  return value === 'canon' || value === 'projection' || value === 'unsubscribe';
}

/**
 * Что сделает выбранный исход — до того, как он сделан.
 *
 * `transfer` считается тем же механизмом, что у переноса и пересборки, и по той
 * же причине: план, который считается иначе, чем применяется, врёт ровно там,
 * где ему верят. У `unsubscribe` его нет — записи не трогаются вовсе, и
 * показывать нечего, кроме слоёв, которые отпишутся.
 */
export interface SubscriptionDriftPlan {
  readonly filePath: string;
  readonly state: SubscriptionDriftState;
  readonly resolution: SubscriptionDriftResolution;
  readonly transfer: TransferPlan | null;
  /** Слои, которые снимет `unsubscribe`; у остальных исходов пуст. */
  readonly layers: readonly EnvItemKind[];
}

/**
 * Почему пересборка не предлагается, хотя подписка есть. Словарь закрыт: каждое
 * значение — отдельный экран разговора с человеком, а не строка лога.
 */
export type SubscriptionHoldReason =
  /** Ни один слой не подписан — пересобирать нечего по просьбе человека. */
  'no_layers';

/**
 * Почему проекция пересобирается ЦЕЛИКОМ, а не по разошедшимся записям.
 *
 * Отдельно от `hold`, потому что это противоположный ответ: удержание — «не
 * буду», пересборка с нуля — «буду, и вот всё сразу». Прежде версия канона
 * давала здесь удержание, из которого не было выхода: отпечатки сравнивать
 * нельзя, а обновить их могла только удачная пересборка — то есть ровно то, что
 * удержание запрещало. Выходом оставалась отписка, а она забывает и хеши
 * файлов, то есть снимает сторожа руки человека (П5.2) на ровном месте.
 *
 * - `canon_version` — отпечатки считала другая версия словаря. Сравнивать их
 *   нельзя, поэтому ни одна запись не объявляется совпавшей: все едут как
 *   `changed`/`new`, а хеши файлов и сторож руки остаются в силе — они считаются
 *   не словарём, а по содержимому файла.
 */
export type SubscriptionRebuildReason = 'canon_version';

/**
 * План пересборки: что разошлось и что из-за этого будет записано.
 *
 * `transfer` — обычный план переноса, но собранный по РАЗОШЕДШЕМУСЯ
 * подмножеству, тем же эмиттером и с тем же честным диффом из песочницы.
 * Второго механизма показа у подписки нет намеренно: план, который считается
 * иначе, чем применяется, врёт ровно там, где ему верят.
 *
 * `null` у `transfer` — не ошибка: «всё совпадает» и «пересборка удержана»
 * выглядят одинаково по файлам и по-разному по причине, и причину несёт `hold`.
 */
export interface SubscriptionSyncPlan {
  readonly key: string;
  readonly target: string;
  readonly scope: EnvScope;
  readonly layers: readonly EnvItemKind[];
  /** Строка о КАЖДОЙ записи подписанных слоёв, включая совпавшие. */
  readonly rows: readonly SubscriptionRow[];
  readonly transfer: TransferPlan | null;
  /** Почему пересборки не будет, даже если строки расходятся. */
  readonly hold: SubscriptionHoldReason | null;
  /**
   * Почему пересобирается ВСЁ подписанное, а не разошедшееся. `null` — обычная
   * пересборка по отпечаткам. Молчать здесь нельзя: план, в котором внезапно
   * «изменилось» всё, человек обязан прочитать вместе с причиной.
   */
  readonly rebuild: SubscriptionRebuildReason | null;
  /**
   * Файлы цели, тронутые рукой человека. Пересборка их не касается — ни одного
   * байта, — и строки их записей несут `heldBy`. Пустой список — обычное дело:
   * цель, которую никто не правил, ведёт себя ровно как в П5.1.
   */
  readonly drift: readonly SubscriptionDrift[];
}

/** Ответ на пересборку: обновлённая память подписки плюс строки о записях. */
export interface SubscriptionApplyAnswer {
  readonly subscription: EnvSubscription;
  readonly rows: readonly SubscriptionRow[];
}

/**
 * Чем кончился выбранный исход расхождения.
 *
 * Строк о записях здесь нет намеренно: исход разбирает ОДИН файл, а строки
 * подписки считаются по всему канону, и отдать их отсюда значило бы отдать
 * список, посчитанный до записи, — то есть устаревший к моменту прочтения.
 * Следующий план скажет правду, и стоит он один вызов.
 */
export interface SubscriptionDriftAnswer {
  readonly subscription: EnvSubscription;
  readonly resolution: SubscriptionDriftResolution;
  readonly filePath: string;
  /** Записи канона, пополненные правкой человека; пусто у остальных исходов. */
  readonly adopted: readonly string[];
  /** Слои, снятые с подписки; пусто у остальных исходов. */
  readonly unsubscribed: readonly EnvItemKind[];
}

/** Все подписки панели — с чем открывается экран. */
export interface SubscriptionsAnswer {
  readonly items: readonly EnvSubscription[];
}

/**
 * Записи, которые разошлись и потому поедут к цели. Выводится из строк, а не
 * хранится: два списка одного и того же разъезжаются, и разъезд этот тихий.
 */
export function driftingRows(rows: readonly SubscriptionRow[]): readonly SubscriptionRow[] {
  return rows.filter((row) => row.state === 'new' || row.state === 'changed');
}

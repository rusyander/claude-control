/**
 * Ячейка CSV для файла, который откроют в Excel.
 *
 * Кавычки по RFC 4180 держат строку целой, но не делают её текстом: Excel
 * вычисляет и `"=HYPERLINK(…)"`. Текст ячейки пишут агент, чужой CI и импорт из
 * чужих таблиц, а файл открывает получатель вне панели — поэтому значение,
 * начинающееся с `= + - @`, табуляции или возврата каретки, получает апостроф
 * впереди (так Excel сам помечает введённый текст). Снимает его `csvCellValue`.
 *
 * Защиту получает и значение, где до символа формулы уже стоят апострофы автора
 * (`'=буквально`): иначе импорт не отличил бы их от защиты и снял бы чужой
 * апостроф. Так множество защищаемых значений замкнуто: импорт снимает ровно
 * один апостроф ровно у них, и выгрузка читается обратно байт в байт (F-137).
 */
const NEEDS_GUARD = /^'*[=+\-@\t\r]/;

/** Защищённая ячейка: апостроф `csvCell` впереди значения из `NEEDS_GUARD`. */
const GUARDED = /^'+[=+\-@\t\r]/;

export function csvCell(value: string): string {
  const text = NEEDS_GUARD.test(value) ? `'${value}` : value;
  return /["\n\r,;]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

/** Обратное к защите `csvCell`: прочитанная ячейка без служебного апострофа. */
export function csvCellValue(value: string): string {
  return GUARDED.test(value) ? value.slice(1) : value;
}

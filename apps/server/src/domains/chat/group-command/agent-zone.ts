import { GLOB } from './glob.ts';

/**
 * Рабочие папки агента в своей копии: `.agent/<папка>/…` (D-8, 25.10). Группа
 * удаляла свои пустые снимки BEFORE из `.agent/screenshots/before-after/…` — весь
 * `.agent/` судился локальным слоем, который git не вернёт, и уборка своего шла
 * человеку. Ниже папки внутри `.agent/` лежит выход самого агента (снимки,
 * журналы, пробы) или зеркало основной копии, чей оригинал цел там. Свои — только
 * ниже такой папки: верхние файлы `.agent/` (заметки, PROGRESS), сама папка
 * целиком и `.agent/` — по-прежнему карточка. Шаблон — только в последнем имени:
 * `.agent/*\/x` задел бы любую папку и верхний слой разом.
 *
 * `parts` — путь от корня копии по частям, в регистре сверки (`fold`).
 * Выход из копии, `.git`, ссылки наружу и секреты судит вызывающий (`targetKind`).
 */
export function inAgentWork(parts: readonly string[]): boolean {
  if (parts[0] !== '.agent' || parts.length < 3) return false;
  return parts.slice(0, -1).every((part) => !GLOB.test(part));
}

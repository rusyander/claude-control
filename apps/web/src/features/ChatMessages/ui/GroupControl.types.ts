/**
 * Действие над группой из строки хаба: пауза, продолжение, «запустить сейчас»
 * (журнал 81, 89), а у группы, оборванной до своего чата, — «завести заново» и
 * «убрать» (живой прогон 29.09), а у остановившейся недоделанной — «продолжить»
 * (владелец 05.10).
 */
export type GroupControlAction = 'pause' | 'resume' | 'start' | 'restart' | 'drop' | 'continue';

/**
 * Что можно сделать с группой из строки хаба (журнал 81, 89): поставить на
 * паузу работающую или ждущую в очереди, продолжить остановленную, запустить
 * сейчас ждущую в очереди, завести заново или убрать оборванную до чата.
 */
export interface GroupControlState {
  /** Родитель разделения — ключ записи конвейера. */
  parentChatId: string;
  /** Номер группы в конвейере — им адресуется запрос родителю. */
  index: number;
  /** Кнопки строки по порядку: первая — главная. */
  actions: GroupControlAction[];
  /** Пауза из очереди: «Продолжить» вернёт группу в очередь, а не запустит. */
  fromQueue?: boolean;
  /** Лимит подписки исчерпан: до какого момента группа (или очередь) ждёт сброса (ISO). */
  limitUntil?: string;
}

export interface GroupControlProps {
  control: GroupControlState;
}

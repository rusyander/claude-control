import type { AppStore } from '../../../lib/app-store.ts';
import type { ImportState } from '../types.ts';

/**
 * Состояние панели глазами импортёра.
 *
 * Половина claude-читателей панели (`readRules`, `readSkills`, `readPermissions`,
 * `readMcpServers`) требует полный `AppStore` — а импортёр обязан работать и на
 * ЧУЖОМ доме: проверка `check-portability-import.mjs` разворачивает эталонный
 * набор файлов во временном каталоге, где состояния панели нет вовсе, и падать
 * там значило бы, что паспорт среды снимается только с этой машины.
 *
 * Поэтому здесь ровно тот же приём, что и у `NEUTRAL_OVERLAY` в `domains/hooks.ts`
 * (`readHooksFromFiles` читает чужой `.claude` без отметок владельца машины):
 * нейтральный вид, в котором ничего не выключено и групп нет. Отметки настоящей
 * панели подмешиваются только когда вызывающий их дал — и только для СВОЕГО дома.
 *
 * Читателям нужны четыре метода из всего хранилища; остальное им не передаётся
 * намеренно — импортёр ничего не пишет, и дать ему пишущий объект значило бы
 * разрешить запись в состояние панели во время чтения паспорта.
 */
export function importStore(state?: ImportState): AppStore {
  const view = {
    isDisabled: (kind: string, id: string, legacyId?: string): boolean =>
      state?.isDisabled(kind, id, legacyId) ?? false,
    // Группы — конструкция панели, а не среды: в каноне они отдельным видом
    // записи (`panelGroup`), и подмешивать их в каждую запись здесь нечем.
    getGroupIdsFor: (): string[] => [],
    // Выключенное право в файле НЕ лежит: подмешивать снимки выключенных сюда
    // нельзя — паспорт описывает то, что действует.
    getDisabledIds: (): string[] => [],
    // Итог прошлой проверки связи к среде не относится: это наблюдение панели,
    // а не факт конфигурации.
    getMcpHealth: () => ({}),
  };

  return view as unknown as AppStore;
}

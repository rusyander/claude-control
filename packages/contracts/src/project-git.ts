/**
 * Git выбранного проекта — компактный пульт во вкладке проекта: где я сейчас,
 * куда переключиться, как завести ветку и закоммитить.
 *
 * Раздел появляется ТОЛЬКО если в каталоге проекта есть `.git` (каталог или
 * файл — так выглядит рабочее дерево worktree). Нет `.git` — нет и пульта:
 * `isRepo: false`, и клиент ничего не рисует.
 *
 * Панель не изобретает своей модели поверх git: всё, что она умеет, — обычные
 * команды (`status`, `checkout`, `checkout -b`, `commit`, `pull`, `push`).
 * Ребейзов и удаления веток здесь нет намеренно: это операции, цену ошибки в
 * которых панель взять на себя не может. Push отправляет только текущую ветку и
 * только вперёд — `--force` не передаётся нигде.
 *
 * `pull` — единственная сетевая операция и единственная, которая может привести
 * к слиянию. Она делает ровно то же, что `git pull` в терминале: при конфликте
 * рабочее дерево остаётся в состоянии конфликта, и разбирать его человек будет
 * сам — панель конфликты не разрешает и не откатывает.
 */

import type { ServerMessageCode, ServerMessageParams } from './server-messages.ts';

/** Что случилось с файлом. `renamed` несёт ещё и прежний путь в `from`. */
export type ProjectGitFileStatus =
  'added' | 'modified' | 'deleted' | 'renamed' | 'typechange' | 'untracked' | 'conflict';

/** Одна строка списка изменённых файлов. */
export interface ProjectGitChange {
  /** Путь от корня репозитория, как его отдаёт git. */
  path: string;
  status: ProjectGitFileStatus;
  /** Правка уже в индексе (`git add`), а не только в рабочем дереве. */
  staged: boolean;
  /** Прежний путь при переименовании или копировании. */
  from?: string;
}

/** Состояние git-репозитория проекта. */
export interface ProjectGitInfo {
  /** В каталоге проекта есть `.git`. Иначе весь раздел скрыт. */
  isRepo: boolean;
  /** Текущая ветка. Пусто при detached HEAD и в репозитории без коммитов. */
  branch?: string;
  /** HEAD отцеплен от ветки — коммитить и переключаться можно, но не «в ветку». */
  detached: boolean;
  /** В репозитории ещё нет ни одного коммита: веток нет, коммит создаст первую. */
  unborn: boolean;
  /** Локальные ветки, по алфавиту. Удалённые не показываются: переключение — по локальным. */
  branches: string[];
  /** Сколько файлов изменено (учтённые + неучтённые) — по нему включается кнопка коммита. */
  dirtyCount: number;
  /**
   * Сами изменённые файлы, в порядке вывода git. Список ограничен сверху:
   * в репозитории с десятками тысяч правок он смысла не несёт, а трафик съедает.
   */
  changedFiles: ProjectGitChange[];
  /** Список обрезан по потолку — `dirtyCount` при этом остаётся полным. */
  changedFilesTruncated?: boolean;
  /** Удалённый, откуда тянем: `origin`, если он есть, иначе первый по алфавиту. */
  remote?: string;
  /** Ветки на этом удалённом, без префикса `<remote>/` — закрытый список для pull. */
  remoteBranches: string[];
  /**
   * Сколько строк добавлено и убрано во всех изменениях рабочего дерева.
   *
   * Считается по ОТСЛЕЖИВАЕМЫМ файлам (`git diff --numstat HEAD`): у нового,
   * ещё не добавленного в git файла «прежней версии» не существует, и git его
   * в подсчёт не берёт. Поэтому число файлов (`dirtyCount`) и строки отвечают
   * на разные вопросы, а не на один и тот же с разной точностью.
   *
   * Пусто — в репозитории ещё нет коммитов либо git ответил ошибкой: строк не
   * показываем вовсе, ноль читался бы как «правок нет».
   */
  insertions?: number;
  deletions?: number;
  /** На сколько коммитов текущая ветка впереди upstream (есть только при upstream). */
  ahead?: number;
  /** На сколько отстала — по нему видно, есть ли что тянуть. */
  behind?: number;
  /** git не найден или каталог недоступен: пульт показывает причину и ничего не пишет. */
  error?: string;
}

/** Ответ на любую операцию записи: новое состояние + что именно сделано. */
export interface ProjectGitResult {
  info: ProjectGitInfo;
  /** Строка вывода git — показывается тостом, чтобы результат не был безмолвным. */
  output: string;
  /** Код своей строки панели, когда git промолчал; вывод git кода не несёт. */
  outputCode?: string;
  outputParams?: Record<string, string | number>;
}

/**
 * Параллельные рабочие копии одного репозитория (`git worktree`) — то, ради чего
 * несколько агентов могут работать над одним проектом одновременно и не мешать
 * друг другу: у каждой копии свой каталог и своя ветка, а история общая.
 *
 * Ветка копии — СНИМОК на момент чтения, а не свойство копии: агент внутри неё
 * волен переключаться и заводить ветки сам, поэтому клиент показывает то, что
 * git ответил только что, и никогда — то, что было при создании.
 */
export interface ProjectWorktree {
  /** Абсолютный путь рабочей копии — им же открывается вкладка проекта. */
  path: string;
  /** Ветка копии сейчас. Пусто при detached HEAD. */
  branch?: string;
  /** Сокращённый commit, на котором стоит копия. */
  head?: string;
  /** Основная копия (сам репозиторий) — её нельзя удалить. */
  isMain: boolean;
  /** HEAD отцеплен от ветки. */
  detached: boolean;
  /** Копия заперта (`git worktree lock`) — git не даст её удалить. */
  locked: boolean;
  /** Каталога больше нет: копию удалили мимо панели, строка ждёт уборки. */
  prunable: boolean;
  /** Бутстрап копии (установка зависимостей): последний запуск, если был. Основной копии нет. */
  bootstrap?: WorktreeBootstrapState;
  /**
   * Полнота копии на момент запроса списка. Основной копии нет: ей не с чем
   * сверяться.
   */
  copy?: WorktreeCopyState;
}

/**
 * Готова ли копия к работе агента — состояние, а не событие.
 *
 * Отчёт зеркала (`WorktreeMirrorReport`) живёт ровно один ответ и умирает
 * вместе с вкладкой, а отказывает по этому состоянию КАЖДЫЙ запуск прогона.
 * Поэтому карточка копии обязана показывать его всегда, а не только сразу
 * после нажатия «Обновить локальный слой».
 */
export interface WorktreeCopyState {
  ready: boolean;
  /** Чего не хватает; пусто — копия полная. */
  gaps: WorktreeCopyGap[];
  /**
   * Запись каталога копии в `.claude.json`: `ok` — есть, `missing` — нужна и
   * её нет (агент спросит про доверие и MCP), `unknown` — сверять не с чем:
   * файла нет или у самого оригинала записи никогда не было. Третье значение
   * не педантизм: без него «не проверяли» выглядело бы как «нет записи», и
   * панель держала бы прогоны там, где помочь ничем не может.
   */
  access: 'ok' | 'missing' | 'unknown';
}

export type WorktreeBootstrapStatus = 'running' | 'ok' | 'failed';

/**
 * Команда после создания копии — обычно установка зависимостей. Идёт до старта
 * агента; провал не отменяет ни копию, ни группу разделения: агент получает
 * хвост лога в задании и решает сам.
 */
export interface WorktreeBootstrapState {
  command: string;
  status: WorktreeBootstrapStatus;
  startedAt: string;
  finishedAt?: string;
  exitCode?: number;
  /** Остановлена по потолку (10 минут). */
  timedOut?: boolean;
  /** Последние строки лога; полный лог — отдельным запросом. */
  logTail: string;
  /** Lock-файлы, которые установка переписала и панель откатила к версии из индекса. */
  reverted?: string[];
}

/** Список копий репозитория. Не репозиторий — `isRepo:false`, раздела нет. */
export interface ProjectWorktreesInfo {
  isRepo: boolean;
  /** Первой всегда идёт основная копия — так их перечисляет сам git. */
  worktrees: ProjectWorktree[];
  /** git не найден или ответил ошибкой: показываем причину, писать не даём. */
  error?: string;
}

/** Ответ на создание, удаление или зеркало копии: новый список + вывод git. */
export interface ProjectWorktreesResult {
  info: ProjectWorktreesInfo;
  output: string;
  outputCode?: string;
  outputParams?: Record<string, string | number>;
  /** Путь созданной копии — по нему панель сразу открывает вкладку. */
  createdPath?: string;
  /** Что из локального слоя перенесено в копию (создание и повторное зеркало). */
  mirror?: WorktreeMirrorReport;
}

/**
 * Локальный слой репозитория, который панель переносит в каждую копию сверх
 * чекаута: файлы `skip-worktree`/`assume-unchanged` и игнорируемое git по
 * списку шаблонов. Здесь — то, что человек дописал к встроенному списку на
 * проекте; пусто = только встроенное. Шаблоны как в `.gitignore`: без «/» —
 * по имени на любой глубине, с «/» — от корня; `*`, `**`, `?`.
 */
export interface WorktreeMirrorSettings {
  /** Зеркалить ещё. */
  include: string[];
  /** Не зеркалить (вычитается после списка). */
  exclude: string[];
  /**
   * Команда после создания копии (оболочка системы, `CI=1`). Пусто — панель
   * определяет по lock-файлу в корне копии: pnpm / npm / yarn; без него ничего.
   */
  bootstrap?: string;
}

export interface WorktreeMirrorSkipped {
  path: string;
  /** Почему не перенесено: размер, ссылка, ошибка записи, флаг git. */
  reason: string;
  /**
   * Тот же текст кодом — клиент показывает его на своём языке, `reason`
   * остаётся запасным для записей, кода не несущих (ошибка файловой системы
   * приходит строкой операционной системы, и переводить её нечем).
   */
  reasonCode?: ServerMessageCode;
  reasonParams?: ServerMessageParams;
  /**
   * Род причины — для группировки на экране.
   *
   * Интерфейсу нужно отличать объяснение («окружение сборки копия ставит сама»)
   * от настоящей помехи, и делать это по ДАННЫМ: разбор русского текста
   * причины ломается от первой же правки формулировки, а она у нас ещё и
   * переезжает в словарь кодов. Поле необязательное: старый ответ без него
   * читается как `other`.
   */
  kind?: 'build-env' | 'other';
}

/** Отчёт одного зеркала — карточка копии показывает его целиком. */
export interface WorktreeMirrorReport {
  /** Перенесено в этот раз, относительные пути. */
  mirrored: string[];
  /** Подходило по списку, но не перенесено — с причиной. */
  skipped: WorktreeMirrorSkipped[];
  /** Игнорируемое git на верхнем уровне, чего в списке нет — чтобы дополнить его. */
  unlisted: string[];
  /** Уже было не старее в копии и осталось как есть (повторное зеркало). */
  kept: number;
  /**
   * Каталоги, которые копия получила ССЫЛКОЙ на оригинал (скиллы, хуки):
   * правка в оригинале сразу видна во всех копиях, файлов там нет.
   */
  linked?: string[];
  /** Запись доступа копии в `.claude.json`: без неё агент спросит про доверие и MCP. */
  access?: WorktreeCopyAccess;
  /** Чего копии не хватает после переноса; пусто — копия полная. */
  gaps?: WorktreeCopyGap[];
}

/** Итог заведения записи доступа для копии. */
export interface WorktreeCopyAccess {
  copied: boolean;
  /** Ключ каталога в `.claude.json`. */
  key: string;
  /** Почему не заведена. */
  reason?: string;
  /** Та же причина кодом; `reason` — запасной текст. */
  reasonCode?: ServerMessageCode;
  reasonParams?: ServerMessageParams;
}

/**
 * Чего копии не хватает: файла локального слоя, ссылки на общий каталог или
 * записи доступа. Пока хоть одна дыра есть, агента в копию не пускают.
 */
export interface WorktreeCopyGap {
  kind: 'file' | 'link' | 'access';
  path: string;
}

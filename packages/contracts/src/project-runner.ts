/**
 * Dev-серверы проекта, запущенные панелью прямо из ряда вкладки-проекта в чате.
 *
 * Реестр запущенных серверов живёт в памяти серверного процесса (см.
 * `domains/project-runner/project-runner.ts`). Запускается не «проект», а ЦЕЛЬ — каталог с
 * собственным package.json: сам корень или пакет монорепозитория. Целей у одной
 * вкладки может работать несколько сразу (api и web), у каждой свой процесс,
 * свой адрес и своя кнопка.
 *
 * Порт панель НЕ назначает: она читает его из вывода dev-сервера («Local:
 * http://localhost:5173»). Навязанный `PORT` игнорируют все, у кого порт прописан
 * в конфиге, — а таких большинство. Закрепить порт можно вручную; тогда панель
 * передаёт `PORT` и ждёт именно его.
 */

/** Стадия жизни запущенного dev-сервера. */
export type ProjectRunnerStatus = 'starting' | 'running' | 'stopped' | 'error';

/** Откуда взялся список пакетов монорепозитория. */
export type ProjectWorkspaceSource = 'pnpm' | 'npm' | 'scan';

/** Состояние одного запущенного dev-сервера — как его видит клиент. */
export interface ProjectRunnerView {
  /** Корень проекта (каталог вкладки). */
  projectPath: string;
  /** Подпапка относительно корня; пустая строка — сам корень. */
  dir: string;
  /** Абсолютный каталог запуска — ключ реестра. */
  path: string;
  /** Как показывать цель: имя из package.json, иначе имя папки. */
  name: string;
  /**
   * Порт — ТОЛЬКО когда он известен: прочитан из вывода или закреплён вручную.
   * Пусто при `running` — сервер работает, но адреса не назвал.
   */
  port?: number;
  /** Адрес для ссылки «Перейти». Пусто ровно тогда же, когда пусто `port`. */
  url?: string;
  /** Стадия: поднимается / работает / остановлен / ошибка. */
  status: ProjectRunnerStatus;
  /** Команда запуска, как она показана пользователю (`pnpm run dev` и т.п.). */
  command: string;
  /** Момент старта, ISO. */
  startedAt: string;
  /** Текст ошибки, если запуск не удался. */
  error?: string;
  /**
   * Порт, из-за занятости которого сервер не поднялся: прочитан из его же
   * ругани («Port 8888 is already in use», `EADDRINUSE`). Панель предлагает по
   * нему освободить порт — сама она никого не убивает.
   */
  busyPort?: number;
  /** Хвост вывода процесса — видно в поповере, когда адрес не определился. */
  output?: string;
}

/** Процесс, занимающий порт, — по данным ОС (netstat/lsof). */
export interface PortHolder {
  /** PID слушающего процесса. */
  pid: number;
  /** Имя исполняемого файла, если ОС его назвала. */
  name?: string;
  /** Это dev-сервер, запущенный самой панелью. */
  ours: boolean;
}

/** Кто держит порт — ответ на запрос и на освобождение. */
export interface PortHoldersInfo {
  /** Порт, о котором спрашивали. */
  port: number;
  /** Слушает ли его кто-нибудь прямо сейчас. */
  busy: boolean;
  /** Найденные процессы; пусто, если порт свободен или ОС не дала список. */
  holders: PortHolder[];
  /** PID, которые удалось погасить (только в ответе на освобождение). */
  killed?: number[];
}

/**
 * Чем запускается цель. `make`/`task`/`just` — цель запускается задачей
 * сборщика проекта (`make run`), язык за ней не угадывается. `custom` —
 * команду вписал человек.
 */
export type RunnerStack =
  | 'node'
  | 'go'
  | 'python'
  | 'rust'
  | 'java'
  | 'dotnet'
  | 'deno'
  | 'make'
  | 'task'
  | 'just'
  | 'custom';

/**
 * Один найденный способ запустить цель. Панель показывает их все: угадать
 * единственно верный нельзя (у Go-сервиса бывает и `make run`, и `go run .`,
 * и `air`), а выбрать из готовых проще, чем вспоминать команду.
 */
export interface RunnerCandidate {
  /** Команда, как её увидит человек: `go run ./cmd/api`. */
  command: string;
  stack: RunnerStack;
  /** Фреймворк, если узнан: `Django`, `FastAPI`, `Spring Boot`. */
  framework?: string;
  /** Файлы проекта, по которым команда угадана, — относительно корня проекта. */
  evidence: string[];
  /** Программа, без которой команда не запустится (`go`, `uv`, `make`). */
  tool?: string;
  /** Нашлась ли эта программа (в PATH или файлом-обёрткой в проекте). */
  available: boolean;
}

/** Одна цель запуска внутри проекта: корень или пакет монорепозитория. */
export interface ProjectRunnerTarget {
  /** Подпапка относительно корня проекта; пустая строка — сам корень. */
  dir: string;
  /** Абсолютный каталог запуска — ключ настроек и реестра. */
  path: string;
  /** Имя из package.json, иначе имя папки. */
  name: string;
  /** Есть ли что запускать (скрипт dev/start или оверрайд команды). */
  runnable: boolean;
  /** Команда, которая будет запущена, — для подсказки на кнопке. */
  command?: string;
  /** Почему запустить нельзя. */
  reason?: string;
  /** Оверрайд команды, сохранённый пользователем. */
  commandOverride?: string;
  /** Закреплённый порт: панель передаёт `PORT` и ждёт именно его. */
  pinnedPort?: number;
  /** Порт прошлого удачного запуска — подсказка, а не обещание. */
  lastPort?: number;
  /**
   * Автозапуск: при старте сервера панели эта цель поднимается сама — без
   * браузера и без перехода на страницу. Флаг живёт в состоянии панели и
   * переживает перезапуск.
   */
  autostart: boolean;
  /** Стек выбранной команды; `custom` — команду задал человек. */
  stack?: RunnerStack;
  /** Фреймворк выбранной команды, если узнан. */
  framework?: string;
  /** Файлы, по которым угадана выбранная команда. */
  evidence?: string[];
  /** Все найденные способы запуска — по порядку предпочтения. */
  candidates: RunnerCandidate[];
  /**
   * Программа, которой нет на машине, хотя выбранная команда без неё не
   * запустится. Цель при этом не запускаемая: панель называет причину ДО
   * запуска, а не показывает «процесс завершился с кодом 1».
   */
  missingTool?: string;
  /** Цель входит в «Запустить всё» этого проекта. */
  inGroup: boolean;
}

/** Ответ на запрос «что здесь вообще можно запустить». */
export interface ProjectRunnerInfo {
  /** Корень проекта, как он пришёл в запросе. */
  projectPath: string;
  /** Цели запуска: корень всегда первым, дальше пакеты монорепозитория. */
  targets: ProjectRunnerTarget[];
  /** Как найдены пакеты: pnpm-workspace.yaml, workspaces или скан папок. */
  workspaceSource?: ProjectWorkspaceSource;
  /** Сколько целей отброшено ограничением на размер списка (0 — ни одной). */
  skipped: number;
}

/** Ответ «Запустить всё»: что поднимается и что отказало — с причиной на цель. */
export interface ProjectRunnerStartAllResult {
  started: ProjectRunnerView[];
  failed: { dir: string; name: string; message: string }[];
}

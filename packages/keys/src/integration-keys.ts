/**
 * Имя ключа интеграции в общем зашифрованном хранилище (`provider-keys.ts`). Один источник на
 * панель (пишет ключ из карточки интеграции) и ядро (читает его для форжа при публикации):
 * разойдись имена — ядро молча не нашло бы ключ и публиковало бы «без доступа».
 *
 * Префикс `int:` отделяет ключи интеграций от ключей провайдеров в том же файле: `int:gitlab`
 * не столкнётся с ключом провайдера и по файлу видно, где чей секрет.
 */
export const INTEGRATION_KEY_PREFIX = 'int:';

export function integrationKeyId(kind: string): string {
  return `${INTEGRATION_KEY_PREFIX}${kind}`;
}

import type { PlatformRunConsumer } from '@agentdeck/contracts/platform-consumers';
import type { ChatEvent } from '../chat-events.ts';
import type { RunOptions } from '../ChatRunner/ChatRunner.ts';

/** Самый поздний ход разговора — параметры пингу тёплого кэша (`latestRunOf`). */
export interface LatestRun {
  chatId: string;
  sessionId: string;
  options: RunOptions;
  meta: RunMeta;
  /** Параметры из журнала прогонов после перезапуска панели: префикс хода по ним не собрать. */
  adopted?: true;
}

/** Сведения о прогоне для группировки и переподключения (в т.ч. после F5). */
export interface RunMeta {
  /**
   * Откуда прогон: обычный чат (`chat`, умолчание) или группа разделения
   * (`groups`). Это же — ПОТРЕБИТЕЛЬ маршрута контура (Т3): реестр знает
   * происхождение каждого прогона, и список «Где работает контур» строится по
   * нему, а не по списку пожеланий.
   */
  origin?: PlatformRunConsumer;
  /**
   * Прогон идёт на локальной модели. Решается реестром на каждом старте по маршруту
   * (`setLocalClassifier`) и пишется в журнал: опции усыновлённого после перезапуска панели
   * прогона адреса контура не несут, а ночному прогону без этой отметки не держали бы
   * компьютер бодрствующим и не продолжали бы после сбоя (L4c, F1).
   */
  local?: true;
  /** Каталог проекта (для группировки статусов); undefined — песочница/дом. */
  projectPath?: string;
  /** Идентификатор сессии на старте (для продолжения разговора). */
  sessionId?: string;
  /**
   * Старт — повтор после сброса лимита (директива §L8): ждали до `resetsAt`, и
   * кэш остыл при любом простое. Нужна только решению о продолжении на этом
   * старте (`setContinuationPolicy`); в запись прогона не попадает, иначе
   * следующий повтор того же прогона считался бы «после лимита» тоже.
   */
  afterLimit?: true;
  /**
   * Человек вернул ход в остывшую сессию кнопкой на заметке «начат новый
   * разговор» (R5 ревью П1): правило остывшей сессии на этом старте не
   * спрашивают. В запись прогона не попадает — следующее продолжение решает
   * правило, как обычно.
   */
  keepSession?: true;
  /**
   * Прогон уехал ступенью НИЖЕ потолка разговора (веер параллельного запуска).
   * Само присутствие поля и означает понижение; внутри — чем именно ведут, уже
   * развёрнутым именем. По этой отметке прогон попадает в журнал сдачи: без неё
   * `lowered` умирал в маршруте, и спросить «окупается ли понижение» было не у
   * кого.
   */
  lowered?: {
    model: string;
    effort: string;
    /**
     * Класс работы, из-за которого ступень и понизили. Есть у детей разделения
     * и у звена правок; у ручного веера его нет вовсе — там ступень выбрал
     * человек, и рода работы никто не называл.
     */
    kind?: string;
  };
}

/**
 * Что реестр отдаёт сторожу групп (`token-ledger/watch`): старт прогона, КАЖДОЕ
 * событие потока, внутренние (`toolResult`, `compact`) тоже, и конец. Отдельный
 * слушатель, а не подписка вкладки: внутренние события в буфер не попадают.
 */
export type RunWatchFeed =
  /**
   * `detached` — прогон подхвачен после перезапуска без потока: событий не будет, только конец.
   * `forkOf` — ответвление (`--fork-session`) этой сессии: окно и кэш начинаются с её.
   */
  | { kind: 'start'; sessionId?: string; cwd: string; detached?: true; forkOf?: string }
  | { kind: 'event'; event: ChatEvent; sessionId?: string }
  | { kind: 'finish'; sessionId?: string };

export type RunWatchListener = (chatId: string, feed: RunWatchFeed) => void;

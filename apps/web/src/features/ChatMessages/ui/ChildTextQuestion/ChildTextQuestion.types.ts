export interface ChildTextQuestionProps {
  /** Хвост ответа ребёнка, кончившегося вопросом, — как его написал агент. */
  text: string;
  /** Чей вопрос: имя чата ребёнка — туда и уйдёт ответ. */
  target: string;
  /** Отправить ответ в чат ребёнка. */
  onAnswer: (answer: string) => void;
  /** Ребёнок ещё работает — ответ встанет в его очередь. */
  busy?: boolean;
  /** На этот вопрос уже ответили (память отвеченных — в сторе, не в карточке). */
  isAnswered?: boolean;
}

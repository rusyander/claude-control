export type PlatformEvidence = (typeof platformEvidences)[number];

/** Одна строка матрицы «что доступно»: состояние, причина словами и подпись. */
export interface PlatformCapabilityFinding {
  id: PlatformCapability;
  state: PlatformCapabilityState;
  /** Человеческая причина: «список ключа», «через владельца ключа», «не объявлено». */
  detail: string;
  /**
   * Код той же причины для перевода (`server-messages.ts`). Пусто — у старой
   * записи из `state.json` или у причины, коду ещё не заведённой: тогда
   * показывается `detail` как есть.
   */
  detailCode?: ServerMessageCode;
  detailParams?: ServerMessageParams;
  /** Проверено на этом контуре или известно про платформу вообще. */
  evidence: PlatformEvidence;
  /** Подпись компромисса, если состояние объясняется подписанным обходом. */
  compromise?: CompromiseId;
  /** Сколько нашлось (моделей, агентов) — пусто, если счёт неизвестен. */
  count?: number;
}

/**
 * Чем кончился поход к контуру. Пять исходов, а не два: «не отвечает» и
 * «отвечает не тем» чинятся по-разному, и самая частая ошибка настройки —
 * адрес админки вместо адреса API — обязана называться отдельно.
 */
export const platformProbeOutcomes = [
  /** Список моделей получен. */
  'ok',
  /** До адреса не дошли вовсе: нет сети, не разобрался адрес, вышло время. */
  'unreachable',
  /** Адрес живой, но отвечает не модельный API (HTML страницы входа, 404). */
  'not-api',
  /** Ключ отклонён (401/403). */
  'unauthorized',
  /** Контур ещё поднимается: реестр моделей не готов (503). */
  'not-ready',
  /**
   * Ключ не передавали, и контур отказал (401/403). Это НЕ «ключ отклонён»:
   * отказ без ключа подтверждает, что по адресу модельный API, — так отвечает
   * первый шаг мастера, где ключ ещё не введён.
   */
  'no-key',
] as const;
export type PlatformProbeOutcome = (typeof platformProbeOutcomes)[number];


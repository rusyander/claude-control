import type { ModelInfo } from '@agentdeck/contracts';

export interface ChatModelPickerProps {
  /** Оверрайд модели для этого чата ('' = брать из настроек). */
  model: string;
  /** Оверрайд глубины для этого чата ('' = брать из настроек). */
  effort: string;
  /** Модель по умолчанию из настроек — чтобы подписать пункт «по умолчанию». */
  defaultModel: string;
  /** Глубина по умолчанию из настроек. */
  defaultEffort: string;
  /**
   * Модели каталога провайдера: их предлагают в дополнение к алиасам, чтобы в
   * чате можно было взять конкретное поколение, а не только «последний opus».
   * Пусто — остаются одни алиасы (каталог не скачался или не поддерживается).
   */
  models?: ModelInfo[];
  /**
   * Потребитель контура, от имени которого пойдёт прогон (Т6): `chat` у своего
   * чата, `groups` у разговора, заведённого разделением, `foreign:<cli>` у
   * чужого. По нему спрашивается, чем прогон пойдёт на самом деле, — контур
   * подменяет и модель, и усилие, а наши слои (Т8) снимает или нет. Умолчание
   * `chat` здесь и есть та ловушка, которую нашло ревью Т8: у разговора группы
   * шапка обещала слои чужого маршрута, поэтому потребителя передаёт страница.
   */
  consumer?: string;
  onModelChange: (value: string) => void;
  onEffortChange: (value: string) => void;
}

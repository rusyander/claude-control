import type { MessageUsage } from '@agentdeck/contracts';

export interface TokenBadgeProps {
  /** Расход одного шага модели: четыре вида токенов, модель, цена. */
  usage: MessageUsage;
  /**
   * Единицы крупного числа — общая настройка панели. `money` показывает цену
   * шага, `tokens` — объём; разбивка в раскрытии одинакова в обоих случаях.
   */
  unit?: 'tokens' | 'money';
  /**
   * Сколько вызовов породил этот шаг. Больше одного — расход у них общий, и
   * бейдж говорит об этом прямо: делить его между вызовами нечем.
   */
  sharedWith?: number;
  /** Глубина продумывания прогона (--effort) — известна только у живого хода. */
  effort?: string;
  /** Подпись, объясняющая, к чему относится расход: «ответ», имя инструмента. */
  label?: string;
  /**
   * Время шага — от предыдущей записи прогона до этой, мс. Третий столбик
   * бейджа: сколько агент шёл к этому действию. Нет (старая запись без
   * времени) — столбика нет, а не «0с»: выдуманный ноль хуже пустого места.
   */
  durationMs?: number;
  /** Границы шага (ISO) — подсказка называет старт и конец, а не только длину. */
  from?: string;
  to?: string;
  /** Сумма прогона — только у его последней записи: от реплики человека до неё. */
  runTotalMs?: number;
  className?: string;
}

/** Тон уведомления — задаёт цвет, иконку и роль для скринридера. */
export type ToastTone = 'success' | 'error' | 'warning' | 'info';

export interface ToastItem {
  /** Уникальный идентификатор — для анимации и закрытия. */
  id: string;
  tone: ToastTone;
  /** Основной текст. */
  message: string;
  /** Необязательный заголовок над текстом. */
  title?: string;
  /** Сколько держать на экране, мс. 0 — не скрывать автоматически. */
  duration: number;
  /** Действие по клику на тост (например, перейти в проект). */
  onClick?: () => void;
}

/**
 * Запись журнала уведомлений. Тосты живут на экране секунды, а журнал хранит
 * последние из них с отметкой времени — чтобы вернуться и прочитать то, что
 * промелькнуло. Действие по клику и длительность в историю не переносим: журнал
 * только показывает, что было.
 */
export interface ToastHistoryEntry {
  id: string;
  tone: ToastTone;
  message: string;
  title?: string;
  /** Когда уведомление появилось, мс epoch. */
  at: number;
}

/** Что можно задать при показе тоста, помимо самого текста. */
export interface ToastOptions {
  title?: string;
  /** Переопределить длительность (по умолчанию 3 секунды). */
  duration?: number;
  /** Клик по тосту выполнит это действие и закроет тост. */
  onClick?: () => void;
}

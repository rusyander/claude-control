import { string } from 'zod';

/**
 * Потребители контура — КТО именно идёт через него, а не «включён ли он».
 *
 * До Т3 у контура был один маршрут на всё: применение писало адрес шлюза в
 * глобальный конфиг CLI, и выбрать «чат через контур, а тесты своим ключом»
 * было негде — либо весь `claude` уходил в контур, либо ни один запуск.
 * Потребитель — это ЗАПУСК с известным происхождением (прогон чата, дети
 * разделения, агент тестов, чат чужого CLI), и маршрут решается в момент
 * запуска, в окружении одного процесса.
 *
 * ПОЧЕМУ СПИСОК НЕ ПИШЕТСЯ РУКАМИ. Галочка, за которой нет ни одного места
 * запуска, — это обещание, которого панель не держит: человек отметил
 * «картинки», ничего не изменилось, и узнать об этом неоткуда. Поэтому набор
 * собирается из того, что ДЕЙСТВИТЕЛЬНО спавнит модель (реестр прогонов,
 * агент тестов, чаты чужих CLI и применение к файлам), а не из списка
 * пожеланий. Появится своя ветка у картинок или презентаций — потребитель
 * появится вместе с ней, одной строкой здесь и одним местом в коде.
 */

/** Прогоны, у которых происхождение известно реестру. */
export const platformRunConsumers = ['chat', 'groups', 'tests'] as const;
export type PlatformRunConsumer = (typeof platformRunConsumers)[number];

/**
 * Ассистент самой панели. Отдельно от прогонов: он ходит не CLI, а
 * управляемым профилем эндпоинта — тем же, который заводит применение
 * контура, — поэтому окружения процесса ему не достаётся вовсе.
 */
export const PLATFORM_ASSISTANT_CONSUMER = 'assistant';

/**
 * Применение к файлам конфигурации CLI — то, чем контур работал до Т3.
 *
 * Называется «терминал», потому что именно это и означает: `claude`,
 * запущенный человеком руками в своей консоли, читает те же файлы. Галочка
 * ОТДЕЛЬНАЯ и по умолчанию снята: запись в чужой глобальный конфиг — самое
 * широкое действие контура (она достаётся и тому запуску, о котором панель
 * ничего не знает), и получать её заодно с «чат через контур» человек не
 * подписывался.
 */
export const PLATFORM_TERMINAL_CONSUMER = 'terminal';

/** Префикс потребителя-чужого CLI: `foreign:codex`. */
export const FOREIGN_CONSUMER_PREFIX = 'foreign:';

export type PlatformConsumerId = string;

/**
 * Набор символов тот же, что у идентификатора провайдера: из потребителя не
 * собирается ни адрес, ни путь, но список хранится в настройках и приезжает в
 * ответ, и мусор в нём разъехался бы молча.
 */
export const platformConsumerPattern =
  /^(chat|groups|tests|assistant|terminal|foreign:[a-zA-Z0-9][a-zA-Z0-9._-]*)$/;

export const platformConsumerSchema = string().regex(
  platformConsumerPattern,
  'потребитель: chat, groups, tests, assistant, terminal или foreign:<cli>',
);

/** Потребитель чужого CLI по его идентификатору в реестре провайдеров. */
export function foreignConsumerId(providerId: string): PlatformConsumerId {
  return `${FOREIGN_CONSUMER_PREFIX}${providerId}`;
}

/** Обратно: `foreign:codex` → `codex`; для остальных — undefined. */
export function foreignProviderId(consumer: string): string | undefined {
  return consumer.startsWith(FOREIGN_CONSUMER_PREFIX)
    ? consumer.slice(FOREIGN_CONSUMER_PREFIX.length)
    : undefined;
}

/**
 * Что получает НОВЫЙ контур. Только ассистент панели — тот единственный
 * сценарий, который через контур работает целиком: у CLI через шлюз нет своих
 * инструментов (подпись `no-client-tools`), и молча увести туда рабочий чат
 * значило бы отнять у человека правку файлов, ничего ему не сказав.
 */
export const PLATFORM_DEFAULT_CONSUMERS: readonly PlatformConsumerId[] = [
  PLATFORM_ASSISTANT_CONSUMER,
];

/**
 * Почему потребитель недоступен. Первые три — те же причины, что у целей
 * применения (`PlatformTargetReason`): у CLI нет задокументированной
 * переменной адреса, диалект шлюзу не по зубам, шлюз не поднят. Четвёртая
 * только здесь:
 *
 * `file_only` — адрес этого CLI живёт в его конфигурационном ФАЙЛЕ (codex,
 * continue), а файл один на машину. Значит выбрать его «только для чата»
 * нельзя физически: запись достанется и ручному запуску в терминале. Панель
 * говорит это словом «только глобально» вместо того, чтобы дать галочку,
 * которая тихо сделает больше обещанного.
 */
export type PlatformConsumerReason =
  'no_env_section' | 'no_documented_base_url' | 'gateway_dialect' | 'file_only';

/** Строка списка «Где работает контур» — то, что рисует мастер. */
export interface PlatformConsumerOption {
  id: PlatformConsumerId;
  /**
   * Имя CLI у чужого потребителя («Codex», «Qwen Code») — имя собственное, и
   * переводить его нечем. У встроенных потребителей пусто НАМЕРЕННО: «Чат» и
   * «Терминал» клиент называет на своём языке, а сервер языка не знает.
   */
  title: string;
  /** Отмечен ли он у этого контура. */
  selected: boolean;
  /**
   * Маршрут достаётся окружению одного процесса (`run`), управляемому профилю
   * панели (`profile`) или файлам конфигурации CLI (`files`). Разница видна
   * человеку: `files` — единственный вид, который действует и на запуск,
   * сделанный мимо панели.
   */
  scope: 'run' | 'profile' | 'files';
  /** Недоступен — и почему; `selected` у такого всегда false. */
  reason?: PlatformConsumerReason;
}

import { object, string, type infer as Infer } from 'zod';
import type { CompromiseId } from './compromises';

/**
 * Картинки из чата: панель просит модель нарисовать и показывает результат.
 *
 * Запрос делает САМА ПАНЕЛЬ, а не CLI, и это не сокращение пути: расшифровка
 * разговора — файл Claude Code, панель в него не пишет ни строки (иначе она
 * подделывала бы чужую историю). Поэтому режим «Картинка» — не сообщение
 * агенту, а свой запрос с своим ответом: файл на диске панели и карточка в
 * превью разговора.
 *
 * Где картинка НЕ лежит: в `state.json` — ни байта. Настройки панели переносятся
 * архивом и читаются человеком, и мегабайт base64 в них означал бы и распухший
 * перенос, и нечитаемый файл настроек. Байты лежат файлом в каталоге данных,
 * запись о картинке — рядом с ним, отдельным `.json`.
 */

/**
 * Откуда возьмётся картинка. Маршрут решает сервер ОДИН раз и называет его
 * экрану: у трёх дорог разная цена, разные отказы и разный промпт.
 */
export const mediaImageSources = [
  /** Контур рисует частью обычного ответа (`driver.images = 'chat-part'`). */
  'contour-chat',
  /** У контура отдельная ручка OpenAI-вида, путь объявлен (`driver.images = { api }`). */
  'contour-images',
  /** Свой эндпоинт человека: адрес объявлен полем профиля (решение В4). */
  'endpoint',
  /**
   * Рисует АГЕНТ этого разговора — вектором, блоком `agentdeck:svg` в
   * ответе. Дорога есть у любого CLI и не требует ни контура, ни ключа, ни
   * объявленной возможности: этим и закрывается «режим заперт, потому что нет
   * контура» — рисовать было чем и тогда (дописано владельцем 13.09.2026).
   *
   * Продукт у неё ДРУГОЙ, и панель об этом говорит: вектор, нарисованный кодом,
   * а не снимок. Поэтому растровые дороги идут первыми, а эта — общая опора.
   */
  'agent',
] as const;
export type MediaImageSource = (typeof mediaImageSources)[number];

/**
 * Почему пункт недоступен. Причина машиночитаемая, текст — на клиенте: панель
 * обязана сказать не «нельзя», а ЧТО именно мешает, иначе человек идёт чинить
 * не то (инвариант 13 партии: недоступность называется, а не подменяется).
 */
export const mediaImageBlockers = [
  /** Ни активного контура, ни профиля эндпоинта: рисовать некому. */
  'no-route',
  /** У драйвера контура картинок нет вовсе (`images: 'none'`). */
  'driver-none',
  /** Контур рисует моделью, но в каталоге ключа модели с флагом нет. */
  'no-model',
  /** Профиль эндпоинта есть, адрес генерации не задан — угадывать нельзя (В4). */
  'endpoint-no-url',
  /** Запрос в контур идёт через шлюз панели, а он выключен в настройках. */
  'gateway-off',
  /**
   * Тумблер шлюза ВКЛЮЧЁН, а слушателя нет: панель попробовала поднять его сама
   * и не смогла (порт занят чужим процессом, отказ `listen`). Отдельная причина,
   * а не `gateway-off`: там человеку есть что нажать, здесь — нечего, и послать
   * его «включить шлюз», который уже включён, значит послать чинить не то.
   */
  'gateway-failed',
  /** Профиль эндпоинта другого вида API: у `anthropic` и `google` такой ручки нет. */
  'endpoint-api-kind',
  /**
   * Рисовать некому даже вектором: нет разговора, в котором можно попросить
   * агента. Единственная причина, которая запирает САМ РЕЖИМ, — остальные пять
   * объясняют лишь отсутствие растровой дороги.
   */
  'no-agent',
] as const;
export type MediaImageBlocker = (typeof mediaImageBlockers)[number];

/**
 * Что панель ответит экрану ДО нажатия: доступен ли режим, чем нарисует и
 * почему нет. Считается на сервере, потому что ответ собирается из трёх мест
 * (драйвер контура, каталог пробы, профили эндпоинтов), и второй расчёт на
 * клиенте разошёлся бы с настоящим маршрутом — та же болезнь, что вылечил
 * `chooseRunModel` в Т6.
 */
export interface MediaImagePlan {
  available: boolean;
  source?: MediaImageSource;
  /** Кто нарисует, человеческим именем: название контура или профиля. */
  title: string;
  /** Модель, которая уедет в запрос. Пусто — маршрут её не требует. */
  model: string;
  /** Что мешает. Есть ровно тогда, когда `available` ложно. */
  reason?: MediaImageBlocker;
  /**
   * Отказ словами от того, кто отказал, — сейчас это ошибка слушателя шлюза при
   * `gateway-failed`. Текст причины живёт в словаре клиента, а ЭТО дописка к
   * нему: «порт занят» панель придумать не может, а без неё человек видит
   * «шлюз не поднялся» и не знает, чем именно.
   */
  reasonDetail?: string;
  /**
   * Почему нет РАСТРОВОЙ дороги, когда рисует агент. Режим при этом доступен, и
   * путать два утверждения нельзя: «панель не умеет» — неправда, а «у этого
   * контура нет генерации картинок» — правда, и именно она чинится.
   */
  rasterReason?: MediaImageBlocker;
  /**
   * Уезжает ли промпт режима из каталога (Т4). У ручки картинок системного
   * сообщения нет вовсе, и человеку это говорится: его правка промпта на этой
   * дороге не работает, а молчание читалось бы как «правка не сработала».
   */
  promptSent: boolean;
  /** Подпись компромисса, объясняющего доступность по возможности. */
  compromise?: CompromiseId;
}

/**
 * РАСТРОВЫЕ типы, которые панель принимает из чужого ответа. Список закрыт.
 *
 * Вектора здесь нет намеренно, и это не забывчивость: SVG — исполняемый документ,
 * и принимать его как «просто ещё один тип картинки» значило бы сохранить на диск
 * файл со скриптом внутри, если чужая ручка ответит `data:image/svg+xml`. Вектор
 * приходит ровно одной дорогой — блоком агента, — и только через проверку
 * `media-block.ts → checkPicture`.
 */
export const mediaImageMimes = ['image/png', 'image/jpeg', 'image/webp'] as const;
export type MediaImageMime = (typeof mediaImageMimes)[number];

/** Тип рисунка с дороги агента. */
export const MEDIA_SVG_MIME = 'image/svg+xml';

/** Тип файла картинки в записи панели: растр из ответа или проверенный вектор. */
export type MediaFileMime = MediaImageMime | typeof MEDIA_SVG_MIME;

/**
 * Потолок одной картинки — тот же, что у собранного ответа шлюза: выше него
 * поток всё равно не отдадут целиком.
 */
export const MEDIA_IMAGE_MAX_BYTES = 8 * 1024 * 1024;

/** Потолок описания. Дальше режет уже сам контур, и режет молча. */
export const MEDIA_PROMPT_MAX = 4000;

/**
 * Сколько картинок панель держит на диске. Каталог данных — не галерея (история
 * галереи прямо вне объёма Т9), и без потолка он растёт молча: каждая картинка
 * мегабайтная, а удалять их человеку негде.
 */
export const MEDIA_KEEP_FILES = 100;

/** Запись о готовой картинке. Байтов здесь нет — они в файле рядом. */
export interface MediaImage {
  /** Идентификатор, он же имя файла. Генерирует панель. */
  id: string;
  /** Разговор, из которого попросили. Пусто — попросили из черновика. */
  chatId: string;
  /** Имя для скачивания. */
  name: string;
  mime: MediaFileMime;
  sizeBytes: number;
  /** Размер в точках — только если он читается из самих байтов файла. */
  width?: number;
  height?: number;
  /** Описание человека — то, что уехало модели. */
  prompt: string;
  /** Модель, которая рисовала. Пусто — маршрут её не назвал. */
  model: string;
  source: MediaImageSource;
  createdAt: string;
}

export const mediaImageRequestSchema = object({
  /** Разговор, к которому привязать картинку. Пусто — черновик без разговора. */
  chatId: string().default(''),
  /**
   * Описание. Обрезка пробелов ДО проверки длины, а не после: строка из одних
   * пробелов проходила `min(1)` и уезжала в контур — то есть запрос, который
   * чужая сторона отклонит, а деньги ключа спишет.
   */
  prompt: string()
    .trim()
    .min(1, 'опишите картинку')
    .max(MEDIA_PROMPT_MAX, 'описание длиннее 4000 знаков'),
});

export type MediaImageRequest = Infer<typeof mediaImageRequestSchema>;

/**
 * Рисунок, который панель приняла из блока в ответе агента (дорога `agent`).
 *
 * Отдельный запрос: в остальных дорогах панель САМА идёт к модели, а здесь
 * принимает то, что агент уже сказал в разговоре. Проверяет она его сама
 * (`media-block.ts → checkPicture`) — пришло оно из ответа модели, а значит
 * доверия к содержимому ровно столько же, сколько к чужому файлу.
 */
export const mediaPictureBlockRequestSchema = object({
  chatId: string().default(''),
  /** Описание человека — подпись карточки. Пусто допустимо: просьба была устной. */
  prompt: string().trim().max(MEDIA_PROMPT_MAX, 'описание длиннее 4000 знаков').default(''),
  /** Тело блока как есть: сам `<svg>`. */
  block: string().min(1, 'блок пустой'),
  /** Модель разговора — чтобы карточка назвала, кто рисовал. */
  model: string().trim().max(120).default(''),
});

export type MediaPictureBlockRequest = Infer<typeof mediaPictureBlockRequestSchema>;

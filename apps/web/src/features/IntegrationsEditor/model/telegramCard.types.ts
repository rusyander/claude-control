/** Группы «Когда звать» — над списками событий подписки. */
export interface TelegramGroups {
  /** «Агент ждёт тебя» — вопрос или разрешение. */
  waits: boolean;
  /** «Что-то сломалось» — упал прогон, красные тесты, группа зависла или пошла по кругу. */
  broken: boolean;
  /** «Бюджет контура» (в «Дополнительно»). */
  budget: boolean;
}

/** Черновик карточки Telegram: поля строками, группы флагами. */
export interface TelegramCardDraft extends TelegramGroups {
  /** Куда писать уведомления. */
  chatId: string;
  /** Ваш id в Telegram — от кого принимаются ответы кнопками. */
  ownerId: string;
  /**
   * «Агент ждёт тебя»: через сколько минут без ответа в панели звать — с
   * кнопками ответа, всегда (отдельной галочки нет с 25.10.2026).
   */
  afterMinutes: string;
  /** «Задача закрыта или агент ждёт решения» — сообщать о конце хода после долгой работы. */
  finished: boolean;
  doneAfterMinutes: string;
}

import type { MessageUsage } from '@agentdeck/contracts';
import type { HandoffRefusal, SplitGroupStatusView } from '@agentdeck/contracts/chat-handoff';
import type {
  ServerMessageCode,
  ServerMessageNestedParams,
} from '@agentdeck/contracts/server-messages';
import type { RunStatus } from './status';

export interface StreamedTool {
  name: string;
  input: string;
  /** Идентификатор вызова — по нему к нему приходит расход шага. */
  id?: string;
  /** Расход шага, породившего вызов; общий на все вызовы одного шага. */
  usage?: MessageUsage;
}

/** Запрос агента на разрешение инструмента — ждёт «Разрешить»/«Запретить». */
export interface PendingPermission {
  toolName: string;
  input: unknown;
  toolUseId: string;
}

/** Группа разделения, которой отдана работа разговора (Д15). */
export interface BranchGateChild {
  /** Номер с единицы — им агент адресует группу в `agentdeck:tell N`. */
  number: number;
  title: string;
  branch: string;
  status: SplitGroupStatusView;
  chatId?: string;
}

/**
 * Первая правка в основной рабочей копии — придержана до ответа человека. Это
 * тот же запрос прав (`toolUseId` общий), но спрашивают здесь не «можно ли», а
 * «где»: завести копию с веткой, писать на месте или не писать вовсе.
 */
export interface PendingBranchGate extends PendingPermission {
  /** Каталог, в котором идёт прогон, — основная копия репозитория. */
  cwd: string;
  /** Имя ветки, предложенное панелью; человек правит его прямо в карточке. */
  branch: string;
  /** Работа разговора отдана группам разделения — карточка говорит, кому (Д15). */
  children?: BranchGateChild[];
  /** Копия встанет на ветку MR детей, а не на HEAD основной копии (Д15). */
  base?: string;
}

/**
 * Сообщение, дописанное человеком, пока агент ещё занят. Уходит само, как только
 * текущий ход закончится, — тем же `--resume`, то есть в тот же разговор.
 *
 * Прервать чужой ход панель не может и не притворяется, что может: CLI в режиме
 * `-p` доводит ход до конца, и любое «мгновенное вмешательство» всё равно легло
 * бы в очередь — только внутри CLI и без права её увидеть или отменить. Здесь
 * очередь на виду: видно, что уйдёт следующим, и можно передумать.
 */
export interface QueuedMessage {
  /** Локальный id — чтобы удалить конкретное сообщение из очереди. */
  id: string;
  prompt: string;
  files?: { name: string; base64: string }[];
  allowEdits?: boolean;
  autoApprove?: boolean;
  model?: string;
  effort?: string;
}

export interface AgentRun {
  /** Стабильный id прогона — chatId, с которым он стартовал. */
  id: string;
  sessionId?: string;
  /**
   * Когда сервер завёл прогон, по его часам. По нему лента отличает ход, что
   * прямо сейчас рисует поток, от записанного в транскрипт раньше.
   */
  startedAt?: number;
  /** Каталог проекта — для группировки статусов (undefined = домашний чат). */
  projectPath?: string;
  status: RunStatus;
  text: string;
  thinking: string;
  tools: StreamedTool[];
  costUsd?: number;
  /** Токенов израсходовано в этом прогоне (input+output+cache). */
  tokens: number;
  /**
   * Расход шагов, не породивших ни одного вызова, — то есть цена самого текста
   * ответа. Складывается по шагам: текст в ленте склеивается в один блок, и
   * разложить его обратно по шагам нечем.
   */
  textUsage?: MessageUsage;
  limitResetsAt?: number;
  error?: string;
  /**
   * Структурный код отказа сервера (`run_busy`, `unsupported_upload`,
   * `workspace_missing`). По нему принимаются решения и подбирается текст на
   * языке интерфейса; сам `error` — только для показа, разбирать его нельзя.
   */
  errorCode?: string;
  /** Сервер (или сеть) сказал, что сбой временный, — можно перезапустить самим. */
  errorRetriable?: boolean;
  /**
   * Ключ, под которым прогон зарегистрирован НА СЕРВЕРЕ. Отличается от `id`,
   * когда разговор начался в другой вкладке под временным `new-…`, а эта знает
   * его по sessionId: по этому ключу идут и подключение к потоку, и остановка.
   */
  serverRunId?: string;
  /** В последнем ходе агент задал вопрос человеку (AskUserQuestion). */
  askedQuestion: boolean;
  /** Запросы на права, ждущие ответа человека (интерактивный permission-prompt). */
  permissions: PendingPermission[];
  /** Ворота ветки: первая правка в основной копии ждёт решения человека. */
  branchGates: PendingBranchGate[];
  /** Дописанное, пока агент занят: уйдёт по очереди, как только он освободится. */
  queued: QueuedMessage[];
  /**
   * Сообщение, которое только что ушло из очереди этим ходом. Пузырь-призрак
   * исчез вместе с очередью, а в транскрипте реплика появится через секунды —
   * без этой метки она на это время пропадала из ленты вовсе. Страница по ней
   * ставит обычный оптимистичный пузырь и снимает его, как только история
   * содержит реплику. Живёт до конца хода.
   */
  sentFromQueue?: QueuedMessage;
  /**
   * Поток замолчал: байтов нет дольше `STREAM_STALL_MS`, идёт переподключение.
   *
   * Прогон при этом жив — он на сервере, а не во вкладке, — но показывать его
   * потоковый пузырь больше нельзя: он оборван на полуслове, и правда теперь в
   * транскрипте. Метка гасит пузырь и тем самым возвращает в ленту историю
   * этого хода (одно условие на двоих, см. `shared/lib/chat-stream`). Снимает
   * её успешно переподключённый поток — и новый ход, конечно.
   */
  stalled?: boolean;
  /**
   * Переподключения исчерпаны — поток восстановить не удалось.
   *
   * Прогон при этом мог спокойно доработать на сервере: это вкладка его больше
   * не слышит, а не агент умер. Отличается от `stalled` тем, что чинить уже
   * нечего, и лента обязана сказать об этом вслух — молчание здесь неотличимо
   * от «агент думает», и человек ждёт ответа, которого никто не пришлёт.
   */
  dropped?: boolean;
  /**
   * Прогон подхвачен уже завершённым — из grace-буфера сервера после F5. Его
   * ответ целиком в транскрипте, поток догоняет только хвост: расход, вопрос
   * человеку, цену. Текст в пузырь не набирается — иначе лента показала бы
   * ответ второй раз, спрятав его же из истории, а «работает» и «Остановить»
   * вернулись бы к разговору, который закончился минуту назад.
   */
  tailOnly?: boolean;
  /**
   * Прогон идёт на сервере, но потока у этой вкладки к нему нет: потоков не
   * больше `MAX_STREAMS`, и место досталось более важным. Статус держится по
   * опросу `/chat/active`, лента — по транскрипту; поток вернётся, как только
   * освободится место (`agent-runs.slots`).
   */
  parked?: boolean;
  /**
   * Прогон усыновлён сервером после его перезапуска: процесс CLI жив, а трубы
   * к нему нет — текста в потоке не будет, правда в транскрипте. Пузырь не
   * рисуется (как у припаркованного), лента говорит об этом строкой, «Остановить»
   * и карточки прав работают. Ставится и по `/chat/active`, и по заметке потока.
   */
  detached?: boolean;
  /** Текст последней заметки панели про этот прогон (запасной, если код незнаком). */
  notice?: string;
  /** Код той же заметки — по нему она читается на языке интерфейса. */
  noticeCode?: ServerMessageCode;
  noticeParams?: ServerMessageNestedParams;
  /** Последний отправленный запрос — для кнопки «Повторить». */
  lastPrompt?: string;
  /** Разрешались ли правки в прошлом запуске — для повтора с теми же правами. */
  allowEdits?: boolean;
  /** Было ли включено автоподтверждение прав — чтобы повтор шёл так же. */
  autoApprove?: boolean;
  /** Модель и глубина продумывания прошлого запуска — для повтора теми же. */
  model?: string;
  effort?: string;
  lastEventAt: number;
}

export interface StartInput {
  chatId: string;
  prompt: string;
  sessionId?: string;
  files?: { name: string; base64: string }[];
  allowEdits?: boolean;
  /** Каталог проекта: серверу — для нового чата, стору — для группировки. */
  projectPath?: string;
  /** Полный доступ (bypassPermissions) — для «Разрешить и продолжить». */
  fullAccess?: boolean;
  /**
   * Автоподтверждение безопасных запросов прав. Опасное (записи в git, удаление,
   * миграции) и всё под правилами `ask`/`deny` панель всё равно спросит.
   */
  autoApprove?: boolean;
  /** Модель для разговора (алиас/полное имя); пусто = по умолчанию. */
  model?: string;
  /** Глубина продумывания (--effort); пусто = по умолчанию. */
  effort?: string;
  /**
   * Прогон идёт ступенью НИЖЕ потолка разговора — так уходит веер параллельного
   * запуска, которому человек выбрал модель слабее своей. Сервер по этой отметке
   * разворачивает алиас в свежую модель семейства и дописывает заданию планку
   * сдачи (`loweredWorkPrompt`).
   */
  lowered?: boolean;
  /** Ветвление: правка своего сообщения не дописывает разговор, а создаёт ветку. */
  fork?: boolean;
  /**
   * Разговор, из которого запущен этот. Уходит на сервер и делает чат ВЕТВЬЮ
   * родителя: в списке он встаёт деревом, а его вопросы и запросы прав
   * показываются в родительском чате. Так живут дети разделения — и так же
   * обязан жить любой агент, заведённый из чата, иначе человек ищет вопрос по
   * вкладкам, пока работа стоит.
   */
  parentChatId?: string;
  /** Подпись ветви в дереве: имя проекта или группы. */
  parentTitle?: string;
}

/**
 * Работа продолжена в чистой сессии — или НЕ продолжена, и тогда есть `reason`.
 * Приходит последним событием закрываемого прогона: по нему вкладка переезжает
 * на новый разговор, а не остаётся смотреть на завершённый.
 */
export interface HandoffEvent {
  /** Ключ нового разговора; пусто — продолжения не было. */
  chatId?: string;
  /** Каталог нового разговора — тот же, что и у закрытого. */
  path?: string;
  /** Какой это шаг цепочки. */
  chainDepth?: number;
  /** Почему не продолжили: код разбирается панелью, текст живёт в словаре. */
  reason?: HandoffRefusal;
  /**
   * Окно контекста, из-за размера которого зашла речь о продолжении. Есть только
   * у повода по порогу — у предложения агента причина смысловая, и число тут
   * сбивало бы с толку.
   */
  contextTokens?: number;
  /**
   * Разговор заведён, но прогон не запущен: дерево на паузе, старт отложен до
   * «Продолжить всё». Тост «работа продолжена» здесь соврал бы.
   */
  deferred?: boolean;
  /**
   * Звено конвейера подбора модели: продолжение завела не «чистая сессия», а
   * проверка работы (`review`) или правки по её замечаниям (`fix`). Для вкладки
   * это то же самое событие — работа уехала в соседний разговор того же
   * каталога, — меняется только подпись. `work` приходит после плана группы
   * (Т1): следующее звено за планом — сама работа.
   */
  stage?: 'triage' | 'plan' | 'work' | 'review' | 'fix';
  /** Замечания ревью, по которым заведены правки. */
  findings?: string[];
  /** Работа группы стартовала БЕЗ плана: прогон плана не дал блока (Т1). */
  planMissing?: boolean;
}

export type ChatEvent =
  | {
      kind: 'session';
      sessionId: string;
      model: string;
      tools: number;
      /** Когда сервер завёл прогон — по ЕГО часам, тем же, что пишут транскрипт. */
      startedAt?: number;
    }
  | { kind: 'text'; text: string }
  | { kind: 'thinking'; text: string }
  | { kind: 'tool'; name: string; input: unknown; id: string }
  | { kind: 'limit'; resetsAt: number; type: string; status: string }
  | {
      kind: 'usage';
      input: number;
      output: number;
      cacheRead: number;
      cacheCreation: number;
      cacheCreation1h?: number;
      model?: string;
      costUsd?: number;
      /** Вызовы, рождённые этим шагом; пусто — шаг закончился одним текстом. */
      toolIds?: string[];
      /**
       * Остаток сверки с итогом прогона: расход, который не удалось разнести по
       * шагам. Идёт в счётчик токенов, но не в цену чьего-то действия.
       */
      remainder?: boolean;
    }
  | { kind: 'done'; costUsd: number; durationMs: number; sessionId: string }
  // `retriable` ставит сервер: временный ли сбой, решает он, а не разбор текста.
  | { kind: 'error'; message: string; retriable?: boolean }
  | { kind: 'permission'; toolName: string; input: unknown; toolUseId: string }
  | { kind: 'permissionResolved'; toolUseId: string; behavior: 'allow' | 'deny' }
  | {
      kind: 'branchGate';
      toolName: string;
      input: unknown;
      toolUseId: string;
      cwd: string;
      branch: string;
      children?: BranchGateChild[];
      base?: string;
    }
  /**
   * Заметка панели про прогон: подхвачен после перезапуска сервера без потока
   * вывода (`adopted`) или его процесс закрылся (`detachedDone`). Код — для
   * своего словаря, текст — запасной, если код незнаком.
   */
  | {
      kind: 'notice';
      /**
       * 'adopted' | 'detachedDone' — прогон подхвачен после перезапуска панели;
       * 'triageApplied' | 'triageMissing' — итог разбора разделения (Т1);
       * 'planMissing' — работа группы стартовала без плана (Т1);
       * 'overlap' — ветки разделения сошлись на одних файлах (Т6);
       * 'groupsActivated' — набор, привязанный к проекту, включился сам;
       * 'contextCarried' — незакрытая работа перенесена к другому CLI (П6.1);
       * 'modelDropped' — имя модели не прошло грамматику аргументов;
       * 'childTold' — родитель написал группам блоком `agentdeck:tell` (Д7).
       */
      code:
        | 'adopted'
        | 'detachedDone'
        | 'triageApplied'
        | 'triageMissing'
        | 'planMissing'
        | 'overlap'
        | 'groupsActivated'
        | 'contextCarried'
        | 'modelDropped'
        | 'childTold';
      text: string;
      /**
       * Код самой строки — отдельно от `code`, который называет повод. Есть не
       * у всякой заметки: сводку разбора сервер собирает из счётчиков, шаблона
       * у неё нет, и она остаётся русской строкой.
       */
      textCode?: ServerMessageCode;
      textParams?: ServerMessageNestedParams;
    }
  | ({ kind: 'handoff' } & HandoffEvent)
  /**
   * Ревью чужого MR по ссылке (Т7): замечания посчитаны, решение за человеком.
   *
   * Стор его не обрабатывает намеренно. Карточка решения живёт на ДЕРЕВЕ (одно
   * состояние на хаб и на чат группы), а дерево пульт и так опрашивает; знать о
   * событии сторy надо лишь затем, чтобы оно не выглядело неизвестным видом.
   */
  | {
      kind: 'review';
      chatId: string;
      url: string;
      findings: string[];
      decided?: boolean;
      decision?: 'fix' | 'post' | 'both' | 'none';
      posted?: boolean;
      postError?: string;
      pushOffer?: boolean;
    };

/**
 * Итог приёма отправки. Нужен вызывающему (полю ввода): текст сообщения можно
 * очищать только после того, как сервер его ПРИНЯЛ, иначе отказ уничтожает
 * набранное — человеку остаётся печатать заново.
 */
export type SendOutcome =
  { ok: true } | { ok: false; code?: string; message: string; files?: string[] };

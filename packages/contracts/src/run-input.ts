/**
 * «Что получил агент» (U8): дословный вход каждого прогона, который завела
 * панель, — чтобы человек мог сверить, что ничего не обрезано и не подменено.
 *
 * Переписка этого не показывает: реплика в ней — слова человека или задание
 * звена, а процесс получает ещё дописку к системному промпту (текст панели,
 * правила ребёнка разделения, строку о тестах проекта), сводку детей поверх
 * реплики и, у прогона через контур, системный промпт контура. Запись
 * снимается в той точке, где всё это уже собрано, — ровно то, что уехало CLI.
 */
export interface RunInputRecord {
  /** Время старта прогона, мс. */
  startedAt: number;
  /** Модель, которой прогон шёл на самом деле (через контур — модель контура). */
  model?: string;
  /** Глубина размышлений; нет — CLI решал сам. */
  effort?: string;
  /** Режим прав CLI (`--permission-mode`); у чужого CLI — нет. */
  permissionMode?: string;
  /** Реплика, уехавшая процессу: со сводкой детей и заметкой о каталоге, если были. */
  prompt: string;
  /** Дописка к системному промпту CLI; у чужого CLI — его системная строка. */
  appendSystemPrompt?: string;
  /** Системный промпт контура, ЗАМЕНЯЮЩИЙ промпт CLI (Т5.4а). */
  systemPrompt?: string;
  /** Флаги слоёв панели, снятых с прогона через контур (Т8). */
  platformArgs?: string[];
}

/**
 * Сколько последних прогонов разговора хранится. Текст каждого — целиком, без
 * обрезки: смысл записи в дословности, и урезанный вход доказывал бы обратное.
 * Ограничено число прогонов, а не длина: старые ходы длинного разговора
 * человеку для сверки не нужны, а звенья конвейера укладываются в пару ходов.
 */
export const RUN_INPUT_KEEP = 30;

export interface RunInputsResponse {
  /** Свежие первыми. */
  runs: RunInputRecord[];
}

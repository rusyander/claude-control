/**
 * Git выбранного проекта — компактный пульт во вкладке проекта: где я сейчас,
 * куда переключиться, как завести ветку и закоммитить.
 *
 * Раздел появляется ТОЛЬКО если в каталоге проекта есть `.git` (каталог или
 * файл — так выглядит рабочее дерево worktree). Нет `.git` — нет и пульта:
 * `isRepo: false`, и клиент ничего не рисует.
 *
 * Панель не изобретает своей модели поверх git: всё, что она умеет, — обычные
 * команды (`status`, `checkout`, `checkout -b`, `commit`, `pull`, `push`).
 * Ребейзов и удаления веток здесь нет намеренно: это операции, цену ошибки в
 * которых панель взять на себя не может. Push отправляет только текущую ветку и
 * только вперёд — `--force` не передаётся нигде.
 *
 * `pull` — единственная сетевая операция и единственная, которая может привести
 * к слиянию. Она делает ровно то же, что `git pull` в терминале: при конфликте
 * рабочее дерево остаётся в состоянии конфликта, и разбирать его человек будет
 * сам — панель конфликты не разрешает и не откатывает.
 */

/** Что случилось с файлом. `renamed` несёт ещё и прежний путь в `from`. */
export type ProjectGitFileStatus =
  'added' | 'modified' | 'deleted' | 'renamed' | 'typechange' | 'untracked' | 'conflict';

/** Одна строка списка изменённых файлов. */
export interface ProjectGitChange {
  /** Путь от корня репозитория, как его отдаёт git. */
  path: string;
  status: ProjectGitFileStatus;
  /** Правка уже в индексе (`git add`), а не только в рабочем дереве. */
  staged: boolean;
  /** Прежний путь при переименовании или копировании. */
  from?: string;
}

/** Состояние git-репозитория проекта. */
export interface ProjectGitInfo {
  /** В каталоге проекта есть `.git`. Иначе весь раздел скрыт. */
  isRepo: boolean;
  /** Текущая ветка. Пусто при detached HEAD и в репозитории без коммитов. */
  branch?: string;
  /** HEAD отцеплен от ветки — коммитить и переключаться можно, но не «в ветку». */
  detached: boolean;
  /** В репозитории ещё нет ни одного коммита: веток нет, коммит создаст первую. */
  unborn: boolean;
  /** Локальные ветки, по алфавиту. Удалённые не показываются: переключение — по локальным. */
  branches: string[];
  /** Сколько файлов изменено (учтённые + неучтённые) — по нему включается кнопка коммита. */
  dirtyCount: number;
  /**
   * Сами изменённые файлы, в порядке вывода git. Список ограничен сверху:
   * в репозитории с десятками тысяч правок он смысла не несёт, а трафик съедает.
   */
  changedFiles: ProjectGitChange[];
  /** Список обрезан по потолку — `dirtyCount` при этом остаётся полным. */
  changedFilesTruncated?: boolean;
  /** Удалённый, откуда тянем: `origin`, если он есть, иначе первый по алфавиту. */
  remote?: string;
  /** Ветки на этом удалённом, без префикса `<remote>/` — закрытый список для pull. */
  remoteBranches: string[];
  /** На сколько коммитов текущая ветка впереди upstream (есть только при upstream). */
  ahead?: number;
  /** На сколько отстала — по нему видно, есть ли что тянуть. */
  behind?: number;
  /** git не найден или каталог недоступен: пульт показывает причину и ничего не пишет. */
  error?: string;
}

/** Ответ на любую операцию записи: новое состояние + что именно сделано. */
export interface ProjectGitResult {
  info: ProjectGitInfo;
  /** Строка вывода git — показывается тостом, чтобы результат не был безмолвным. */
  output: string;
}

/**
 * Параллельные рабочие копии одного репозитория (`git worktree`) — то, ради чего
 * несколько агентов могут работать над одним проектом одновременно и не мешать
 * друг другу: у каждой копии свой каталог и своя ветка, а история общая.
 *
 * Ветка копии — СНИМОК на момент чтения, а не свойство копии: агент внутри неё
 * волен переключаться и заводить ветки сам, поэтому клиент показывает то, что
 * git ответил только что, и никогда — то, что было при создании.
 */
export interface ProjectWorktree {
  /** Абсолютный путь рабочей копии — им же открывается вкладка проекта. */
  path: string;
  /** Ветка копии сейчас. Пусто при detached HEAD. */
  branch?: string;
  /** Сокращённый commit, на котором стоит копия. */
  head?: string;
  /** Основная копия (сам репозиторий) — её нельзя удалить. */
  isMain: boolean;
  /** HEAD отцеплен от ветки. */
  detached: boolean;
  /** Копия заперта (`git worktree lock`) — git не даст её удалить. */
  locked: boolean;
  /** Каталога больше нет: копию удалили мимо панели, строка ждёт уборки. */
  prunable: boolean;
}

/** Список копий репозитория. Не репозиторий — `isRepo:false`, раздела нет. */
export interface ProjectWorktreesInfo {
  isRepo: boolean;
  /** Первой всегда идёт основная копия — так их перечисляет сам git. */
  worktrees: ProjectWorktree[];
  /** git не найден или ответил ошибкой: показываем причину, писать не даём. */
  error?: string;
}

/** Ответ на создание или удаление копии: новый список + вывод git. */
export interface ProjectWorktreesResult {
  info: ProjectWorktreesInfo;
  output: string;
  /** Путь созданной копии — по нему панель сразу открывает вкладку. */
  createdPath?: string;
}

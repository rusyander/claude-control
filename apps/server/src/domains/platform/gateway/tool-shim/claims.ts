/**
 * Эвристика H1-послушания: модель ЗАЯВИЛА действие, но вызова не сделала.
 *
 * H1 (§2.3) показала, зачем она нужна: 7B и 14B с полным промптом Claude Code
 * отвечают «Файл создан.», не написав ни одного блока вызова. Файла при этом
 * нет, ход завершён успешно, и человек узнаёт об этом, только открыв папку.
 * Обнаружить такое по проводу нечем — кроме собственных слов модели.
 *
 * Это ПОМЕТКА, а не запрет (Т5.5). Эвристика по словам ошибается в обе стороны:
 * «я создал бы файл» она считает заявкой, а «done» — нет. Блокировать ход по
 * такой догадке нельзя; сказать человеку «модель описала действие, но ничего не
 * вызвала» — можно и нужно, потому что иначе он ищет поломку в панели.
 */

/**
 * Границы слова здесь — свои, через свойства Unicode.
 *
 * `\b` в JavaScript считает словом только латиницу, цифру и подчёркивание, и
 * «\bсоздан\b» не совпадает НИ С ЧЕМ русским: эвристика молчала бы всегда,
 * оставаясь при этом зелёной на любом английском примере. Ошибка ровно того
 * рода, ради которого пометка и заведена, — тихая.
 */
const EDGE_LEFT = '(?<![\\p{L}\\p{N}])';
const EDGE_RIGHT = '(?![\\p{L}\\p{N}])';

/** Русская заявка от первого лица: «я создал», «записал файл». */
const RU_FIRST_PERSON = new RegExp(
  `${EDGE_LEFT}(создал|создала|записал|записала|обновил|обновила|удалил|удалила|изменил|изменила|сохранил|сохранила|выполнил|выполнила)${EDGE_RIGHT}`,
  'iu',
);

/** Русская безличная: «файл создан», «команда выполнена». */
const RU_PASSIVE = new RegExp(
  `${EDGE_LEFT}(файл|каталог|папк\\p{L}*|команд\\p{L}*|скрипт)${EDGE_RIGHT}[^.!?\\n]{0,40}${EDGE_LEFT}(создан\\p{L}*|записан\\p{L}*|обновлён|обновлен\\p{L}*|удалён|удален\\p{L}*|изменён|изменен\\p{L}*|сохранён|сохранен\\p{L}*|выполнен\\p{L}*)${EDGE_RIGHT}`,
  'iu',
);

/**
 * Английская — оба лица сразу. Сокращение `I've` здесь не украшение: модели
 * пишут им чаще, чем полной формой, и без него эвристика молчала бы ровно на
 * самой частой формулировке заявки.
 */
const EN_CLAIM =
  /\b(i(?:['’]ve| have| just| already)?\s+(?:created|written|wrote|updated|deleted|saved|modified|ran|executed)|(?:the )?(?:file|directory|folder|command|script)\b[^.!?\n]{0,40}\b(?:has been |have been |was |were )?(?:created|written|updated|deleted|saved|executed))\b/i;

/** Сослагательное наклонение: «я создал БЫ» — это не заявка о сделанном. */
const RU_WOULD = new RegExp(`${EDGE_LEFT}бы${EDGE_RIGHT}`, 'iu');

/**
 * Отрицание — тот же случай, что сослагательное, и цена ошибки тут выше всего.
 *
 * «Файл не создан — инструмент вернул ошибку доступа» это ЧЕСТНЫЙ ответ о
 * неудаче, и без этой проверки панель показывала его теми же словами, что и
 * галлюцинацию «файл создан»: два противоположных исхода человек не различал
 * никак. Промолчать о настоящей заявке не так дорого — пометка и так лишь
 * пометка.
 */
const RU_NOT = new RegExp(`${EDGE_LEFT}(не|нет)${EDGE_RIGHT}`, 'iu');
const EN_NOT =
  /\b(not|never|cannot|failed|unable|without)\b|n['’]t\b|\b(?:did|was|were|has|have|is|are|could|would|can|will)\s+not\b/i;

/**
 * Ход, в котором модель описала действие словами вместо вызова.
 *
 * Спрашивать её имеет смысл ровно тогда, когда инструменты объявлены (иначе
 * разговор о файлах — обычный разговор) и ни одного вызова не состоялось.
 */
export function claimedWithoutCall(text: string, calls: number): boolean {
  if (calls > 0 || !text.trim()) return false;

  for (const sentence of text.split(/[.!?\n]+/)) {
    if (!sentence.trim()) continue;
    if (RU_WOULD.test(sentence) || RU_NOT.test(sentence) || EN_NOT.test(sentence)) continue;
    if (RU_FIRST_PERSON.test(sentence) || RU_PASSIVE.test(sentence) || EN_CLAIM.test(sentence)) {
      return true;
    }
  }
  return false;
}

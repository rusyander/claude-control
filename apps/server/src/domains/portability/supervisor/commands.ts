/**
 * СЛЭШ-КОМАНДЫ ДЛЯ CLI БЕЗ СВОЕГО МЕХАНИЗМА (П3.4).
 *
 * У Claude команда — это файл, который CLI разворачивает в текст сам. У чужого CLI
 * такого механизма нет, поэтому разворачивает панель: до запуска команда заменяется
 * своим телом, и модель видит обычный текст.
 *
 * Развёртывание ОБЯЗАНО быть видно в переписке. Человек написал три слова, а модели
 * уехало две страницы — не показать этого значит спрятать то, за что он потом
 * получит ответ.
 */

export interface SupervisorCommand {
  /** Имя без ведущей косой черты. */
  readonly name: string;
  /** Тело команды — текст, который уедет вместо неё. */
  readonly body: string;
  /**
   * Куда встают аргументы. Не задано — аргументы дописываются в конец тела:
   * выбрасывать написанное человеком нельзя ни при каких обстоятельствах.
   */
  readonly argsPlaceholder?: string;
}

export interface ExpandedCommand {
  /** Текст, который уедет модели. */
  readonly text: string;
  /** Имя развёрнутой команды — для заметки человеку. */
  readonly name: string;
  /** Аргументы, как их написал человек. */
  readonly args: string;
}

/**
 * Развернуть команду, если запрос ею начинается.
 *
 * `undefined` — команды здесь нет, и текст уезжает как есть. Неизвестная команда
 * тоже уезжает как есть: панель не знает, что имел в виду человек, и выдумывать за
 * него нечего — зато `/` в начале обычной фразы не превратится в отказ.
 *
 * Разбирается ТОЛЬКО начало текста: `/` посреди фразы (путь, дата, регулярное
 * выражение) командой не считается.
 */
export function expandCommand(
  text: string,
  commands: readonly SupervisorCommand[],
): ExpandedCommand | undefined {
  // Имя команды — это имя файла на диске, а имя файла бывает каким угодно:
  // список разрешённых букв отсёк бы команду «/разбор» молча, и человек получил
  // бы в ответ свою же строку с косой чертой. Поэтому запрещено ровно то, что
  // именем быть не может: пробел (за ним начинаются аргументы) и косая черта
  // (за ней начинался бы путь).
  const match = /^\s*\/([^\s/\\]+)(?:[ \t]+([\s\S]*))?$/.exec(text);
  if (!match) return undefined;

  const name = match[1] ?? '';
  const args = (match[2] ?? '').trim();
  const command = commands.find((candidate) => candidate.name === name);
  if (!command) return undefined;

  const placeholder = command.argsPlaceholder;
  const body =
    placeholder && command.body.includes(placeholder)
      ? command.body.split(placeholder).join(args)
      : // Места для аргументов в теле нет — они дописываются в конец. Потерять их
        // нельзя: человек их написал, значит они часть запроса.
        args
        ? `${command.body}\n\n${args}`
        : command.body;

  return { text: body, name, args };
}

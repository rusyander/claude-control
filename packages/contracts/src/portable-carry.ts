import type { HandoffRefusal } from './chat-handoff.ts';

/**
 * Незакрытая работа переезжает вместе со средой (П6.1).
 *
 * Среду панель переносит записями канона, а работу — нет: разговор перенести
 * нечем. Транскрипта в чужом формате не существует ни у одного CLI, и выдумывать
 * его здесь значило бы пообещать человеку то, чего не будет. Поэтому переезжает
 * НЕ переписка, а то же самое, чем живёт продолжение в чистой сессии: файл-опора
 * в рабочем каталоге плюс исходное задание цепочки. Каталог общий для всех CLI,
 * файл лежит в нём — переносить, строго говоря, вообще ничего не надо, надо
 * ОТКРЫТЬ у нового CLI разговор, который прочитает тот же файл.
 *
 * Отсюда три следствия, и все три видны в этих типах:
 *
 *  1. Кандидат несёт `checkpoint` — путь файла-опоры, а не кусок переписки.
 *  2. Причина отказа — `HandoffRefusal`, тот же перечень, которым отказывает
 *     автопродолжение. Своего списка причин у переноса нет намеренно: предел
 *     цепочки и защита от петли обязаны быть ОДНИ, иначе «те же пределы» у двух
 *     дорог к одному и тому же окажутся разными.
 *  3. Исход честно отвечает, легла ли заметка в ленту ИСХОДНОГО разговора
 *     (`noticedSource`). У Claude лента — транскрипт самого Claude Code, панель
 *     в него не пишет, и сказать о переносе она может только в живой прогон.
 *     Разговор без прогона заметки не получит, и это сказано полем, а не
 *     умолчанием.
 *
 * Модуль без zod, как и остальные `portable-*`: точка экспорта
 * `@agentdeck/contracts/portable-carry`, бочка не используется.
 */

/** Один незакрытый разговор глазами переноса. */
export interface CarryCandidate {
  /**
   * Ключ разговора в памяти цепочек: `sessionId` у Claude, `foreignChatKey` у
   * чужого CLI. Им же переносом и просят — второго написания у разговора для
   * цепочек не бывает.
   */
  readonly key: string;
  /** Чей это разговор СЕЙЧАС: провайдер, у которого он лежит. */
  readonly providerId: string;
  /** Идентификатор внутри хранилища провайдера — для ссылки на разговор. */
  readonly chatId: string;
  readonly title: string;
  /** Рабочий каталог: там же лежит файл-опора, и там же откроется продолжение. */
  readonly cwd: string;
  /** Последнее касание, ISO — по нему человек узнаёт свои сегодняшние разговоры. */
  readonly updatedAt: string;
  /** Файл-опора, который прочитает новый разговор. */
  readonly checkpoint: string;
  /** Длина цепочки продолжений на этом разговоре: потолок считается от неё. */
  readonly chainDepth: number;
  /** Переносить можно. `false` — причина названа в `reason`. */
  readonly ready: boolean;
  /**
   * Почему нельзя. Только предохранители продолжения: потолка цепочки нет,
   * файла-опоры нет, файл-опора слово в слово тот же, что при прошлом переносе.
   */
  readonly reason?: HandoffRefusal;
}

/** Что панель предлагает перенести к новому CLI. */
export interface CarryPlan {
  /** Кому переносим — активный провайдер панели. */
  readonly target: string;
  /**
   * Кандидаты: разговоры ЧУЖИХ провайдеров с рабочим каталогом, тронутые внутри
   * окна цепочек. Непригодные не выброшены, а названы причиной: молча
   * укоротившийся список читается как «переносить нечего».
   */
  readonly candidates: readonly CarryCandidate[];
}

/**
 * Почему разговор не завёлся У ЦЕЛИ. Отдельно от `HandoffRefusal`: тот перечень
 * — предохранители продолжения (потолок цепочки, опора), решаемые ДО того, как
 * цель о переносе узнала, и добавлять в него отказ чужого хранилища значило бы
 * смешать «панель не стала» с «у цели не вышло».
 *
 * Все три ветки различимы для человека, и разница у них не косметическая:
 *
 * - `run_not_started` — у Claude прогон не пошёл (ключ не вернул стартер);
 * - `chat_not_created` — хранилище панели не завело разговор чужому CLI;
 * - `send_failed` — разговор заведён, но задание в него не ушло: чинить надо
 *   CLI, а заведённый разговор у цели уже лежит.
 */
export type CarryTargetFailure = 'run_not_started' | 'chat_not_created' | 'send_failed';

/** Чем кончился перенос одного разговора. */
export interface CarryOutcome {
  /** Ключ ИСХОДНОГО разговора — по нему вкладка находит строку списка. */
  readonly key: string;
  /** Разговор у нового CLI заведён. */
  readonly carried: boolean;
  /** Ключ заведённого разговора; пусто — не завели. */
  readonly chatId?: string;
  /** Какой это шаг цепочки: первый перенос — 1. */
  readonly chainDepth?: number;
  /** Почему не перенесли: предохранитель продолжения сказал «нет». */
  readonly reason?: HandoffRefusal;
  /**
   * Почему не перенесли: предохранители пропустили, а цель разговор не завела.
   * Без этого поля три разных отказа цели приезжали одним `carried: false` без
   * единого слова — человек видел «не перенесено» и не знал, чинить ли CLI,
   * хранилище или ничего.
   */
  readonly failure?: CarryTargetFailure;
  /**
   * Заметка легла в ленту исходного разговора. `false` у разговора Claude без
   * живого прогона: сказать было некуда, и панель это признаёт.
   */
  readonly noticedSource: boolean;
}

/** Ответ применения: по строке на каждый запрошенный разговор. */
export interface CarryApplyAnswer {
  readonly target: string;
  readonly outcomes: readonly CarryOutcome[];
}

export interface ResizeHandleProps {
  /** Текущая ширина панели в пикселях. */
  width: number;
  onResize: (width: number) => void;
  min?: number;
  max?: number;
  /** Подпись для скринридера. */
  label: string;
  /**
   * С какой стороны от разделителя лежит панель, которую он тянет. Справа
   * (по умолчанию) движение влево её расширяет, слева — наоборот, и без этой
   * поправки один и тот же разделитель тянулся бы в обратную сторону.
   */
  side?: 'left' | 'right';
}

import type { FastifyInstance } from 'fastify';
import type { ServerContext } from '../context.ts';

/**
 * Единая форма сборки маршрутов: `register<Раздел>Routes(app, ctx)`.
 *
 * Раньше форм было четыре — с контекстом, без контекста, с обязательным
 * реестром третьим параметром и с реестром по умолчанию, — и список регистраций
 * в `index.ts` приходилось читать построчно, сверяя, чем эта строка отличается
 * от соседней. Разницы по существу за этим не стояло: просто каждый модуль
 * заводился отдельно и брал ровно то, что было нужно в тот день.
 *
 * Модулю, которому контекст не нужен, параметр всё равно объявлен: цена — одно
 * неиспользуемое имя, выгода — тип, под который обязан подойти КАЖДЫЙ модуль
 * маршрутов, и таблица регистраций, где все строки одинаковы.
 *
 * Исключение ровно одно и оно осознанное: объект, живущий дольше запроса
 * (реестр прогонов чата, реестр dev-серверов проектов), создаётся в `index.ts`
 * — только оттуда его можно погасить при выходе — и передаётся третьим,
 * ОБЯЗАТЕЛЬНЫМ параметром. Значения по умолчанию здесь опасны: модуль молча
 * заводил бы собственный реестр, до которого никто снаружи уже не дотянется.
 * Такой модуль подводится под общую форму замыканием на месте регистрации.
 */
export type RouteRegistrar = (app: FastifyInstance, ctx: ServerContext) => void;

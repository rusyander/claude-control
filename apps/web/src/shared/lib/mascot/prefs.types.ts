export interface MascotPrefs {
  /** Показывать ли Деку вообще: боковая панель, чат, «не найдено», сбой. */
  enabled: boolean;
  /** Реплики по своей инициативе: советы и комментарии долгих ходов. */
  chatty: boolean;
  /** Приветствие уже прозвучало — второй раз не здороваемся. */
  greeted: boolean;
  /**
   * Реакции на события: связь с сервером пропала и вернулась, ход или группа
   * упали, группа остановлена или доставлена, упёрлись в лимит, долгий ход
   * закончен. Выключены — о сбое хода Дека говорит прежней одной фразой.
   */
  reactions: boolean;
}

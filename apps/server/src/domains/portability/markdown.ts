/**
 * Разбор markdown с шапкой — общее у обеих половин переноса.
 *
 * Живёт отдельным файлом ровно потому, что нужен и импортёру (тело скилла в
 * канон), и эмиттеру (сверка того, что уже лежит у цели, с тем, что мы
 * собираемся записать). Вторая копия этой функции сравнивала бы не то же самое,
 * и «запись не изменилась» стало бы ложью на первом же файле с BOM или CRLF.
 */

/** Тело markdown после шапки. Шапки нет → весь текст. */
export function bodyAfterFrontmatter(raw: string): string {
  const match = /^---\r?\n[\s\S]*?\r?\n---\r?\n?([\s\S]*)$/.exec(raw);
  return (match?.[1] ?? raw).trim();
}

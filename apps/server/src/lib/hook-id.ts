import { createHash } from 'node:crypto';

/**
 * Идентификатор хука — от его содержимого, а не от места в файле.
 *
 * Раньше id складывался из события и двух индексов (`Stop:0:0`). Стоило
 * удалить соседний хук — и все следующие сдвигались, а вместе с ними уезжали
 * отметки «выключено», участие в группах и снимок команды: отметка,
 * поставленная одному хуку, оказывалась на другом.
 *
 * Хеш короткий: он попадает в адрес страницы (`?id=…`) и в состав группы,
 * поэтому должен читаться. Событие оставлено в открытом виде — по нему видно,
 * о чём речь, не заглядывая в файл.
 *
 * Живёт в `lib/`, а не рядом с чтением хуков, потому что тем же ключом
 * хранилище состояния держит снимки выключенных хуков: считай их по-разному —
 * и снимок нельзя будет ни найти, ни удалить (см. `AppStore.disabledHooks`).
 */
export function hookContentId(event: string, matcher: string | undefined, command: string): string {
  // Разделитель — нулевой байт, а не пробел: в matcher и в команде пробелы
  // встречаются сплошь и рядом, и на пробеле пара («a», «b c») дала бы тот же
  // хеш, что и («a b», «c»). Менять его нельзя — id уже записаны в составе
  // групп, в отметках «выключено» и в ссылках вида `?id=…`.
  const digest = createHash('sha1')
    .update(`${matcher ?? ''}\u0000${command}`)
    .digest('hex');
  return `${event}:${digest.slice(0, 8)}`;
}

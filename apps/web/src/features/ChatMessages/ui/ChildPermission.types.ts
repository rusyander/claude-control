import type { PendingPermission } from '@shared/lib/agent-runs';

/**
 * Запрос прав дочернего разговора. Своим файлом — по той же причине, что и
 * `ChildQuestion`: его читают и лента (`ChatMessages.types`), и хаб групп
 * (`ChildStages.types`), а друг друга эти два файла не импортируют.
 */
export interface ChildPermission {
  /** Ключ прогона ребёнка — по нему уходит решение. */
  chatId: string;
  /** Как назван этот чат в списке: человеку нужно понимать, кого он разрешает. */
  title: string;
  /** Всё, на чём ребёнок сейчас стоит: за один ход запросов бывает несколько. */
  permissions: PendingPermission[];
  /**
   * Все ключи разговора: прогона (`new-…`), сессии, списка, псевдонимы дерева.
   * По ним запрос находит карточку своей группы в хабе — ключ прогона с ключом
   * карточки (последнее звено в списке) не совпадает, пока CLI не назвал сессию.
   */
  chatKeys?: string[];
}

import { emitUniversalSections } from './sections.ts';
import type { Emitter } from './types.ts';

/**
 * Канон → Kimi CLI.
 *
 * Хуки — массив таблиц `[[hooks]]` в `config.toml`, таймаут в СЕКУНДАХ, и
 * блокировать умеют лишь три события из четырнадцати: хук-запрет на остальных
 * приезжает наблюдателем, поэтому приговор уводит его с «нативно» — молча запрет
 * не снимается (инвариант 6).
 *
 * Скиллы Kimi читает из `~/.claude/skills` наравне со своим каталогом: скилл,
 * который уже лежит там, копии НЕ получает — иначе у человека появятся два
 * экземпляра одного скилла, которые дальше разойдутся правками.
 */
export const emitToKimi: Emitter = (env, deps) => emitUniversalSections(env, deps);

/** Сколько раз пробуем переподключиться при обрыве, прежде чем сдаться. */
export const MAX_RECONNECT = 5;

/**
 * Сколько тишины в потоке считать обрывом (мс).
 *
 * Сокет умеет умирать молча: уснувшая машина, моргнувшая сеть, перезапуск
 * прокси. Читатель при этом не получает ни ошибки, ни конца потока — он просто
 * ждёт вечно, прогон навсегда остаётся «идущим», а лента прячет из истории
 * ответы этого хода (см. `pages/Chat/lib/liveTurn.ts`) и показывает пустоту.
 * Ровно на это и жаловались: «висит бесконечно, после F5 агент уже ответил».
 *
 * Считаем по пульсу сервера: он шлёт `: ping` каждые 10 секунд
 * (`domains/chat/ChatStream.ts`), значит три пропущенных подряд — уже не
 * задумчивость, а мёртвый сокет. Ждать дольше незачем: переподключение дешёвое
 * и догоняет пропущенное с последнего `seq`.
 */
export const STREAM_STALL_MS = 30_000;

/**
 * Сколько ждать ответа на сам запрос потока (мс).
 *
 * У `fetch` своего срока нет вовсе. Запрос, не получивший сокет (браузер даёт
 * шесть соединений на источник, а панель держит по одному на каждый идущий
 * прогон плюс ленту файлов), встаёт в очередь браузера НАВСЕГДА — и выглядит
 * это точно так же, как работающий агент.
 */
export const STREAM_CONNECT_MS = 30_000;

/** Сколько раз сам перезапускаем прогон, упавший по «мигнувшей» причине. */
export const MAX_AUTO_RETRIES = 2;

/**
 * Сколько потоков прогонов вкладка держит разом.
 *
 * Браузер по HTTP/1.1 даёт шесть соединений на источник — на все вкладки
 * сразу. Одно занимает лента событий, остальные должны оставаться отправке и
 * коротким запросам: три потока плюс лента — четыре, и два свободны даже при
 * скрытой соседней вкладке (та не держит ни одного). Прогоны сверх лимита
 * ведутся опросом `/chat/active` и получают поток, когда он освободится.
 */
export const MAX_STREAMS = 3;

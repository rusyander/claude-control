/**
 * Сколько тишины в потоке считать обрывом (мс).
 *
 * Сокет умеет умирать молча: телефон уснул, сеть моргнула, панель
 * перезапустилась. Читатель при этом не получает ни ошибки, ни конца потока —
 * он ждёт вечно, а прогон навсегда остаётся «идущим». Сервер шлёт `: ping`
 * каждые 10 секунд, значит три пропущенных подряд — уже не задумчивость агента,
 * а мёртвый сокет. Переподключение дешёвое и догоняет пропущенное с `seq`.
 */
export const STREAM_STALL_MS = 30_000;

/**
 * Сколько ждать ответа на сам запрос потока (мс). У `fetch` своего срока нет:
 * запрос к недоступной панели висит бесконечно и выглядит как работающий агент.
 */
export const STREAM_CONNECT_MS = 30_000;

/**
 * Дольше этого срока сохранённая очередь считается протухшей и не досылается.
 * Очередь — «скажи ему вот ещё что, как освободится», а не письмо на завтра:
 * приложение, открытое через сутки, не должно само поднимать агента.
 */
export const QUEUE_MAX_AGE_MS = 2 * 60 * 60 * 1000;

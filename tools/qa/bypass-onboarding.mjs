/**
 * Общий помощник для QA-скриптов: убирает мастер онбординга с дороги теста.
 *
 * Мастер (`OnboardingWizard`) — модалка Radix, которая висит поверх всех
 * страниц, пока в настройках `onboardingDone !== true`, и через focus-trap
 * прячет остальную страницу из дерева доступности (её нельзя закрыть Escape —
 * так задумано). В свежем контексте Playwright это состояние обычное, поэтому
 * без обхода тесты видят только модалку.
 *
 * Обход — чисто клиентский: перехватываем ответ GET /api/settings и подменяем в
 * нём `onboardingDone` на true. Настоящее состояние сервера НЕ меняется (никаких
 * записей), меняется только то, что видит эта вкладка. Вызывать ДО page.goto.
 *
 * `patch` — те же клиентские подмены для настроек, от которых зависит проверка
 * (модель разговора, глубина). Через тот же перехват, а не вторым маршрутом:
 * Playwright отдаёт запрос ПОСЛЕДНЕМУ подходящему обработчику, и вторая подмена
 * настроек просто отменила бы обход мастера.
 */
export async function bypassOnboarding(page, patch = {}) {
  await page.route('**/api/settings', async (route) => {
    // Запрос может быть ещё в полёте, когда проверка уже закрыла браузер: тогда
    // любое действие с ним бросает TargetClosedError, и это НЕ отказ проверки —
    // но без перехвата он всплывает необработанным отказом и роняет процесс
    // ненулевым кодом уже после всех «чисто». Прогон a11y так и падал: 62
    // страницы пройдены, а выход 1.
    try {
      if (route.request().method() !== 'GET') return await route.continue();
      const response = await route.fetch();
      let body;
      try {
        body = await response.json();
      } catch {
        return await route.fulfill({ response });
      }
      return await route.fulfill({ response, json: { ...body, ...patch, onboardingDone: true } });
    } catch {
      /* контекст закрыт — отвечать уже некому */
    }
  });
}

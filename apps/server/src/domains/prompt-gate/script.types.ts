import type { PromptGateAction } from '@agentdeck/contracts';

// Отдельно от сборки: английский шаблон (`script-en.ts`) берёт отсюда только
// тип, а сборка берёт шаблон — иначе два модуля импортировали бы друг друга.

export interface GateScriptConfig {
  /** Откуда читать правила — тот же файл, что у прокси. */
  rulesPath: string;
  /** Куда писать журнал; пусто — не писать вовсе. */
  journalPath: string;
  /**
   * `state.json` панели: тумблер «Вести журнал» читается отсюда в момент
   * срабатывания, а не зашивается в скрипт — иначе каждое переключение
   * оставляло бы на диске устаревший файл. Пусто — журнал ведётся всегда.
   */
  statePath?: string;
  action: PromptGateAction;
  /**
   * Язык шапки и сообщений скрипта — язык интерфейса панели при сборке. Только
   * `en`: русский скрипт ключа не несёт и потому собирается байт в байт как до
   * появления языка, иначе установленные гейты стали бы «правкой руками».
   */
  language?: 'en';
}

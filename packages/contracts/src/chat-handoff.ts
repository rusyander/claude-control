/**
 * Передача работы в чистую сессию («автоклир») — формат канала и его разбор.
 *
 * Разговор дорожает с каждым ходом: окно контекста переставляется целиком на
 * каждый запрос, и когда задача закрыта, платить дальше не за что. В самом CLI
 * это лечится командой `/clear`, но вызвать её не может ни модель, ни хук — она
 * живёт на стороне клиента. Панель же держит процесс сама, поэтому «чистая
 * сессия» здесь — это просто прогон БЕЗ `--resume`: новый разговор в том же
 * каталоге, знающий ровно то, что записано в файле-опоре.
 *
 * Канал — блок в ОТВЕТЕ агента, а не вызов инструмента: текст умеет любой CLI.
 *
 * ```claude-control:handoff
 * {"done":"что закрыто","next":"чем продолжить","checkpoint":".agent/PROGRESS.md"}
 * ```
 *
 * Панель прячет блок из показа и рисует на его месте карточку «Продолжить в
 * чистой сессии». Автоматически это происходит, только если человек включил
 * автопродолжение В ЭТОМ разговоре: молча стереть контекст по решению модели —
 * это потеря работы, а не экономия.
 *
 * Модуль намеренно САМОДОСТАТОЧЕН и без zod (как `task-split`, `uploads`,
 * `vocabulary`): его значения нужны и серверу, и обоим отрисовщикам ленты, а
 * сервер работает без сборки (`--experimental-strip-types`) и падает на импорте
 * значения из бочки контрактов. По той же причине разбор блока написан здесь
 * заново, а не взят у разделения задач: подпакеты контрактов друг на друга не
 * ссылаются — общий модуль пришлось бы тащить через три сборщика сразу (Node без
 * сборки, Vite, Metro), и цена такой связки выше тридцати строк разбора.
 */

/** Язык блока: он же признак, по которому панель узнаёт предложение. */
export const HANDOFF_BLOCK_LANG = 'claude-control:handoff';

/** Файл-опора по умолчанию: с него начинается новая сессия. */
export const HANDOFF_DEFAULT_CHECKPOINT = '.agent/PROGRESS.md';

/**
 * Сколько раз подряд разговор может продолжиться сам. Потолок не настройка, а
 * предохранитель: цепочка «закончил → продолжил» без него крутится всю ночь и
 * тратит подписку на задачу, которую человек давно закрыл бы сам.
 */
export const HANDOFF_MAX_CHAIN = 5;

const MAX_DONE = 400;
const MAX_NEXT = 4_000;
const MAX_PRUNED = 400;
const MAX_CHECKPOINT = 200;

/** Предложение агента: этап закрыт, дальше — с чистого листа. */
export interface HandoffProposal {
  /** Что закрыто — строка для карточки, а не пересказ всего разговора. */
  done: string;
  /** Чем продолжить: этот текст уйдёт первым сообщением в новую сессию. */
  next: string;
  /**
   * Файл, из которого новая сессия узнает состояние. Только путь ВНУТРИ проекта:
   * абсолютные и уходящие вверх (`..`) отбрасываются при разборе — по этому пути
   * панель потом проверяет, что чекпойнт действительно обновлён.
   */
  checkpoint: string;
  /** Что вычищено из рабочих файлов перед предложением — для показа человеку. */
  pruned?: string;
}

/** Чат, заведённый под продолжение. */
export interface HandoffStarted {
  /** Ключ нового разговора: под ним он живёт в реестре и в памяти вкладки. */
  chatId: string;
  /** Рабочий каталог — тот же, что и у закрытого разговора. */
  path: string;
  /** Прогон запущен сразу; иначе в чат положен только текст задания. */
  started: boolean;
  /** Текст задания целиком — им засевается поле ввода, когда прогон не пускали. */
  prompt: string;
  /** Какой это шаг цепочки: первый handoff — 1. */
  chainDepth: number;
}

/**
 * Почему автопродолжение не состоялось. Коды разбираются панелью и телефоном,
 * поэтому это перечисление, а не текст: текст живёт в словарях интерфейса.
 */
export type HandoffRefusal =
  /** В ответе нет блока — обычное завершение хода. */
  | 'no_block'
  /** Автопродолжение в этом разговоре не включали. */
  | 'auto_off'
  /** Прогон кончился ошибкой, лимитом или остановкой — продолжать нечего. */
  | 'run_failed'
  /** Цепочка уже длиной в потолок. */
  | 'chain_cap'
  /** Файла-опоры нет: продолжать было бы не по чему. */
  | 'checkpoint_missing'
  /** Файл-опора не обновлялся в этом прогоне — контекст стёрся бы впустую. */
  | 'checkpoint_stale'
  /** Разговор идёт вне проекта: каталог для новой сессии неизвестен. */
  | 'no_project';

/** Итог проверки: либо продолжаем, либо отказ с причиной. */
export type HandoffVerdict =
  | { ok: true; proposal: HandoffProposal }
  | { ok: false; reason: HandoffRefusal; proposal?: HandoffProposal };

/**
 * Одна строка, которая дописывается к системному промпту прогона (у чужих CLI —
 * приписывается к промпту сверху). Именно ОДНА: на Windows аргумент уезжает
 * через оболочку, а перевод строки внутри аргумента cmd.exe разрывает командную
 * строку.
 *
 * Половина инструкции — про уборку, и это не украшение. Чистая сессия читает
 * ровно файл-опору; если в нём лежит вчерашнее вперемешку с закрытым, экономия
 * превращается в потерю: новый агент возьмётся не за то. Поэтому порядок жёсткий
 * — сначала вычистить и записать, и только потом предлагать очистку.
 */
export const HANDOFF_SYSTEM_PROMPT =
  'Когда задача, о которой шёл разговор, закрыта и проверена, не начинай следующую в этом же ' +
  'разговоре: контекст уже дорогой. Сначала приведи в порядок рабочие файлы агента — из ' +
  `${HANDOFF_DEFAULT_CHECKPOINT} убери закрытое и устаревшее, из TASKS.md — сделанное, перенеся ` +
  'каждый пункт одной строкой в .agent/ARCHIVE.md; оставь только незакрытое, принятые решения и ' +
  'пути к коду, после чего запиши туда актуальное состояние работы. Затем выведи РОВНО ОДИН блок ' +
  `кода с языком ${HANDOFF_BLOCK_LANG}, внутри — JSON вида {"done":"что закрыто","next":"чем ` +
  `продолжить","checkpoint":"${HANDOFF_DEFAULT_CHECKPOINT}","pruned":"что вычищено"}. Панель ` +
  'покажет человеку карточку вместо этого блока и по его решению продолжит работу в чистой ' +
  'сессии, поэтому не пересказывай JSON словами. Блока не выводи, пока файл-опора не обновлён в ' +
  'этом же прогоне, и не выводи его, если задача не закончена или ты ждёшь ответа человека.';

/** Строка нужной длины или undefined: пустое поле лучше пустой строки. */
function text(value: unknown, limit: number): string | undefined {
  if (typeof value !== 'string') return undefined;
  const trimmed = value.trim();
  return trimmed ? trimmed.slice(0, limit) : undefined;
}

/**
 * Путь файла-опоры, пригодный для проверки. Наружу проекта не выпускаем: по
 * этому пути сервер потом смотрит время правки, и `..\..\Windows\System32` или
 * `C:\чужое` там не нужны ни в каком виде. Разделитель приводим к прямому слэшу
 * — модель пишет и так, и так, а сравнивать удобнее в одном виде.
 */
function checkpointPath(value: unknown): string | undefined {
  const raw = text(value, MAX_CHECKPOINT);
  if (!raw) return undefined;
  const normalized = raw.replace(/\\/g, '/').replace(/^\.\//, '');
  if (!normalized || normalized.startsWith('/')) return undefined;
  // Диск в начале (`C:/…`) — тоже абсолютный путь, просто по-виндовому.
  if (/^[a-z]:/i.test(normalized)) return undefined;
  if (normalized.split('/').includes('..')) return undefined;
  return normalized;
}

/**
 * Разбор предложения из уже разобранного JSON или из строки. Отбрасываем молча:
 * это ответ модели, а не форма пользователя, — «почти правильный» блок лучше не
 * показывать вовсе, чем стирать по нему разговор.
 */
export function parseHandoffProposal(raw: unknown): HandoffProposal | undefined {
  let value = raw;
  if (typeof value === 'string') {
    try {
      value = JSON.parse(value);
    } catch {
      return undefined;
    }
  }
  if (!value || typeof value !== 'object') return undefined;

  const source = value as {
    done?: unknown;
    next?: unknown;
    checkpoint?: unknown;
    pruned?: unknown;
  };

  const done = text(source.done, MAX_DONE);
  const next = text(source.next, MAX_NEXT);
  if (!done || !next) return undefined;

  const checkpoint = checkpointPath(source.checkpoint) ?? HANDOFF_DEFAULT_CHECKPOINT;
  const pruned = text(source.pruned, MAX_PRUNED);

  return { done, next, checkpoint, ...(pruned ? { pruned } : {}) };
}

/** Что осталось от текста после вырезания блоков и что из них разобрано. */
export interface HandoffScan {
  /** Текст, который видит человек: без блоков и без лишних пустых строк. */
  text: string;
  /** Предложения в порядке появления. */
  proposals: HandoffProposal[];
  /**
   * Сколько закрытых блоков разобрать не удалось. Считается по той же причине,
   * что и у разделения задач: непонятый блок остаётся в ленте текстом, и без
   * этого числа человек видит простыню JSON, не понимая, что панель предложение
   * ОТВЕРГЛА, а не агент так решил написать. Разделение эту строку получило
   * после живого разбора 1 сентября; передача этапа устроена ровно так же, и
   * молчать здесь значило бы ждать того же вопроса второй раз.
   */
  rejected: number;
}

/** Начало блока: тройная кавычка в начале строки и наш язык за ней. */
const OPEN = new RegExp(`(^|\\n)[ \\t]*\`\`\`[ \\t]*${HANDOFF_BLOCK_LANG}[ \\t]*\\r?\\n`);

/**
 * Вырезать блоки предложений из текста ответа.
 *
 * Три случая, и все три встречаются в ленте:
 *
 * - блок закрыт и разобран → уходит из показа, предложение попадает в карточку;
 * - блок закрыт, а JSON внутри сломан → остаётся в тексте КАК ЕСТЬ: прятать то,
 *   чего панель не поняла, значит потерять слова агента без следа;
 * - блок ещё пишется (закрывающей кавычки нет) → всё от него до конца текста
 *   прячем, чтобы лента не показывала голый JSON, пока ответ печатается.
 */
export function scanHandoffBlocks(source: string): HandoffScan {
  const proposals: HandoffProposal[] = [];
  let rejected = 0;
  let rest = source;
  let out = '';

  for (;;) {
    const open = OPEN.exec(rest);
    if (!open) {
      out += rest;
      break;
    }

    // Перенос строки перед кавычками — часть совпадения, но не часть блока:
    // он принадлежит тексту выше и остаётся в показе.
    const lead = (open[1] ?? '').length;
    const bodyStart = open.index + open[0].length;
    out += rest.slice(0, open.index + lead);

    const close = /(^|\n)[ \t]*```[ \t]*(\r?\n|$)/.exec(rest.slice(bodyStart));
    if (!close) break;

    const body = rest.slice(bodyStart, bodyStart + close.index);
    const proposal = parseHandoffProposal(body);
    if (proposal) {
      proposals.push(proposal);
    } else {
      rejected += 1;
      out += rest.slice(open.index + lead, bodyStart + close.index + close[0].length);
    }

    rest = rest.slice(bodyStart + close.index + close[0].length);
  }

  return { text: out.replace(/\n{3,}/g, '\n\n').trim(), proposals, rejected };
}

/**
 * Первое сообщение новой сессии. Собирается в ОДНОМ месте: текст, ушедший в
 * автоматически заведённый чат, и текст, положенный в поле ввода при ручном
 * продолжении, обязаны совпадать — иначе «продолжил сам» и «продолжил кнопкой»
 * разошлись бы уже на второй правке.
 *
 * Первой строкой стоит прямое предупреждение о том, что контекста больше нет:
 * без него агент отвечает так, будто помнит разговор, и первые ходы уходят на
 * пересказ того, чего он не видел.
 */
export function buildHandoffPrompt(proposal: HandoffProposal): string {
  return [
    `Это новая сессия: прошлый разговор закрыт, его контекста у тебя нет.`,
    `Сначала прочитай ${proposal.checkpoint} — там состояние работы.`,
    '',
    proposal.next,
  ].join('\n');
}

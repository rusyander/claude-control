/**
 * Процент окна — до трёх знаков после точки и НИ ОДНОГО знака сверх того, что
 * дал источник: `68` → «68%», `42.137` → «42.137%», `42.1` → «42.1%». Дописать
 * «68.000%» значило бы заявить точность до тысячной, которой у сервера нет —
 * сейчас он отдаёт целые проценты.
 */
export function formatLimitPercent(percent: number): string {
  return `${Math.round(percent * 1000) / 1000}%`;
}

/**
 * Общий сигнал «формат чужого конфига не распознан» — один на все форматы.
 *
 * Он не про TOML и не про YAML: любой раздел, который читает файл чужого CLI и
 * не может доказать, что перепишет его без потерь, бросает ровно этот класс, а
 * маршрут превращает его в 422 «только для чтения». Отдельный модуль нужен
 * потому, что класс обязан быть ОДИН: два объявления — и `instanceof` в
 * маршрутах молча перестанет ловить половину случаев.
 *
 * `lib/codex-toml.ts` и `lib/aider-yaml.ts` переэкспортируют его: прежние пути
 * импорта продолжают работать, объявление остаётся здесь одно.
 */

/** Формат файла не распознан → раздел только для чтения, запись запрещена. */
export class UnrecognizedFormatError extends Error {
  constructor(message = 'Формат файла не распознан — раздел доступен только для чтения.') {
    super(message);
    this.name = 'UnrecognizedFormatError';
  }
}

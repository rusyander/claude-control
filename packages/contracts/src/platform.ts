/** Ответ `GET /api/platforms/:id/apply` — предпросмотр без единой записи. */
export interface PlatformApplyPlan {
  platformId: string;
  /** Управляемый профиль эндпоинта, порождаемый контуром. */
  profileId: string;
  /** Адрес шлюза для целей в диалекте OpenAI (с версией). */
  baseUrl: string;
  /** Тот же адрес без версии — так его ждут anthropic-клиенты. */
  rootUrl: string;
  /** Шлюз поднят и контур включён: без этого применять нечего. */
  ready: boolean;
  targets: PlatformApplyTarget[];
  /**
   * «Где работает контур» — потребители маршрута с уже проставленными
   * галочками и причинами недоступности.
   *
   * Едет вместе с планом файлов намеренно: это два ответа на один вопрос
   * человека («что будет, если я это включу»), и разносить их по двум
   * запросам значило бы показать их на экране в разные моменты.
   */
  consumers: PlatformConsumerOption[];
  /**
   * Модель, которая уедет в управляемый профиль и в конфигурацию CLI (Т6), и
   * откуда она взялась. Пустая `model` — единственное честное «не выбрана»:
   * пробы не было, человек не выбирал, и CLI пойдёт с именем вендора, которого
   * контур не знает. План обязан сказать это ДО записи, а не после 403.
   */
  model: string;
  modelSource: PlatformModelSource;
  /**
   * Чем у целей-CLI дойдут инструменты. Едет с планом, потому что подпись у
   * цели («работает как чат» или «через прослойку») зависит от него, а мастер
   * рисует цели раньше, чем карточка контура появится в списке.
   */
  toolRoute: PlatformToolRoute;
}

/** Потребитель, которого выбрал человек, — то, что уходит в `PUT /api/platforms/:id`. */
export type PlatformSelectedConsumer = PlatformConsumerId;

/** Что реально записано в одну цель. */
export interface PlatformApplyEntry {
  targetId: string;
  filePath: string;
  written: PlatformVarPlan[];
  /** Копия файла до правки — та же, что показывает History. */
  backupPath?: string;
}

/** Ответ `POST /api/platforms/:id/apply`. */
export interface PlatformApplyResult {
  applied: PlatformApplyEntry[];
  /** Цель пропущена и почему — конфликт без явного выбора или неподдержанная цель. */
  skipped: { targetId: string; reason: PlatformTargetReason | 'conflict' }[];
}

/** Одна цель при откате. */
export interface PlatformRollbackEntry {
  targetId: string;
  filePath: string;
  /**
   * Файл вернулся в исходный вид (`restored`), был изменён человеком после
   * применения и потому оставлен как есть (`kept`), либо исчез сам (`missing`).
   */
  outcome: 'restored' | 'kept' | 'missing';
}

/** Ответ `POST /api/platforms/:id/disable`. */
export interface PlatformRollbackResult {
  entries: PlatformRollbackEntry[];
  /** Управляемый профиль удалён вместе с применением. */
  profileRemoved: boolean;
}

/**
 * След применения — срез состояния панели (`state.json`), не настройка.
 *
 * Хранит ровно то, что нужно откату: что было в файле ДО нас и каким мы его
 * оставили. Отпечаток — единственный способ отличить «человек не трогал» от
 * «человек правил после нас», а без этого откат затирал бы чужую работу.
 */
export interface PlatformAppliedTarget {
  targetId: string;
  filePath: string;
  appliedAt: string;
  /** Ключи, которые панель записала, и их прежние значения (пусто — ключа не было). */
  previous: { key: string; value?: string }[];
  /** Прежний вид региона файла — для целей, у которых правится не env, а кусок конфига. */
  previousRegion?: string;
  /** sha1 файла сразу после нашей записи — сверяется, только если нет `ownedFingerprint`. */
  fingerprint: string;
  /**
   * sha1 одних НАШИХ значений сразу после записи (аудит DRV-02): правка других
   * ключей того же файла — прав, хуков, чужих переменных — расхождением не считается.
   * Нет у следа, записанного раньше.
   */
  ownedFingerprint?: string;
  backupPath?: string;
}

export interface PlatformAppliedRecord {
  platformId: string;
  profileId: string;
  targets: PlatformAppliedTarget[];
  /** Ассистент панели был переключён на контур — при откате вернём прежний выбор. */
  previousAssistantProfileId?: string;
}

/**
 * «Ждёт вас» (этап 12, P153): одна функция на доску ядра, ретранслятор и телефон. Задача ждёт
 * человека, только если открыт хоть один БЛОКИРУЮЩИЙ вопрос — без действия по умолчанию
 * (`defaultAction === null`). Неблокирующий вопрос оставляет карточку в её колонке со значком;
 * пауза человеком, провал и ожидание окна — не «ждёт вас».
 *
 * Без единого импорта: модуль грузится телефоном как значение (`metro.config.js` VALUE_MODULES),
 * а импорт потянул бы zod и соседние схемы в сборку телефона.
 */

/** Что функции нужно знать о вопросе: строка свёртки, вид вопроса панели или сам `human.asked`. */
export interface WaitingAsk {
  /** `null` — вопрос блокирует; строка — действие по умолчанию; нет поля — вид до этапа 12. */
  defaultAction?: string | null;
  /** Нет поля — это сама строка `human.asked`, то есть вопрос открыт. */
  state?: string;
}

/** Вопрос держит задачу: открыт и без действия по умолчанию. */
export function askWaits(ask: WaitingAsk): boolean {
  return ask.defaultAction === null && (ask.state === undefined || ask.state === 'open');
}

/** Задача ждёт человека: хоть один вопрос держит её. */
export function taskWaits(asks: readonly WaitingAsk[]): boolean {
  return asks.some(askWaits);
}

/** Чип ввода чата с готовым текстом для агента (выбранный элемент сайта и подобное). */
export interface ComposerChip {
  /** Один и тот же предмет — один чип: повторный выбор того же элемента его не дублирует. */
  id: string;
  /** Что видно на чипе: коротко, без разметки. */
  label: string;
  /** Подсказка при наведении: полный селектор, адрес. */
  title?: string;
  /** Блок, который уйдёт агенту в сообщении вместе с набранным текстом. */
  block: string;
}

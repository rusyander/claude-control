/**
 * Какой моделью пойдёт ОДИН прогон через контур (Т6).
 *
 * Живёт в контрактах, а не на сервере, по той же причине, что и каскад моделей:
 * ответ нужен ОБОИМ берегам. Сервер кладёт выбранное имя в окружение прогона и
 * в `--model`, а шапка чата обязана показать то же самое ДО запуска — человек
 * выбирает модель там же. Две реализации разошлись бы молча: в шапке стояло бы
 * одно имя, в контур уезжало бы другое, и узнать об этом было бы неоткуда.
 *
 * ПОЧЕМУ ВЫБОР ЧЕЛОВЕКА ВООБЩЕ ПЕРЕВОДИТСЯ. Панель называет модели своими
 * именами (`sonnet`, `opus`) — это имена вендора, и контуру они неизвестны.
 * Прогон со своим выбором уходит с `--model`, оно перебивает адресную
 * переменную окружения, и контур отвечает 403 «модель»: пока имена случайно
 * совпадают, этого не видно, а как только расходятся — падает каждый запуск.
 * Карта соответствия («панельное имя → модель контура») и есть то место, где
 * человек говорит, что `sonnet` у него значит.
 */

/**
 * Минимум, по которому модель каталога отличается от вложения. Структурным
 * типом, а не импортом `PlatformModelInfo`: карточка контура и сервер зовут
 * `catalogChatModels` с одним и тем же списком, а импорт замкнул бы круг
 * (`platform.ts` берёт типы отсюда).
 */
export interface PlatformCatalogModel {
  id: string;
  kind?: string;
  retired?: boolean;
  imageGeneration?: boolean;
}

/**
 * Виды, которыми разговор не ведут. Список семейств, а не «всё, кроме чата», по
 * той же причине, по какой драйвер не считает `{"type":"model"}` объявлением
 * вида: в это поле разные шлюзы кладут разное, и «вид не распознан» обязано
 * оставаться молчанием, а не отказом.
 */
const NOT_CHAT_KINDS = /embed|image|rerank|audio|speech|video|moderation/;

/**
 * Модели каталога, которыми можно ВЕСТИ РАЗГОВОР.
 *
 * Вид объявляет контур. Панель не додумывает виды за платформу: модель без
 * объявленного (или с нераспознанным) видом остаётся в списке, потому что «вид
 * не объявлен» — это не «для чата не годится», а промолчавший контур. Зато
 * ОБЪЯВЛЕННЫЙ не-чат из списка выпадает: до 12.09.2026 здесь стояло «всё, кроме
 * `embed`, — чат», и контур, честно назвавший `image`/`rerank`/`audio`, отдавал
 * модель рисования в выбор разговора, а `defaultModelOf` берёт первую из этого
 * списка — то есть она становилась моделью ВСЕХ прогонов.
 *
 * Пропавшие из каталога (`retired`) не предлагаются: выбрать модель, которой
 * контур больше не отдаёт, значит выбрать будущий 404.
 */
export function catalogChatModels<T extends PlatformCatalogModel>(models: readonly T[]): T[] {
  return models.filter((model) => {
    if (model.retired) return false;
    const kind = model.kind?.toLowerCase() ?? '';
    // Явный чат сильнее семейства: `chat-vision` объявлен чатом и им остаётся.
    if (kind.includes('chat') || kind.includes('text')) return true;
    return !NOT_CHAT_KINDS.test(kind);
  });
}

/**
 * Модель, которую панель подставляет САМА, когда человек не выбирал: первая
 * чатовая модель каталога, не объявившая рисование.
 *
 * Рисование отсекается только здесь, а не в `catalogChatModels`. У enterprise-platform
 * модели рисования приходят видом `chat` с флагом `image_generation`, и контур
 * ведёт их дорогой без цикла инструментов (аудит MD-13): первая в каталоге, она
 * становилась моделью КАЖДОГО прогона агента. Но выбрать её руками человек
 * вправе — у другого шлюза тот же флаг бывает у полноценной чатовой модели, и
 * спрятать её из списка значило бы решить за него. Нет другой — модели нет:
 * подставить рисование молча хуже, чем честное «не выбрана».
 */
export function catalogDefaultModel<T extends PlatformCatalogModel>(
  models: readonly T[],
): T | undefined {
  return catalogChatModels(models).find((model) => model.imageGeneration !== true);
}

/** Откуда взялась модель прогона. */
export type PlatformModelSource =
  /** Имя, которое назвал прогон: контур знает его сам. */
  | 'asked'
  /** Имя прогона переведено картой соответствия. */
  | 'mapped'
  /** Модель этого потребителя (переопределение в карточке контура). */
  | 'consumer'
  /** Модель контура по умолчанию — выбор человека. */
  | 'default'
  /** Человек не выбирал: взята первая чатовая модель каталога. */
  | 'catalog'
  /** Модели нет: каталог пуст и выбора не было. CLI пойдёт со своей. */
  | 'none';

/** Чем пойдёт прогон — и почему именно этим. */
export interface PlatformModelChoice {
  /** Имя, которое уедет в контур. Пусто — контур ничего не назначил. */
  model: string;
  /** Что просил прогон; пусто — не просил ничего. */
  asked: string;
  source: PlatformModelSource;
  /**
   * Просьба прогона заменена. Ради этого признака выбор и возвращается целиком:
   * подмена имени модели — это то, о чём человек узнаёт последним, и шапка чата
   * обязана сказать её вслух, а не показать чужое имя как своё.
   */
  replaced: boolean;
}

/** Из чего считается модель прогона у одного потребителя. */
export interface PlatformModelRules {
  /**
   * Модель контура для этого потребителя: его переопределение, иначе общая по
   * умолчанию, иначе первая чатовая из каталога.
   */
  model: string;
  /** Откуда взялась `model`, когда прогон своей не назвал. */
  source: PlatformModelSource;
  /** Карта соответствия: имя панели → модель контура. */
  map: Record<string, string>;
  /** Идентификаторы моделей каталога: по ним имя прогона узнаётся своим. */
  catalog: readonly string[];
}

/**
 * Регистр в именах моделей не значит ничего ни у одного контура, а человек
 * пишет карту руками — и `Sonnet` в ней против `sonnet` в прогоне не должно
 * стоить ему отказа.
 */
function lower(value: string): string {
  return value.trim().toLowerCase();
}

/**
 * Модель одного прогона. Порядок один и тот же на сервере и в шапке чата:
 *
 * 1. Прогон назвал имя, и оно есть в карте соответствия → перевод.
 * 2. Прогон назвал имя, и контур отдаёт такую модель в каталоге → уезжает
 *    ИДЕНТИФИКАТОР КАТАЛОГА: сверка регистронезависимая (человек набирает имя
 *    руками), а контуру регистр может быть важен, и «совпало» не должно
 *    превращаться в 403.
 * 3. Прогон назвал незнакомое имя → модель контура, и подмена НАЗВАНА
 *    (`replaced`). Молча отпустить незнакомое имя значило бы подарить человеку
 *    403 «модель» на каждом сообщении.
 * 4. Прогон не называл ничего → модель потребителя / по умолчанию / каталога.
 *
 * **У контура может не быть модели вовсе** (пробы не было, каталог пуст, выбора
 * не делали) — и тогда заменять НЕЧЕМ: сервер в этом случае оставляет `--model`
 * прогона как есть, и подмена, объявленная на экране, была бы ложью о пустоте
 * (`source: 'none'`, `replaced: false`). Экран обязан сказать это отдельной
 * строкой, а не показать модель с прочерком.
 */
export function chooseRunModel(rules: PlatformModelRules, asked: string): PlatformModelChoice {
  const wanted = asked.trim();
  // Заменять нечем: модель прогона уезжает как есть (сервер поступает ровно
  // так же — он кладёт модель маршрута в параметры прогона, только если она не
  // пуста), и подмена не объявляется. Карта и каталог ниже при этом работают:
  // строка карты — прямое слово человека, и пустой каталог её не отменяет.
  const nothingToReplace: PlatformModelChoice = {
    model: wanted,
    asked: wanted,
    source: 'none',
    replaced: false,
  };
  const fallback: PlatformModelChoice = rules.model
    ? {
        model: rules.model,
        asked: wanted,
        source: rules.source,
        replaced: Boolean(wanted) && wanted !== rules.model,
      }
    : nothingToReplace;
  if (!wanted) return { ...fallback, replaced: false };

  const mapped = Object.entries(rules.map).find(([from]) => lower(from) === lower(wanted))?.[1];
  if (mapped?.trim()) {
    const model = mapped.trim();
    return { model, asked: wanted, source: 'mapped', replaced: model !== wanted };
  }

  const known = rules.catalog.find((id) => lower(id) === lower(wanted));
  if (known) {
    return { model: known, asked: wanted, source: 'asked', replaced: false };
  }

  return fallback;
}

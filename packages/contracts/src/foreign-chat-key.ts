/**
 * Ключи связей чужих разговоров — ОТДЕЛЬНЫМ модулем, без единой зависимости.
 *
 * Соседний `provider-chat.ts` живёт рядом, но взять их оттуда нельзя: он
 * собирает схемы zod и берёт значение у другого файла контрактов, а сервер
 * читает исходники контрактов как есть (`--experimental-strip-types`), где
 * относительный путь без расширения не разрешается. Поэтому всё, что нужно
 * серверу в РАБОТЕ, а не в типах, лежит в модуле без импортов.
 */
/**
 * Ключ связи чужого разговора: `codex:c1a2b3…`.
 *
 * Идентификатор чужому разговору выдаёт его собственное хранилище, и складывать
 * его в одно пространство с сессиями Claude без приставки нельзя: связь — это
 * АДРЕС, а адрес обязан быть однозначным. Приставка — идентификатор провайдера,
 * разделитель — двоеточие: его нет ни в сессии Claude (uuid), ни во временном
 * ключе разделения (`new-<время>-<номер>`), так что старые связи по-прежнему
 * читаются как свои.
 */
export function foreignChatKey(providerId: string, chatId: string): string {
  return `${providerId}:${chatId}`;
}

/**
 * Разбор ключа обратно. Не именованный ключ — `undefined`, а не догадка: по
 * «голому» идентификатору связь чужого чата не находится, и наоборот.
 */
export function parseForeignChatKey(
  key: string,
): { providerId: string; chatId: string } | undefined {
  const at = key.indexOf(':');
  if (at <= 0 || at >= key.length - 1) return undefined;
  const providerId = key.slice(0, at);
  // Claude сюда не попадает никогда: его разговоры живут под своими ключами, и
  // приставка у них означала бы второй адрес того же чата.
  if (providerId === 'claude') return undefined;
  return { providerId, chatId: key.slice(at + 1) };
}

import { object, string, array, type infer as Infer } from 'zod';

/**
 * Каталог промптов приложения: тексты, которыми панель разговаривает с моделью
 * НЕ от имени человека.
 *
 * Почему они вообще выделены. Промпт режима — это поведение продукта: от него
 * зависит, синтезирует ли модель вызов инструмента, что окажется на слайде и
 * каким тоном агент говорит через корпоративный контур. Пока такой текст лежит
 * строкой в коде, его нельзя ни посмотреть, ни поправить под свой контур, ни
 * вернуть обратно — а правится он чаще всего кодом вокруг него, и человек об
 * этом узнаёт по изменившемуся ответу модели.
 *
 * Поэтому здесь ровно два слоя и ни одного больше:
 *   - ВСТРОЕННЫЙ текст лежит в репозитории (`domains/prompts/catalog/*.md`) и
 *     обновляется вместе с панелью;
 *   - ПРАВКА человека лежит отдельно, в каталоге данных панели, и обновление
 *     панели её не трогает. «Сбросить к встроенному» стирает правку — и текст
 *     репозитория снова становится рабочим.
 *
 * Третьего слоя (промпт на контур, промпт на проект) здесь нет намеренно: он
 * превращает «какой текст уехал модели» в вопрос с четырьмя ответами, и
 * отлаживать такое человеку нечем.
 */

/**
 * Идентификаторы встроенных промптов. Порядок — порядок карточек на экране, и
 * он же порядок чтения: протокол инструментов объясняет, ЧЕМ модель работает,
 * два контурных — как она держится через контур, режимы — что она делает.
 *
 * Идентификатор попадает в адрес (`/api/prompts/:id`) и в имя файла правки,
 * поэтому он стабилен: переименование здесь оставит правку человека сиротой.
 */
export const PROMPT_IDS = [
  'tool-protocol',
  'contour-agent',
  'contour-preamble',
  'image',
  'image-svg',
  'presentation',
] as const;

export type PromptId = (typeof PROMPT_IDS)[number];

export function isPromptId(value: unknown): value is PromptId {
  return typeof value === 'string' && (PROMPT_IDS as readonly string[]).includes(value);
}

/**
 * Потолок длины правки. Промпт уезжает в КАЖДЫЙ запрос режима, и мегабайтный
 * текст — это не «подробная инструкция», а счёт за токены и обрезанный контекст
 * у модели среднего класса. 64 КБ с запасом перекрывают самый длинный
 * встроенный текст и всё ещё читаются человеком целиком.
 */
export const PROMPT_MAX_BYTES = 64 * 1024;

/**
 * Правка человека — то, что хранится на диске и уезжает в архив переноса.
 *
 * `baseSha` — отпечаток ВСТРОЕННОГО текста на момент сохранения. Он отвечает на
 * единственный вопрос, который у человека возникает после обновления панели:
 * «встроенный промпт с тех пор переписали, а я об этом знаю?». Версия для этого
 * не годится — её забывают поднять, отпечаток забыть нельзя.
 */
export const promptOverrideSchema = object({
  id: string(),
  text: string(),
  baseSha: string(),
  updatedAt: string(),
});

export type PromptOverride = Infer<typeof promptOverrideSchema>;

/** Секция правок в архиве переноса окружения. */
export const promptOverridesSchema = array(promptOverrideSchema);

/**
 * Что панель отдаёт экрану. Оба текста приезжают вместе: «Сбросить к
 * встроенному» должен показывать, к ЧЕМУ он вернёт, до нажатия, а не после.
 */
export interface PromptRecord {
  id: PromptId;
  /** Версия встроенного текста; растёт правкой в репозитории, человеку — метка. */
  version: number;
  /** Текст, которым панель работает: правка человека, если она есть, иначе встроенный. */
  text: string;
  /** Встроенный текст репозитория. */
  builtinText: string;
  /** Правка человека существует. */
  overridden: boolean;
  /**
   * Встроенный текст изменился ПОСЛЕ того, как человек сохранил свой: панель
   * обновилась, а правка осталась прежней. Не ошибка — повод перечитать.
   */
  builtinChanged: boolean;
  /** Когда сохранена правка, ISO. Нет правки — нет и отметки. */
  updatedAt?: string;
}

export const promptSaveSchema = object({
  text: string().max(PROMPT_MAX_BYTES, 'промпт длиннее 64 КБ'),
});

/** Строка каталога в ответе списка — без текстов, чтобы список был дешёвым. */
export interface PromptSummary {
  id: PromptId;
  version: number;
  overridden: boolean;
  builtinChanged: boolean;
  bytes: number;
  updatedAt?: string;
}

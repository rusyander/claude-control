/**
 * Похож ли шаблон на известные формы прав доступа. Мягкая проверка — она не
 * блокирует сохранение, лишь подсказывает о возможной опечатке, которая иначе
 * всплыла бы уже в работе.
 *
 * Набор допустимых форм согласован с серверным разбором (`permissions.ts`):
 *   - имя инструмента целиком: `Bash`, `Read`, `WebFetch`;
 *   - имя с уточнением: `Bash(git push:*)`, `Read(~/**)`;
 *   - MCP-инструмент: `mcp__<сервер>__<инструмент>` или весь сервер `mcp__<сервер>`.
 *
 * Важно: в имени MCP-сервера допустимо одиночное подчёркивание
 * (`mcp__my_server__tool`) — разделитель сервер↔инструмент это двойное `__`,
 * ровно как в серверном `MCP_PATTERN`. Прежняя регулярка запрещала `_` в имени
 * сервера и давала ложное предупреждение на именах, которые сервер парсит верно.
 */
export function looksLikePermission(pattern: string): boolean {
  const value = pattern.trim();
  if (!value) return true;
  if (/^[A-Za-z][A-Za-z0-9]*$/.test(value)) return true;
  if (/^[A-Za-z][A-Za-z0-9]*\(.+\)$/.test(value)) return true;
  // Имя сервера: начинается не с `_`, дальше любые символы, но одиночное `_`
  // допускается только когда за ним НЕ идёт второе (иначе это разделитель).
  // Инструмент необязателен — `mcp__server` разрешает весь сервер целиком.
  if (/^mcp__[^_]+(?:[^_]|_(?!_))*(?:__.+)?$/.test(value)) return true;
  return false;
}

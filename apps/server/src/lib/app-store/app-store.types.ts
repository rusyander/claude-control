export interface ChatLink {
  /** Разговор, в котором человек согласился на разделение. */
  parentChatId: string;
  /** Название группы из предложения — подпись ветви в дереве. */
  title?: string;
  /** Ветка, под которой завели копию репозитория. */
  branch?: string;
  /**
   * Номер группы в разделении — ключ её строки в хабе (Д12). Ветка ключом не
   * годится: агент переключает её или уходит в detached HEAD, и одна группа
   * распадалась на две строки.
   */
  groupIndex?: number;
  /**
   * Канонический ключ разговора (Д11): под ним связь записана ПЕРВОЙ, обычно
   * временный `new-…`. Копия на `sessionId` несёт его же — так два ключа одного
   * разговора узнаются и тогда, когда их связи разошлись (`firstEditAt` пишется
   * под ключами одного прогона). Нет — связь старше поля, узнаём по содержимому.
   */
  conversation?: string;
  /** Когда связь записана — по ней вытесняются самые старые. */
  createdAt: string;
  /**
   * Когда звено снято перезапуском групп (ISO). Снятая связь для панели мертва —
   * `getChatLink`/`getChatLinks` её не отдают, — но хранится: по ней список
   * держит старый разговор под родителем (`getRetiredChatLinks`).
   */
  retiredAt?: string;
  /**
   * Чем этот чат ведут: модель и глубина, подобранные под род его работы, и сам
   * распознанный класс.
   *
   * Хранится в связи, а не только в прогоне, потому что прогон кончается, а
   * разговор остаётся: второе сообщение приходит уже без модели (телефон и
   * API-клиенты её не шлют вовсе), и без этой записи оно уехало бы на дефолте из
   * настроек — то есть на другой модели, чем первое.
   */
  model?: string;
  effort?: string;
  kind?: string;
  /**
   * Работа шла НИЖЕ потолка разговора. Отсюда берётся право завести звено
   * проверки: понижение оплачивается ревью на потолке, и знать об этом должен
   * тот, кто заводит следующее звено, а не только тот, кто запускал первое.
   */
  lowered?: boolean;
  /** Первая правка кода агентом в этом разговоре (ISO) — метрика чистого старта. */
  firstEditAt?: string;
  /**
   * Стадия конвейера: `work` — то, что завело разделение, `review` — проверка
   * на потолке, `fix` — правки по её замечаниям. Пусто читается как `work`:
   * связи, записанные до появления конвейера, — это работа и есть.
   */
  stage?: string;
  /**
   * Потолок ТОГО разговора, который завёл цепочку, — на нём пойдёт ревью.
   *
   * Хранится, а не вычисляется заново: потолок складывается из настройки и
   * оверрайда в шапке родительского чата, и второй половины к моменту ревью уже
   * нет нигде. Без записи проверка поехала бы на настройке — то есть, возможно,
   * НИЖЕ модели, ради превосходства которой всё и затевалось.
   */
  ceilingModel?: string;
  ceilingEffort?: string;
  /**
   * Чем шла РАБОТА: на неё возвращается звено правок. У связи ревью `model` —
   * это потолок (им ведут проверку), и без отдельной пары правки уехали бы на
   * потолке тоже, а платить за них второй раз незачем: список замечаний уже
   * превратил неизвестное в понятное.
   */
  workModel?: string;
  workEffort?: string;
  /**
   * Когда по этой работе завели ревью. Отметка одноразовая: без неё второе
   * сообщение человека в тот же чат заводило бы ещё одну проверку — и так на
   * каждый ход.
   */
  reviewedAt?: string;
  /**
   * Когда план этой связи отдан работе (звено `plan`, Т1). Отметка одноразовая
   * по той же причине, что и `reviewedAt`: второе сообщение человека в чат плана
   * без неё заводило бы вторую работу.
   */
  plannedAt?: string;
  /**
   * Когда по концу этого чата (правки или ревью без замечаний) завели звено
   * доставки (W3-3). Одноразово на круг цепочки: сообщение человека в
   * законченный чат правок без отметки заводило бы вторую доставку той же
   * работы. Снова — только по просьбе человека (`asksDelivery`).
   */
  deliveredAt?: string;
  /**
   * Задание группы целиком (с преамбулой копии) — у звеньев `plan` и `work`.
   * Хранится, потому что первое сообщение РАБОТЕ собирается после плана из
   * задания + границ + плана, а задание к тому моменту есть только здесь:
   * промпт прогона плана — это уже промпт плана, не задание.
   */
  task?: string;
  /**
   * Выжимка плана группы от звена плана — едет по всем следующим звеньям, чтобы
   * ревью, правки и доставка знали план, не видя его разговора (аудит 25.09, L238).
   */
  planSummary?: string;
  /** Границы группы из разбора (Т1): чем владеет только она и заметки соседям. */
  owns?: string[];
  notes?: string;
  /**
   * Ревью запроса на слияние по ссылке (Т7): что ревьюим, что нашли и что
   * человек решил с этим делать.
   *
   * Живёт в связи, а не в записи разделения, потому что вопрос задаётся ЧАТУ:
   * карточку решения видно и в хабе родителя, и в самом разговоре группы, а
   * стадия правок — это уже другой чат, которому состояние ревью надо унести с
   * собой. Переезжает на продолжения вместе со всей связью.
   */
  review?: ChatReviewState;
}

/** Ревью по ссылке глазами связи: предмет, замечания, решение и его судьба. */
export interface ChatReviewState {
  url: string;
  /** Ветка MR; на ней же стоит копия, если её удалось узнать. */
  branch?: string;
  /**
   * Копия группы: в ней шло ревью, в ней же пойдут правки и коммит в MR.
   *
   * Хранится здесь, потому что каталога у связи нет вовсе, а решение приходит
   * ЧЕРЕЗ ЧАСЫ после ревью — из хаба, с телефона, после перезапуска панели, — и
   * взять его в тот момент больше неоткуда.
   */
  path?: string;
  /** Копия отведена ОТ ветки MR; `false` — от базы (ревью читало не тот дифф). */
  onMrBranch?: boolean;
  /** Удалённый ветки MR — туда уходит push (Д9). */
  remote?: string;
  /** Копия в detached HEAD на `<remote>/<branch>`: push только `HEAD:<branch>` (Д2). */
  detached?: boolean;
  /**
   * Ревью кончилось без блока `agentdeck:review` (Д4): итога нет, группа не
   * закрыта, на карточке — «повторить ревью». Снимается повтором.
   */
  missing?: boolean;
  /** Замечания из блока ревью; пустой список — законный ответ, группа закрыта. */
  findings?: string[];
  decision?: 'fix' | 'post' | 'both' | 'none';
  decidedAt?: string;
  /** Сводный комментарий записан в MR (ISO). */
  postedAt?: string;
  /** Почему запись не удалась — человеку на карточку, а не в лог. */
  postError?: string;
  /** Правки кончились — панель предлагает закоммитить и отправить их в MR. */
  pushOffer?: boolean;
  /** Правки есть, но push не предложен: ветка MR неизвестна (Д9). */
  pushBlocked?: 'branch-unknown';
  /** Согласие на коммит и push отдано агенту (ISO). */
  pushedAt?: string;
}

/**
 * Состояние группы (Д3): `started` — работает; `awaiting` — ход кончился
 * вопросом или по ревью ждут решения человека; `background` — ход кончился, а
 * фоновая команда агента ещё идёт; `paused` — остановлена человеком (место в
 * очереди отдала, продолжается его кнопкой); `done` — только явный итог;
 * `failed` — сбой. Ждущих соседей отпускают только `done` и `failed`.
 */
export type SplitGroupStatus =
  | 'pending'
  | 'waiting'
  | 'held'
  | 'started'
  | 'awaiting'
  | 'background'
  | 'paused'
  | 'done'
  | 'failed';

/** Группа разделения глазами конвейера уровней (Т1): где она и чего ждёт. */

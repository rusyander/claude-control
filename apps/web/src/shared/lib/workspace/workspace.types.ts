/** Постоянный таб домашнего чата — он всегда есть и не закрывается. */
export const HOME_TAB_ID = 'home';

/** Открытый таб проекта в шапке чата. */
export interface ProjectTab {
  /** Нормализованный путь — стабильный id таба (для дедупликации и адреса). */
  id: string;
  /** Абсолютный путь каталога проекта. */
  path: string;
  /** Короткое имя для подписи таба. */
  name: string;
}

export interface WorkspaceState {
  /** Открытые табы проектов (домашний таб подразумевается первым, вне списка). */
  projectTabs: ProjectTab[];
  /** Активный таб: `home` или id проекта-таба. */
  activeTabId: string;
  /**
   * Какой разговор открыт в каждой вкладке: id таба → id чата (настоящий
   * `sessionId` или временный `new-…` черновик).
   *
   * Ради параллельной работы: пока в одной вкладке думает агент, человек уходит
   * в другую, а возвращаясь — обязан увидеть СВОЙ разговор, а не пустой лист.
   * Без этого «три агента разом» превращались в перебор истории вручную.
   */
  views: Record<string, string>;
}

import type { TextKind } from '@agentdeck/contracts/core/publish';
import { isLetter } from './scan.ts';
import type { TextSieveContext } from './text.types.ts';

/**
 * Строки подписи авторства (published-text: текст говорит, что изменилось и зачем, без авторов):
 * `Co-Authored-By`, `Claude-Session`, `Generated-By` и строки «Generated with/by …» в любом
 * оформлении (эмодзи, курсив, ссылка). `Signed-off-by` — DCO проекта: остаётся только в коммите и
 * только когда его требует настройка пользователя или история репозитория (≥ 80 % коммитов).
 */

export interface TrailerLine {
  line: string;
  start: number;
  end: number;
}

const ATTRIBUTION_KEYS = ['co-authored-by:', 'claude-session:', 'generated-by:'];
const GENERATED = ['generated with ', 'generated by ', 'generated using '];
const SIGN_OFF = 'signed-off-by:';

/** Порог доли подписанных коммитов, с которого подпись — соглашение проекта. */
export const SIGN_OFF_SHARE = 0.8;

export function keepsSignOff(kind: TextKind, ctx: TextSieveContext): boolean {
  if (kind !== 'commit') return false;
  return ctx.config.requireSignOff || (ctx.convention?.signedOffShare ?? 0) >= SIGN_OFF_SHARE;
}

function isAttribution(line: string, keepSignOff: boolean): boolean {
  const lower = line.trim().toLowerCase();
  if (ATTRIBUTION_KEYS.some((key) => lower.startsWith(key))) return true;
  if (lower.startsWith(SIGN_OFF)) return !keepSignOff;
  let i = 0;
  while (i < lower.length && !isLetter(lower[i])) i += 1;
  const bare = lower.slice(i);
  return GENERATED.some((head) => bare.startsWith(head));
}

/** Строки подписи с их промежутком в тексте (конец — до перевода строки). */
export function findTrailers(text: string, keepSignOff: boolean): TrailerLine[] {
  const out: TrailerLine[] = [];
  let start = 0;
  for (const line of text.split('\n')) {
    const end = start + line.length;
    if (isAttribution(line, keepSignOff)) out.push({ line: line.replace('\r', ''), start, end });
    start = end + 1;
  }
  return out;
}

/**
 * Текст без строк подписи. Пустые строки, оставшиеся хвостом (разделитель перед блоком
 * трейлеров), уходят вместе с ним; завершающий перевод строки исходника сохраняется.
 */
export function stripTrailers(text: string, trailers: readonly TrailerLine[]): string {
  const drop = new Set(trailers.map((t) => t.start));
  const kept: string[] = [];
  let start = 0;
  for (const line of text.split('\n')) {
    if (!drop.has(start)) kept.push(line);
    start += line.length + 1;
  }
  const endsWithNewline = text.endsWith('\n');
  while (kept.length > 0 && kept.at(-1)!.trim() === '') kept.pop();
  return kept.join('\n') + (endsWithNewline && kept.length > 0 ? '\n' : '');
}

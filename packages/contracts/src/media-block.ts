/**
 * Картинка и презентация РУКАМИ АГЕНТА — блоком в его ответе.
 *
 * Зачем эта дорога вообще есть. Растровую картинку рисует ручка провайдера, и
 * там, где её нет, режим до этого просто запирался — а неправда в том, что
 * рисовать было чем: любой агент умеет нарисовать вектор кодом и надиктовать
 * структуру колоды, и Claude в том числе (генерации изображений у него нет
 * вовсе, зато SVG он пишет). Поэтому у обоих режимов есть дорога, не требующая
 * ни контура, ни ключа, ни особой возможности модели.
 *
 * Канал — БЛОК В ОТВЕТЕ, а не вызов инструмента, ровно по причине из
 * `task-split.ts`: текст умеет любой CLI, инструменты — только Claude, и формат
 * иначе существовал бы в двух видах. Панель прячет блок из показа и рисует на
 * его месте карточку.
 *
 *     ```agentdeck:deck
 *     {"title":"…","slides":[{"title":"…","bullets":["…"],"notes":"…"}]}
 *     ```
 *
 *     ```agentdeck:svg
 *     <svg viewBox="0 0 800 600" xmlns="http://www.w3.org/2000/svg">…</svg>
 *     ```
 *
 * (Примеры выше нарочно даны отступом, а не забором: с 13.09.2026 разбор считает
 * наш блок внутри чужого забора ЦИТАТОЙ, и файл, показанный агентом человеку,
 * больше не превращается в предложение собрать презентацию.)
 *
 * Модуль самодостаточен и без zod — как и его сосед по идиоме: значения нужны и
 * серверу (он работает без сборки и падает на импорте значения из бочки
 * контрактов), и обоим отрисовщикам ленты, а ручная проверка одна и та же на
 * разборе ответа и на приёме запроса, поэтому разойтись двум пониманиям формата
 * негде.
 *
 * Файл — тонкий фасад над `media-block/`: разбор колоды, проверка рисунка,
 * разбор заборов и конверты просьб лежат по соседству, а все прежние ввозы
 * (`@agentdeck/contracts/media-block`) продолжают работать.
 */


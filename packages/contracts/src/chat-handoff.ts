/**
 * Первое сообщение прогону, продолженному после паузы дерева. Идёт в ТУ ЖЕ
 * сессию (`--resume`), поэтому контекст у агента есть и пересказывать задание
 * не нужно; сказать надо ровно одно — что его остановили снаружи и на чём он
 * стоял, неизвестно: иначе агент считает прерванный инструмент выполненным.
 */
export function buildTreeResumePrompt(): string {
  return [
    'Прогон был остановлен панелью на паузу и сейчас продолжен в той же сессии.',
    'Последний инструмент мог не выполниться — проверь состояние файлов и продолжай работу с того места, где остановился.',
  ].join(' ');
}

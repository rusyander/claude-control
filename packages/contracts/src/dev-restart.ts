/**
 * Отложенный перезапуск dev-сервера (`GET/POST /api/dev-restart`).
 *
 * В разработке сервер поднимает dev-сторож: правка кода перезапускает его, но
 * пока идут ходы чатов или готовятся копии групп, перезапуск ждёт без предела.
 * Панель показывает, что правки ждут, и даёт перезапустить сейчас.
 */

/**
 * Чего ждёт перезапуск: идущих ходов, подготовки копий, автотестов и проверок
 * поломкой (`checks`) — или нескольких из них сразу (`both`).
 */
export type DevRestartWait = 'runs' | 'setup' | 'checks' | 'both';

export interface DevRestartStatus {
  /** Правки сервера ждут перезапуска. Вне dev-сторожа — всегда `false`. */
  pending: boolean;
  /** С какого времени ждут (ISO). */
  since?: string;
  /** Какие файлы правлены, от корня репозитория. */
  files?: string[];
  waitingFor?: DevRestartWait;
  /** Человек уже попросил перезапуск — сторож исполнит его при ближайшей сверке. */
  requested?: boolean;
}

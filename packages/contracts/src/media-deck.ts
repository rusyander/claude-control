import { object, string, type infer as Infer } from 'zod';
import type { CompromiseId } from './compromises';
import type { MediaImageBlocker } from './media';

/**
 * Презентации из чата: тема человека → колода слайдов, которую панель показывает
 * и отдаёт файлом.
 *
 * Колоду СОБИРАЕТ ПАНЕЛЬ из структуры, а не принимает готовый файл от модели, и
 * причина ровно та же, по которой у картинок закрыт список типов: файл из чужого
 * ответа открывается у человека, и решать, что в нём лежит, панель никому не
 * передаёт. Структура же проверяема: заголовок, слайды, пункты, заметки — и из
 * неё панель делает три вида (HTML для показа, PDF печатью системного браузера,
 * PPTX для PowerPoint), ни один из которых не тянет ничего из сети.
 *
 * Отсюда же главное отличие от Т9: у картинок дорога решала, ЧЕМ рисовать, а
 * здесь — КТО надиктует структуру. Умеет это любая текстовая модель, поэтому
 * режим доступен и без контура: колоду диктует агент самого разговора (любой CLI),
 * а контур и свой эндпоинт остаются дорогами для разговоров, где агента нет.
 */

/** Кто надиктует колоду. Решает СЕРВЕР один раз, как и у картинок. */
export const mediaDeckSources = [
  /** Агент этого разговора: отвечает блоком, панель собирает. Любой CLI. */
  'agent',
  /** Активный контур через свой же шлюз (диалект OpenAI). */
  'contour',
  /** Свой эндпоинт человека OpenAI-вида. */
  'endpoint',
] as const;
export type MediaDeckSource = (typeof mediaDeckSources)[number];

/**
 * Почему режим недоступен. Причина машинная, текст — на клиенте; список короче,
 * чем у картинок, потому что дорога агента снимает почти все: чтобы собрать
 * презентацию, особой возможности модели не нужно.
 */
export const mediaDeckBlockers = [
  /** Ни разговора с агентом, ни контура, ни своего эндпоинта. */
  'no-route',
  /** Контур активен, но модель для запроса не названа ни ключом, ни настройкой. */
  'no-model',
  /** Запрос в контур идёт через шлюз панели, а он не поднят. */
  'gateway-off',
  /** Профиль эндпоинта другого вида API: разговор идёт только с OpenAI-видом. */
  'endpoint-api-kind',
] as const;
export type MediaDeckBlocker = (typeof mediaDeckBlockers)[number];

/** Виды файла, которые панель отдаёт по одной колоде. */
export const mediaDeckFormats = ['html', 'pdf', 'pptx'] as const;
export type MediaDeckFormat = (typeof mediaDeckFormats)[number];

/** Почему PDF недоступен. Единственная причина — и она чинится установкой браузера. */
export type MediaDeckPdfBlocker = 'no-browser';

/**
 * Что панель ответит экрану ДО нажатия: кто соберёт, какой моделью, и получится
 * ли PDF. Считается на сервере целиком — ровно по той причине, по которой там же
 * считается план картинки: второй расчёт на клиенте разошёлся бы с настоящим
 * маршрутом.
 */
export interface MediaDeckPlan {
  available: boolean;
  source?: MediaDeckSource;
  /** Кто соберёт, человеческим именем: «агент разговора», контур или профиль. */
  title: string;
  /** Модель, которая уедет в запрос. Пусто — дорога её не называет (агент). */
  model: string;
  reason?: MediaDeckBlocker;
  /**
   * PDF получится только печатью системного браузера, и его наличие — факт
   * файловой системы, а не догадка: не нашёлся — причина названа, а HTML и PPTX
   * остаются на месте.
   */
  pdf: { available: boolean; reason?: MediaDeckPdfBlocker };
  compromise?: CompromiseId;
}

/**
 * Раскладка слайда. Список ЗАКРЫТ намеренно: панель рисует ровно то, что умеет
 * нарисовать и в HTML, и в PPTX, а «свободная вёрстка от модели» означала бы
 * разметку из чужого ответа в нашей странице.
 *
 * Раскладка — главный рычаг вида: колода из одних `bullets` выглядит списком дел
 * (ровно на это жаловался владелец 13.09.2026), а те же факты в `statement`,
 * `stats` и `figure` читаются как презентация.
 */
export const deckLayouts = [
  /** Заголовок и пункты. По умолчанию — и единственная раскладка до 13.09.2026. */
  'bullets',
  /** Один крупный тезис во весь слайд: им открывают и закрывают мысль. */
  'statement',
  /** Два-четыре крупных числа с подписями: то, что запоминают. */
  'stats',
  /** Две колонки: сравнение, «было — стало», «плюсы — цена». */
  'columns',
  /** Цитата с автором. */
  'quote',
  /** Разделитель части: тёмный слайд, номер и название. */
  'section',
  /** Схема во весь слайд и короткая подпись под ней. */
  'figure',
] as const;
export type DeckLayout = (typeof deckLayouts)[number];

/**
 * Цвет колоды. Тоже закрытый список: модель выбирает НАСТРОЕНИЕ, а конкретные
 * цвета остаются на нашей стороне — иначе первая же колода приехала бы с
 * нечитаемым сочетанием, и отвечала бы за это панель.
 */
export const deckAccents = ['indigo', 'teal', 'amber', 'crimson', 'violet', 'slate'] as const;
export type DeckAccent = (typeof deckAccents)[number];

/**
 * Насколько развёрнута колода. Спрашивает АГЕНТ в разговоре (там есть у кого), а
 * на дорогах без разговора панель берёт середину и говорит об этом.
 */
export const deckPresets = [
  /** Полная: разделы, схемы, числа, сравнение, риски, вывод. */
  'deep',
  /** Средняя: костяк истории, две-три схемы, короткие пункты. */
  'balanced',
  /** Короткая: один тезис на слайд, почти без списков. */
  'lean',
] as const;
export type DeckPreset = (typeof deckPresets)[number];

/** Крупное число на слайде: сама величина и подпись под ней. */
export interface DeckStat {
  value: string;
  label: string;
}

/** Колонка сравнения. */
export interface DeckColumn {
  title: string;
  bullets: string[];
}

export interface DeckQuote {
  text: string;
  author: string;
}

/**
 * Источник. Ссылка остаётся ТЕКСТОМ в готовом файле: страница колоды отдаётся с
 * запретом сети, и «кликабельная сноска», которая ничего не грузит, обманывала бы
 * сильнее, чем честный адрес рядом с названием.
 */
export interface DeckSource {
  title: string;
  url: string;
}

/** Потолки колоды. Модель вправе надиктовать что угодно — принимаем разумное. */
export const DECK_MAX_SLIDES = 40;
export const DECK_MAX_BULLETS = 12;
export const DECK_MAX_TITLE = 200;
export const DECK_MAX_BULLET = 400;
export const DECK_MAX_NOTES = 2_000;
export const DECK_MAX_STATS = 4;
export const DECK_MAX_STAT_VALUE = 24;
export const DECK_MAX_COLUMNS = 2;
export const DECK_MAX_QUOTE = 600;
export const DECK_MAX_SOURCES = 16;
export const DECK_MAX_URL = 500;
/**
 * Схема кодом. Потолок свой, меньше картинки режима (512 КБ): схем в колоде до
 * сорока, и одна страница из сорока полумегабайтных SVG не открылась бы.
 */
export const DECK_MAX_FIGURE_CHARS = 32_000;
/** Описание растровой картинки, которую панель дорисует своей дорогой. */
export const DECK_MAX_ILLUSTRATION = 400;
/**
 * Сколько растровых картинок панель рисует на одну колоду. Каждая — запрос к
 * модели и деньги ключа, поэтому потолок низкий и сказан человеку.
 */
export const DECK_MAX_RASTER = 2;
/** Потолок темы от человека — тот же, что у описания картинки. */
export const DECK_PROMPT_MAX = 4_000;

/**
 * Сколько колод панель держит на диске. Тот же потолок, что у картинок, и по той
 * же причине: галереи нет, удалять человеку негде, а каждая колода — это ещё и
 * PDF с PPTX рядом.
 */
export const DECK_KEEP_FILES = 100;

/**
 * Один слайд. Заметка докладчику — часть колоды, а не украшение: её просят.
 *
 * Всё, кроме первых трёх полей, необязательно, и это не вежливость к модели:
 * колода из одних заголовков с пунктами обязана продолжать работать — так
 * выглядели все колоды до 13.09.2026, и такие уже лежат у человека на диске.
 */
export interface DeckSlide {
  title: string;
  bullets: string[];
  notes: string;
  /** Чем рисовать слайд. Пусто — `bullets`, как было всегда. */
  layout?: DeckLayout;
  /** Крупные числа (`stats`). */
  stats?: DeckStat[];
  /** Колонки сравнения (`columns`). */
  columns?: DeckColumn[];
  /** Цитата (`quote`). */
  quote?: DeckQuote;
  /**
   * Схема, нарисованная моделью кодом. Проверяется ТЕМ ЖЕ разбором, что рисунок
   * режима «Картинка кодом»: ни скриптов, ни ссылок наружу — иначе страница
   * колоды перестала бы быть самодостаточной.
   */
  figure?: string;
  /** Подпись под схемой: что именно на ней показано. */
  figureCaption?: string;
  /**
   * Описание растровой картинки для этого слайда. Панель дорисует её САМА, если
   * растровая дорога есть (контур с генерацией, свой эндпоинт), и вшьёт байтами.
   * Нет дороги — слайд остаётся без снимка, и это сказано на карточке.
   */
  illustration?: string;
  /**
   * Картинка, которую панель УЖЕ нарисовала для этого слайда, — идентификатор
   * файла в своём же хранилище. Это поле заполняет панель, а не модель.
   *
   * Зачем оно в колоде, а не в записи: правка возвращает модели структуру
   * целиком, и без этого поля «поправь третий слайд» отправляло бы в мусор
   * картинки остальных — каждая из них стоила запроса и денег ключа. Приходящий
   * от модели идентификатор панель принимает только из СВОЕГО прошлого набора
   * (`presentations.ts`): иначе в колоду можно было бы вписать чужой файл.
   */
  pictureId?: string;
  /** Источники именно этого слайда — сноской под содержимым. */
  sources?: DeckSource[];
}

/** Колода целиком — то, что панель превращает в HTML, PDF и PPTX. */
export interface Deck {
  title: string;
  subtitle: string;
  slides: DeckSlide[];
  /** Настроение цвета. Пусто — `indigo`. */
  accent?: DeckAccent;
  /** Выбранная глубина: её держит запись, чтобы правка не начинала с нуля. */
  preset?: DeckPreset;
  /** Общий список источников — последним слайдом. */
  sources?: DeckSource[];
}

/** Запись о готовой колоде. Самих файлов здесь нет — они рядом, на диске. */
export interface MediaDeck {
  /** Идентификатор, он же имя файлов. Генерирует панель. */
  id: string;
  /** Разговор, из которого попросили. Пусто — попросили из черновика. */
  chatId: string;
  /** Заголовок колоды — им же названы файлы при скачивании. */
  title: string;
  slideCount: number;
  /** Тема человека — то, что уехало модели. */
  prompt: string;
  /** Модель, которая надиктовала. Пусто — дорога её не назвала. */
  model: string;
  source: MediaDeckSource;
  createdAt: string;
  /**
   * Что панель отдаст по этой колоде. `pdf` появляется только там, где нашёлся
   * браузер: обещать кнопку, которая ответит отказом, — то же самое, что скрыть
   * причину.
   */
  formats: MediaDeckFormat[];
  /** Размер показанного HTML. Остальные виды собираются по требованию. */
  sizeBytes: number;
  /**
   * Колода, которую эта заменила. Правка не стирает прежнюю: файлы прежней
   * остаются на диске, пока их не подметёт потолок, — иначе неудачная правка
   * забирала бы с собой и то, что уже показывали.
   */
  revisionOf?: string;
  /** Сколько растровых картинок панель дорисовала своей дорогой. */
  drawnPictures?: number;
  /**
   * Почему растровых картинок нет, хотя модель их просила. Машинная причина —
   * та же, что у режима «Картинка»: человек чинит именно её.
   */
  pictureReason?: DeckPictureBlocker;
  /**
   * Панель обрезала колоду по своим потолкам (слайды, пункты, длина строки).
   * Признак хранится и показывается: иначе «агент надиктовал меньше, чем
   * просили» выглядело бы небрежностью агента, а обрезала панель.
   */
  truncated?: boolean;
}

/**
 * Почему у слайда нет растровой картинки: те же причины, по которым недоступен
 * режим «Картинка», плюс отказ самой ручки рисования.
 */
export type DeckPictureBlocker = MediaImageBlocker | 'draw-failed';

export const mediaDeckRequestSchema = object({
  /** Разговор, к которому привязать колоду. Пусто — черновик без разговора. */
  chatId: string().default(''),
  /**
   * Тема. Обрезка ДО проверки длины — та же ловушка, что оплачена в Т9: строка
   * из пробелов проходила `min(1)` и уезжала в сеть.
   */
  prompt: string()
    .trim()
    .min(1, 'назовите тему презентации')
    .max(DECK_PROMPT_MAX, 'тема длиннее 4000 знаков'),
  /**
   * Правка готовой колоды: её структура уезжает модели вместе с просьбой, и
   * менять она будет ИМЕННО ЕЁ, а не собирать заново по теме. Без этого поля
   * «поправь третий слайд» означало бы новую колоду с новым текстом везде.
   */
  reviseOf: string().trim().max(64).default(''),
});

export type MediaDeckRequest = Infer<typeof mediaDeckRequestSchema>;

/**
 * Колода, которую панель приняла из блока в ответе агента (дорога `agent`).
 *
 * Отдельный запрос, а не поле в общем: там панель САМА ходит к модели, здесь она
 * принимает то, что агент уже сказал в разговоре. Тема нужна и тут — она станет
 * подписью карточки, и без неё через день по колоде не понять, о чём просили.
 */
export const mediaDeckBlockRequestSchema = object({
  chatId: string().default(''),
  prompt: string().trim().max(DECK_PROMPT_MAX, 'тема длиннее 4000 знаков').default(''),
  /** Тело блока как есть — разбирает и проверяет сервер. */
  block: string().min(1, 'блок пустой'),
  /** Модель разговора, чтобы карточка назвала, кто диктовал. */
  model: string().trim().max(120).default(''),
  /** Колода, которую этот блок заменяет (правка по просьбе человека). */
  reviseOf: string().trim().max(64).default(''),
});

export type MediaDeckBlockRequest = Infer<typeof mediaDeckBlockRequestSchema>;

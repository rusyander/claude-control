/**
 * След одного запроса для панели. Тел здесь нет, ключа нет, и НЕТ ТЕКСТА, на
 * котором сработали проверки контура: наружу отдаётся только что именно
 * нарушено (подпись `status-451-bridge`).
 */
export interface PlatformGatewayEvent {
  at: string;
  platformId: string;
  /** Путь запроса как пришёл от CLI. */
  path: string;
  /** На каком диалекте говорил клиент. */
  dialect: string;
  status: number;
  /**
   * Стадии контура из потока: `thinking`, `summarizing`, `generating`; `reasoning` —
   * пришли кадры размышления модели.
   */
  stages: string[];
  /** Контур сжал историю сам — человек обязан это видеть (`context-managed`). */
  summarized: boolean;
  /** Категории сработавших проверок. Проверявшийся текст сюда не попадает. */
  violations: string[];
  /**
   * Контур ЗАМАСКИРОВАЛ часть данных и всё-таки ответил (`platform_sanitized`).
   *
   * Отдельно от `violations` потому, что это другое событие: не отказ, а
   * молчаливая правка того, что увидела модель. Человек, не знающий о ней,
   * читает ответ как ответ на свой запрос — а модель отвечала на другой.
   */
  masked: boolean;
  /**
   * Запрос не приняли ИМЕННО ПРОВЕРКИ СОДЕРЖИМОГО (контур ответил 451).
   *
   * Отдельным полем, а не по коду ответа: клиенту 451 уезжает четырёхсотым, а
   * четырёхсотыми приходят ещё отклонённый ключ, исчерпанный бюджет и лимит
   * частоты. Считать любой отказ отказом проверок значило бы отправить человека
   * чинить свой запрос там, где кончился бюджет.
   */
  blocked: boolean;
  /**
   * Проверки оборвали УЖЕ ИДУЩИЙ ответ. От «запрос не приняли» отличается тем,
   * где человек ищет причину: там — в своём запросе, здесь — в том, что успела
   * сказать модель, и половина ответа у него уже на экране.
   */
  interrupted: boolean;
  /**
   * Чей исход какой: имя проверки → что сделал именно её кадр. Нет поля — исходы
   * запроса относятся ко всем названным проверкам (отказ 451, старый след).
   * Без него правило, оборвавшее ответ, в сводке ещё и «маскировало данные», если
   * в том же запросе маскировало другое.
   */
  violationActions?: Record<string, PlatformViolationAction[]>;
  /** Вендорные кадры, которых шлюз не знает: только имена полей. */
  unknownFrames: string[];
  /**
   * Что не перенёс мост диалектов (`dialect-bridge`). Пусто — перенеслось всё.
   * Молча потерянное поле здесь и есть та ложь, ради которой заведён след:
   * человек считает, что модель видела инструменты, а она их не видела.
   */
  lost: string[];
  /**
   * Что доехало не полем, а ТЕКСТОМ прослойки инструментов (`tool-shim`, Т5):
   * `tools`, `tool_choice`, следы прошлых вызовов.
   *
   * Отдельный список рядом с `lost`, а не строка в нём: «не доехало» и «доехало
   * другим способом» человек чинит в разных местах — первое выключателем
   * прослойки, второе не чинит вовсе.
   */
  shimmed: string[];
  /** Вызовов инструментов, собранных прослойкой из текста ответа. */
  toolCalls: number;
  /**
   * Вызовов, которые контур сделал САМ своими инструментами (Т7, режим
   * `single_turn`). Отдельно от `toolCalls`: сводка прослойки считается по тому
   * счётчику, и вызовы контура в ней читались бы как её работа.
   */
  contourCalls: number;
  /**
   * Вызовов инструментов КЛИЕНТА, которые модель сделала полем `tool_calls` у
   * платформы, принимающей инструменты полем (`clientTools: 'native'`). Отдельно
   * от `contourCalls`: те — набор платформы, эти — руки самого агента.
   * Нет в следах, записанных до аудита DRV-01.
   */
  nativeCalls?: number;
  /** Блоки, которые вызовом не стали, — с причиной каждого. */
  toolFlaws: string[];
  /**
   * Модель описала действие словами и не вызвала ничего (эвристика Т5.5).
   * Пометка, а не запрет: ход состоялся, но файла после него нет.
   */
  claimedWithoutCall: boolean;
  /**
   * Сколько байт картинок приехало частями ответа (Т9). Именно РАЗМЕР: след
   * читает человек, и содержимое картинки в нём не читается ни глазами, ни
   * поиском, зато мегабайт base64 сделал бы журнал нечитаемым целиком.
   * Отсутствует — картинок в ответе не было.
   */
  imageBytes?: number;
  /**
   * Платформа прислала итоговый текст ответа, который НЕ продолжает отданный
   * потоком: её проверки вывода поправили ответ уже после того, как он ушёл.
   * Цельное тело несёт итоговый текст, а клиент потока читал прежний — забрать
   * отданное нельзя, и без этой отметки расхождение не видно нигде.
   * Отсутствует — расхождения не было.
   */
  rewritten?: 'diverged';
  totalTokens: number;
  /**
   * Ответ пришёл, а расхода платформа не прислала: `totalTokens` ноль не потому,
   * что бесплатно, а потому, что счёта нет (так у платформы компании приходит картинка
   * частью ответа). Отсутствует — расход сообщён или ответа не было.
   */
  usageUnreported?: true;
  /** Причина отказа словами, если отказ. */
  error?: string;
}


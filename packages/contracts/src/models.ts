/**
 * Каталог моделей активного провайдера.
 *
 * Панель сама узнаёт, какие модели у провайдера сейчас есть, а не хранит
 * список, зашитый в код: модели выходят чаще, чем обновляется панель, и
 * зашитый список устаревает молча — пользователь просто не видит новую модель
 * в выборе. Источник — открытый каталог models.dev (тот же, которым живёт
 * OpenCode): один запрос отдаёт модели всех вендоров с идентификаторами,
 * семействами, датами выхода и лимитами.
 *
 * Провайдер, для которого вендор не задан (Continue, Goose, Aider, Cursor —
 * это оболочки поверх любых моделей), каталога не получает: угадывать, чей
 * список ему показать, панель не будет (fail-closed).
 */

/** Одна модель в каталоге. */
export interface ModelInfo {
  /** Идентификатор, который принимает CLI/API провайдера (`claude-opus-5`). */
  id: string;
  /** Человеческое имя (`Claude Opus 5`). */
  name: string;
  /**
   * Семейство (`claude-opus`, `gpt-mini`, `gemini-flash`). По нему считается
   * «вышла модель НОВЕЕ той, что стоит по умолчанию»: сравнивать поколения
   * внутри одного семейства осмысленно, между семействами — нет.
   */
  family: string;
  /** Вендор в каталоге (`anthropic`, `openai`, `google`, …). */
  vendor: string;
  /** Дата выхода `YYYY-MM-DD` или `YYYY-MM`; пусто — источник её не знает. */
  releaseDate?: string;
  /** Окно контекста в токенах. */
  contextLimit?: number;
  /** Потолок вывода в токенах. */
  outputLimit?: number;
  /** Умеет рассуждать (reasoning/thinking). */
  reasoning?: boolean;
}

/** Ответ `GET /api/models`. */
export interface ModelCatalogResponse {
  /** Провайдер, для которого собран каталог. */
  provider: string;
  /** Вендоры каталога, относящиеся к этому провайдеру. */
  vendors: string[];
  /** Модели, свежие сверху. */
  models: ModelInfo[];
  /**
   * `models.dev` — данные из сети или из кэша этого источника;
   * `none` — источник ни разу не отвечал, показывать нечего.
   */
  source: 'models.dev' | 'none';
  /** Когда каталог был скачан. Пусто — ни разу не скачивался. */
  fetchedAt?: string;
  /** Данные старше суток — панель покажет, что список может быть неполным. */
  stale: boolean;
  /** Адрес источника — чтобы было видно, откуда цифры. */
  url: string;
  /** Провайдер не объявил вендора: каталог для него не поддерживается. */
  unsupported: boolean;
  /** Идентификаторы моделей, появившихся с прошлого обновления. */
  newIds: string[];
  /** Автозамена модели по умолчанию, если она произошла именно сейчас. */
  promoted?: ModelPromotion;
}

/**
 * Замена модели по умолчанию на более новую того же семейства.
 *
 * Панель делает это сама, когда включено `autoUpdateModels` и в настройках
 * стоит КОНКРЕТНАЯ модель (не алиас и не «как выберет CLI»): алиас `opus` и
 * так означает «последняя», а вот пришпиленный `claude-opus-4-8` остаётся
 * прошлым поколением навсегда, пока его не переставят руками.
 */
export interface ModelPromotion {
  /** Что стояло. */
  from: string;
  /** Что стало. */
  to: string;
  /** Подпись новой модели для сообщения пользователю. */
  toName: string;
  /** Когда заменили, ISO. */
  at: string;
}

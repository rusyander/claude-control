/**
 * Что известно о конце хода тому, кто решает, звать ли человека в Telegram.
 *
 * Факты собирает источник: реестр прогонов панели, чат чужого CLI или
 * транскрипт сессии из терминала и VS Code. Толкует их одно правило
 * (`classifyTurnEnd`), поэтому «закрыта» и «ждёт» значат одно и то же, откуда бы
 * ход ни пришёл.
 */
export interface TurnEndFacts {
  /** Итог хода — текст после последнего вызова инструмента. */
  answer?: string;
  /** На конце хода висит вопрос `AskUserQuestion` (или разрешение) — ждут человека. */
  asked?: boolean;
  /** Текст висящего вопроса — из входа `AskUserQuestion`. */
  question?: string;
  /** Варианты висящего вопроса — их подписи. */
  options?: readonly string[];
  /**
   * Работа пошла дальше: хук Stop отбил конец хода, начался следующий ход,
   * работа уехала в новый разговор, человек уже пишет.
   */
  continued?: boolean;
  /** Ход оборван: процесс умер посреди него или унёс фоновые задачи. */
  interrupted?: boolean;
  /** Чат — звено группы: конец его хода — шаг чужой задачи, о ней скажет группа. */
  subtask?: boolean;
  /** Фоновые задачи ещё идут (панель знает это точно) — их итог вернёт агента в работу. */
  background?: boolean;
  /** Агент сам назначил себе пробуждение — ход вернётся без человека. */
  wakeup?: boolean;
}

/** Почему конец хода — промежуточный и в Telegram не уходит. */
export type IntermediateReason =
  'continued' | 'interrupted' | 'subtask' | 'background' | 'wakeup' | 'progress' | 'empty';

/**
 * Итог разбора: задача закрыта, агент ждёт решения — или промежуточная
 * остановка, о которой человеку не пишут.
 */
export type TurnEnd =
  | {
      kind: 'closed';
      /** Одна-две фразы о том, что сделано, — сырой текст, маска уже наложена. */
      summary: string;
    }
  | {
      kind: 'waiting';
      /** Что решить — вопрос или просьба, сырой текст под маской. */
      ask: string;
      /** Варианты ответа, если они названы. */
      options: string[];
    }
  | { kind: 'intermediate'; reason: IntermediateReason };

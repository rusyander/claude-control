import {
  object,
  string,
  boolean,
  number,
  record,
  array,
  enum as zodEnum,
  type infer as Infer,
} from 'zod';
import { endpointProfileSchema } from './endpoints';
import { dlpSettingsSchema } from './dlp';
import { promptGateSettingsSchema } from './prompt-gate';
import { remoteAccessSettingsSchema } from './remote';

/**
 * Тариф за миллион токенов. Панель считает по нему справочную стоимость —
 * на подписке за токены не списывают, поэтому число означает «столько же
 * работы через API стоило бы вот столько».
 */
export const modelPricingSchema = object({
  input: number().nonnegative(),
  output: number().nonnegative(),
  cacheRead: number().nonnegative(),
  /** Запись кэша со сроком жизни 5 минут — обычный режим. */
  cacheWrite: number().nonnegative(),
  /**
   * Запись кэша со сроком жизни 1 час — в прайсе это ОТДЕЛЬНАЯ колонка (2×
   * базового входа против 1.25× у пятиминутной). Поле необязательное, но
   * молчаливо домножать чужую цену на этот множитель нельзя: пока схема знала
   * четыре поля, zod срезал часовую ставку из своих цен пользователя, и
   * введённые $6.25 превращались в счёте в $10. Пусто у СВОЕЙ цены означает
   * «часовая равна пятиминутной, как введено», а не «выведи множителем».
   */
  cacheWrite1h: number().nonnegative().optional(),
});

export type ModelPricing = Infer<typeof modelPricingSchema>;

/**
 * Строка прайса. Цена привязана к конкретной версии модели, а не к семейству:
 * Opus 4.1 стоит втрое дороже Opus 4.8, и считать их одной ценой — врать в разы.
 * Срок действия нужен ценам, которые меняются по расписанию (вводные тарифы).
 */
export interface PricingEntry {
  id: string;
  label: string;
  price: ModelPricing;
  /** Действует с этой даты (YYYY-MM-DD). */
  from?: string;
  /** Действует по эту дату включительно (YYYY-MM-DD). */
  until?: string;
}

/**
 * Ответ `/api/analytics/pricing`: актуальный прайс и свои цены пользователя.
 * `source` и `fetchedAt` показывают, насколько ценам можно верить — панель
 * обязана это отображать, иначе стоимость снова окажется посчитанной по
 * прошлогоднему прайсу молча.
 */
export interface AnalyticsPricing {
  entries: PricingEntry[];
  /** `anthropic` — прайс с сайта, `built-in` — запасная таблица в коде. */
  source: 'anthropic' | 'built-in';
  fetchedAt: string;
  url: string;
  /** Прайс старше суток либо ни разу не загружался. */
  stale: boolean;
  custom: Record<string, ModelPricing>;
}

export const themeSchema = zodEnum(['light', 'dark', 'system']);
export type Theme = Infer<typeof themeSchema>;

export const languageSchema = zodEnum(['ru', 'en']);
export type Language = Infer<typeof languageSchema>;

/**
 * Цветовой акцент интерфейса. Пресеты, а не произвольный hex: значения берутся
 * из палитры дизайн-системы, поэтому акцент остаётся на токенах и согласуется с
 * обеими темами. `default` — базовый индиго темы.
 */
export const accentSchema = zodEnum(['default', 'blue', 'green', 'purple', 'amber']);
export type Accent = Infer<typeof accentSchema>;

/** Настройки самого приложения — хранятся отдельно от конфигов Claude Code. */
export const appSettingsSchema = object({
  theme: themeSchema.default('system'),
  language: languageSchema.default('ru'),
  /**
   * Цветовой акцент поверх темы — пресет палитры ДС (см. accentSchema).
   * `default` — базовый индиго; остальные переопределяют токены --color-accent*.
   */
  accent: accentSchema.default('default'),
  /**
   * Активный провайдер конфигурации (id из реестра провайдеров). По умолчанию
   * `claude` — панель работает с Claude Code. Пока это единственное валидное
   * значение; сервер сверяет его с реестром. Задел под мульти-провайдерность:
   * в будущих фазах отсюда выбирается адаптер путей/CLI/форматов.
   */
  provider: string().default('claude'),
  /**
   * Пользователь прошёл приветственный мастер первого запуска. Пока false —
   * при открытии панели показывается онбординг (или пока каталог .claude невалиден).
   */
  onboardingDone: boolean().default(false),
  /**
   * Ручной путь к каталогу .claude. Пустая строка — определять автоматически.
   * Заполняется, когда автоопределение не сработало или каталог нестандартный.
   */
  claudeDirOverride: string().default(''),
  /** Показывать значения секретов сразу, без клика по «глазу». */
  revealSecretsByDefault: boolean().default(false),
  /** Делать резервную копию файла перед каждой записью. */
  backupBeforeWrite: boolean().default(true),
  /**
   * Сколько резервных копий одного файла хранить (ротация). Больше — глубже
   * история отката; меньше — меньше копий, в том числе секретов, на диске.
   */
  backupKeep: number().int().min(1).max(100).default(10),
  /** Следить за файлами и обновлять интерфейс при внешних изменениях. */
  watchFiles: boolean().default(true),
  /** Крупнее шрифт и заметнее фокус — для доступности. */
  largeText: boolean().default(false),
  /** Отключить анимации: для чувствительных к движению и слабых машин. */
  reduceMotion: boolean().default(false),
  /** Усиленный контраст интерфейса. */
  highContrast: boolean().default(false),
  /**
   * Команда редактора кода для «Открыть в редакторе» (например, code, cursor,
   * webstorm). Пустая строка — брать первый найденный в системе.
   */
  editor: string().default(''),
  /** Показывать расход в токенах или в деньгах. По умолчанию — токены. */
  costUnit: zodEnum(['tokens', 'money']).default('tokens'),
  /**
   * Потолок ожидания подключения к сетевым MCP-серверам (http/sse), мс. stdio
   * этим не управляется: там в рукопожатие входит запуск процесса, и у него
   * свой потолок в 45с. Меньше — быстрее сдаётся на молчащем адресе; больше —
   * терпит медленные серверы за прокси/туннелем.
   */
  mcpNetworkTimeoutMs: number().int().min(2_000).max(120_000).default(10_000),
  /**
   * Автоматически проверять связь всех включённых MCP-серверов при открытии
   * раздела MCP. Выключено — проверка только по кнопке на карточке.
   */
  mcpAutoCheck: boolean().default(false),
  /**
   * Модель по умолчанию для чата: алиас (opus/sonnet/haiku/fable) или полное имя.
   * Пустая строка — как выберет сам Claude (у этого аккаунта это Opus 4.8, 1M).
   * Централизованный дефолт; в конкретном чате его можно переопределить локально.
   */
  chatModel: string().default(''),
  /**
   * Глубина продумывания по умолчанию для чата (--effort). Пусто — по умолчанию
   * CLI; наш дефолт — очень глубокое обдумывание (xhigh).
   */
  chatEffort: zodEnum(['', 'low', 'medium', 'high', 'xhigh', 'max']).default('xhigh'),
  /**
   * Агент сам предлагает разделить список задач по нескольким чатам, увидев в
   * одном сообщении три и более независимых задачи. Включено — к прогону
   * дописывается строка о формате предложения. Выключено — инициативы нет, но
   * кнопка «Разделить задачи» в поле ввода работает по-прежнему: она посылает ту
   * же просьбу вручную.
   */
  taskSplitInitiative: boolean().default(true),
  /**
   * Агент сам предлагает продолжить работу в чистой сессии, когда задача закрыта:
   * к прогону дописывается строка о формате предложения и о том, что перед ним
   * надо привести в порядок рабочие файлы (`.agent/PROGRESS.md`, `TASKS.md`).
   * Само предложение НИЧЕГО не стирает — оно показывается карточкой, а
   * продолжение начинается кнопкой человека либо, если он это включил, само.
   * Выключено — инициативы нет, но кнопка в поле ввода работает по-прежнему.
   */
  handoffInitiative: boolean().default(true),
  /**
   * Порог контекста, после которого панель предлагает продолжить в чистой
   * сессии, в токенах. Ноль — не следить.
   *
   * Инициатива выше отдаёт решение агенту: он предложит продолжение, когда
   * СЧИТАЕТ задачу закрытой. Разговор же дорожает независимо от того, закрыта
   * задача или нет: каждый запрос перевыставляет накопленное окно целиком, и
   * длинная работа доезжает до автосжатия, где сводка становится сводкой сводок.
   * Этот порог — второй, независимый повод: не «задача кончилась», а «окно
   * стало дорогим». Ничего не стирает сам — предохранители продолжения те же.
   */
  handoffContextLimit: number().int().nonnegative().default(0),
  /**
   * Свои тарифы: фрагмент имени модели → цена за миллион токенов. Пустой
   * объект — считать по встроенным. Заведено потому, что тарифы меняются, а
   * зашитые в код цифры устаревают молча: пользователь видит стоимость, не
   * зная, что она посчитана по прошлогоднему прайсу.
   */
  modelPricing: record(string(), modelPricingSchema).default({}),
  /**
   * Шифровать резервные копии файла секретов `.mcp-secrets.env`. По умолчанию
   * выключено — копии лежат открытым текстом. Когда включено, копии этого файла
   * пишутся зашифрованными (AES-256-GCM, ключ из парольной фразы). Сама фраза
   * НЕ хранится: её запрашивают при включении и при восстановлении.
   */
  encryptSecretBackups: boolean().default(false),
  /**
   * Самой обновлять список моделей активного провайдера (не чаще раза в сутки)
   * и переставлять модель по умолчанию, когда вышло новое поколение того же
   * семейства. Выключено — список обновляется только по кнопке, а дефолт не
   * трогается вовсе.
   */
  autoUpdateModels: boolean().default(true),
  /**
   * Показывать дифф перед записью в конфигурацию ЧУЖОГО CLI. Включено по
   * умолчанию: файлы этих провайдеров человек вёл руками, и «сохранить» вслепую
   * в незнакомом формате — самый неприятный вид доверия. Для Claude
   * предпросмотра нет: его разделы давно свои и проверены.
   */
  previewProviderWrites: boolean().default(true),
  /**
   * Профили своего эндпоинта: адрес модели, вид API и модель. Уровень панели, а
   * не провайдера: один и тот же локальный сервер или корпоративный шлюз обычно
   * раздают на все CLI сразу, и держать его копию в каждом разделе — тот самый
   * ручной ввод `ANTHROPIC_BASE_URL`, ради отмены которого профиль и заведён.
   * ТОКЕНА здесь нет: он в зашифрованном хранилище панели (см. endpoints.ts).
   */
  endpointProfiles: array(endpointProfileSchema).default([]),
  /**
   * Профиль, по которому ходит ассистент САМОЙ панели (формы, проверка
   * провайдера). Пусто — ассистент идёт в облако вендора, как раньше. Отдельно
   * от применения к CLI: панель и CLI могут смотреть в разные стороны, и молча
   * переводить ассистента на чужой адрес вслед за правкой профиля нельзя.
   */
  assistantEndpointId: string().default(''),
  /**
   * Защита данных: локальный прокси между CLI и моделью. Здесь только
   * настройки слушателя — САМИ правила лежат отдельным файлом (`dlp-rules.json`),
   * потому что в их словарях стоят настоящие фамилии и телефоны, а `state.json`
   * ездит между машинами экспортом настроек.
   */
  dlp: dlpSettingsSchema.default(() => dlpSettingsSchema.parse({})),
  /**
   * Гейт на промпте. Правила у него общие с прокси — второго словаря нет
   * намеренно: два списка «что защищать» разошлись бы в первую же неделю.
   */
  promptGate: promptGateSettingsSchema.default(() => promptGateSettingsSchema.parse({})),
  /**
   * Доступ с телефона. Выключено — API живёт как жил, на петле и без токена;
   * включено — токен обязателен всем, включая свой интерфейс (его подставляет
   * прокси Vite, потому что он на той же машине и читает файл токена сам).
   */
  remoteAccess: remoteAccessSettingsSchema.default(() => remoteAccessSettingsSchema.parse({})),
});

export type AppSettings = Infer<typeof appSettingsSchema>;

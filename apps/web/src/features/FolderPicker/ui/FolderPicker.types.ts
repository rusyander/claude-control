export interface FolderPickerProps {
  isOpen: boolean;
  onOpenChange: (open: boolean) => void;
  /** Выбранный путь — абсолютный. В режиме папки это каталог, в режиме файла — файл. */
  onPick: (path: string, name: string) => void;
  /**
   * Что выбираем. По умолчанию папку (выбор проекта — исходное назначение).
   * В режиме `file` кнопки «выбрать эту папку» нет, а щелчок по файлу сразу
   * отдаёт его путь.
   */
  mode?: 'dir' | 'file';
  /** Какие файлы показывать вдобавок к каталогам (`['.zip']`). Только для режима `file`. */
  fileExtensions?: string[];
  /** Заголовок окна. Пусто — заголовок выбора папки проекта. */
  title?: string;
  /** Пояснение под заголовком. */
  hint?: string;
}

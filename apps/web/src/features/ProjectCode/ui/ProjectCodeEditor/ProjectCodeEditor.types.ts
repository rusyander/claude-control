export interface ProjectCodeEditorProps {
  /** Путь от корня проекта: по нему выбирается грамматика подсветки. */
  path: string;
  /** Текущее содержимое файла — оно и правится. */
  content: string;
  /** Текст до правок агента; не задан — сравнивать не с чем. */
  baseline?: string;
  /** Время записи на диске: смена = файл переписали, состояние пересобирается. */
  mtimeMs: number;
  isEditable: boolean;
  showDiff: boolean;
  onChange: (value: string) => void;
  onSave: () => void;
  /**
   * Доступное имя поля правки. Окну кода хватает заголовка окна, а на странице
   * среди других полей текстовое поле без имени скринридер назвал бы просто
   * «поле ввода» — и тест не нашёл бы его по роли.
   */
  ariaLabel?: string;
  /**
   * Фокус в текст сразу при появлении редактора — когда его открыли явной
   * кнопкой «Править». Ставит сам редактор, на своём экземпляре: фокус снаружи
   * попадал в экземпляр, который строгий режим React тут же пересоздаёт, и
   * уходил на body.
   */
  autoFocus?: boolean;
}

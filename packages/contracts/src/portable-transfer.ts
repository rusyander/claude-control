import type { DiffLine } from './history';
import type { EmitEntry } from './portable-emit.ts';
import type { EnvScope } from './portable-env.ts';
import type { FidelityReport } from './portable-fidelity.ts';

/**
 * Перенос среды как ТРИ отдельных шага: показать, применить, отменить (П2.3).
 *
 * Разведены они не ради аккуратности маршрутов. «Сохранить» в чужой конфиг — шаг
 * вслепую: человек не видит ни того, что окажется в файлах, ни того, сколько их.
 * Поэтому план считается первым и НИЧЕГО не пишет, применение принимает только
 * тот план, который человеку показали (`fingerprint`), а отмена существует и без
 * провала: пока нельзя вернуть всё назад одной кнопкой, первую кнопку человек не
 * нажмёт — цена ошибки для него неизвестна.
 *
 * Модуль без zod, как и остальные `portable-*`: сервер берёт его точкой экспорта
 * `@agentdeck/contracts/portable-transfer`, минуя бочку. `DiffLine` приходит
 * ТИПОМ (импорт стирается при сборке), чтобы второй формы строки диффа в панели
 * не завелось: лента истории, предпросмотр одной записи и перенос показывают
 * один и тот же дифф.
 */

/**
 * Одна правка одного файла цели — тем же диффом, что и предпросмотр одной
 * записи (`provider-preview.ts`), и посчитанная тем же способом: настоящая
 * запись по временной копии, а не предсказание.
 *
 * Строка на ФАЙЛ, а не на правку: у цели записи сливаются в один файл —
 * `settings.json` собирает хуки и переменные, конфиг Aider — ссылку на файл
 * инструкций и переменные окружения. Дифф каждого слоя по отдельности показал бы
 * человеку три «версии» одного файла, ни одна из которых не станет тем, что в
 * нём окажется. Поэтому слои применяются к копии ПО ОЧЕРЕДИ, и дифф у файла
 * один — итоговый. Отсюда и множественное число у `kinds` и `itemIds`.
 */
export interface TransferFilePlan {
  readonly filePath: string;
  /** Слои, которые лягут в этот файл — виды канона (`portable-env.ts`). */
  readonly kinds: readonly string[];
  readonly itemIds: readonly string[];
  /** Файл уже существует (иначе перенос его создаст). */
  readonly exists: boolean;
  /** Запись ничего не меняет: у цели уже лежит ровно это. */
  readonly unchanged: boolean;
  readonly lines: readonly DiffLine[];
  readonly added: number;
  readonly removed: number;
  /** Файл слишком велик для построчного сравнения — дифф не строился вовсе. */
  readonly truncated: boolean;
}

/**
 * План переноса: что человеку показывают ДО первой записи.
 *
 * Три списка отвечают на три разных вопроса и потому не сливаются в один:
 * `entries` — что будет с каждой записью паспорта (включая те, что никуда не
 * лягут), `files` — какие файлы цели изменятся и как, `report` — прогноз
 * верности целиком (П1.2), чтобы «работает только при запуске через панель»
 * стояло перед кнопкой, а не после неё.
 */
export interface TransferPlan {
  readonly source: string;
  readonly target: string;
  readonly scope: EnvScope;
  /** Корень цели: дом провайдера или каталог проекта. */
  readonly root: string;
  /**
   * Отпечаток ПОКАЗАННОГО: пара CLI, уровень, исходы всех записей и дифф
   * каждого файла. Применение без него — 409: писать то, чего человек не видел,
   * панель не станет. Он же ловит вторую беду — файлы цели, сменившиеся между
   * показом и нажатием: дифф считается от них, и отпечаток перестаёт совпадать.
   */
  readonly fingerprint: string;
  readonly computedAt: string;
  readonly entries: readonly EmitEntry[];
  readonly files: readonly TransferFilePlan[];
  readonly report: FidelityReport;
}

/**
 * Записи, которые на диск не лягут ничем и держатся запуском через панель или
 * проводом (волны П3 и П4).
 *
 * Считается ОТСЮДА, а не хранится в плане полем: второй список разошёлся бы с
 * исходами молча, и экран показал бы «уйдёт в рантайм» про запись, которая уже
 * легла в файл.
 */
export function runtimeOnlyEntries(plan: TransferPlan): readonly EmitEntry[] {
  return plan.entries.filter((entry) => entry.outcome === 'runtime_only');
}

/**
 * Один файл, тронутый переносом: чем он был до и чем стал сразу после.
 *
 * Без обоих полей отмена невозможна: `backupPath` отвечает, куда возвращаться
 * (а `null` — что файла не было вовсе и отмена его удалит), `writtenHash` — не
 * правил ли человек этот файл уже ПОСЛЕ переноса. Второе важнее первого: вернуть
 * копию поверх его собственной правки значило бы стереть её молча.
 */
export interface TransferFileRecord {
  readonly filePath: string;
  /** Копия «до» с именем провайдера. `null` — файла не существовало. */
  readonly backupPath: string | null;
  /** SHA-256 содержимого сразу после записи. */
  readonly writtenHash: string;
  /**
   * Верхний из каталогов, которых до переноса не было и которые он создал.
   * Отмена удаляет его, если он опустел: иначе «байт в байт как до» оставляло бы
   * после себя пустые папки скиллов и команд.
   */
  readonly createdDir: string | null;
}

/** След одного применённого переноса — то, что делает отмену возможной. */
export interface TransferRecord {
  readonly source: string;
  readonly target: string;
  readonly scope: EnvScope;
  readonly appliedAt: string;
  /** Отпечаток плана, который был применён. */
  readonly fingerprint: string;
  readonly files: readonly TransferFileRecord[];
}

/** Ответ применения: след для отмены и строки о судьбе каждой записи. */
export interface TransferApplyAnswer {
  readonly record: TransferRecord;
  readonly entries: readonly EmitEntry[];
}

/**
 * След последнего переноса к этой цели — то, с чем страница открывается.
 *
 * Отдельный читающий ответ нужен ровно ради одного: кнопка отмены обязана
 * пережить перезагрузку страницы. Держи панель след только в памяти вкладки —
 * человек, вернувшийся к экрану на следующий день, увидел бы перенесённую среду
 * и НИ ОДНОГО способа её вернуть, то есть ровно ту неизвестную цену ошибки,
 * ради которой отмена и заводилась.
 *
 * `changedSince` считается здесь же, а не только при нажатии: «два файла вы
 * правили после переноса» человек обязан прочитать ДО того, как решится, — иначе
 * выбор между «отменить» и «оставить» он делает вслепую.
 */
export interface TransferStateAnswer {
  /** `null` — переноса к этой цели панель не делала (или он уже отменён целиком). */
  readonly record: TransferRecord | null;
  readonly changedSince: readonly string[];
}

/**
 * Ответ отмены.
 *
 * `changedSince` — файлы, которые человек правил уже после переноса. Панель их
 * НЕ трогает, пока он не назовёт их сам: его правка новее нашей записи, и
 * «отменить перенос» не означает «стереть всё, что было потом».
 */
export interface TransferRevertAnswer {
  readonly restored: readonly string[];
  readonly changedSince: readonly string[];
  /** Остаток следа: файлы, которые не вернули. `null` — перенос отменён целиком. */
  readonly record: TransferRecord | null;
}

/**
 * Настроение маскота. Каждое — своя мимика и своё движение:
 *
 *   idle     — покой: следит глазом за курсором, время от времени моргает,
 *              оглядывается, потягивается, подпрыгивает, машет;
 *   working  — агенты работают: шкала вокруг глаза крутится, глаз «читает»;
 *   waiting  — кто-то ждёт ответа человека: подпрыгивает с «!»;
 *   error    — у агента ошибка: встревожен, вздрагивает;
 *   happy    — ход закончен: прыжок, искры, руки вверх;
 *   sleeping — человек давно не трогал панель: глаз закрыт, «z-z-z»;
 *   thinking — даёт совет: глаз вверх, «?»;
 *   waving   — приветствие: машет рукой;
 *   lost     — страница не найдена: оглядывается;
 *   dizzy    — сбой (или его затискали): глаз-спираль, покачивается.
 *
 * Постоянно движется только `working`; в остальных настроениях — разовые
 * действия с паузами (mascot-acts.ts), между ними Дека неподвижен.
 */
export type MascotMood =
  | 'idle'
  | 'working'
  | 'waiting'
  | 'error'
  | 'happy'
  | 'sleeping'
  | 'thinking'
  | 'waving'
  | 'lost'
  | 'dizzy';

export interface MascotProps {
  mood?: MascotMood;
  /** Сторона квадрата, px. */
  size?: number;
  /**
   * Куда смотрит зрачок в покое: −1…1 по каждой оси. Остальные настроения
   * задают взгляд сами — там он часть мимики.
   */
  look?: { x: number; y: number };
  /** Подпись для чтения с экрана; без неё маскот — украшение (`aria-hidden`). */
  label?: string;
  className?: string;
}

export interface MascotCameoProps {
  /** Сколько идёт живой прогон, мс: Дека выходит только на долгом ходу. */
  elapsed: number;
}

export interface MascotNoteProps {
  mood: MascotMood;
  text: string;
}

export interface MascotGreetingProps {
  /** Что рисовать, если маскот выключен в настройках. */
  fallback: React.ReactNode;
  /** Набор советов: в чате — про чат, на других экранах — общий. */
  scope: 'chat' | 'any';
}

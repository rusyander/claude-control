import type { EnvScope } from './portable-env.ts';
import type { FidelityLevel } from './portable-fidelity.ts';

/**
 * Приёмочная проба: отчёт верности из ПРОГНОЗА становится ИЗМЕРЕНИЕМ (П2.4).
 *
 * Матрица (П1) говорит, чего ждать от цели; проба идёт и смотрит, что произошло
 * на самом деле. Две колонки рядом — «обещано» и «проверено» — и есть весь
 * смысл: расхождение между ними является дефектом ПЕРЕНОСА, а не пробы, и
 * читается именно так. Это третий этаж доктрины §9 плана, вынесенный в продукт:
 * человек получает не обещание верности, а её измерение.
 *
 * Модуль без zod и без импортов кода, как остальные `portable-*`: сервер берёт
 * его точкой экспорта `@agentdeck/contracts/portable-probe`, минуя бочку.
 */

/**
 * Шесть слоёв — по одной настоящей пробе на каждый (§9 плана).
 *
 * Имена совпадают с видами канона (`portable-env.ts`) намеренно: проба сажает в
 * дом цели ОБЫЧНУЮ запись своего вида и гонит её тем же эмиттером, что и
 * перенос. Заведи проба свой словарь слоёв — она мерила бы собственную
 * выдумку, а не то, что панель пишет человеку.
 */
export const probeLayers = [
  'hook',
  'skill',
  'permission',
  'mcpServer',
  'envVar',
  'command',
] as const;

export type ProbeLayer = (typeof probeLayers)[number];

/**
 * ЧТО НАБЛЮДАЛИ. Словарь закрыт и нарочно беден: проба отвечает на один вопрос —
 * дошёл ли механизм, — и градаций у ответа ровно столько, сколько различает
 * матрица верности.
 *
 * - `enforced` — механизм СРАБОТАЛ и остановил действие (хук заблокировал,
 *   право отказало). Единственное наблюдение, которым подтверждается «нативно»
 *   у блокирующих слоёв;
 * - `present` — запись доехала и видна там, где обязана быть видна (слово скилла
 *   в запросе к модели, инструмент MCP в списке, значение переменной в
 *   окружении, команда развернулась), но ничего не останавливает;
 * - `absent` — ничего из этого не произошло. Для уровня «невозможно» это верный
 *   исход, для «нативно» — дефект переноса;
 * - `unknown` — прогона не было вовсе. Всегда идёт вместе с названной причиной
 *   (`skip`), потому что «не проверено» без причины неотличимо от «проверено и
 *   ничего не нашли», а это противоположные ответы.
 */
export const probeObservations = ['enforced', 'present', 'absent', 'unknown'] as const;

export type ProbeObservation = (typeof probeObservations)[number];

/**
 * Почему прогона не было. Словарь ЗАКРЫТ — каждая причина переводится на экране,
 * и «не проверено» без причины из этого списка в отчёт не попадает вовсе.
 *
 * Причины первых пяти видов означают «так и задумано»: механизма для измерения
 * ещё нет, и зелёный на его месте был бы враньём. Последние три — про сам
 * прогон.
 *
 * - `cli_not_installed` — бинаря цели нет в PATH: измерять нечем;
 * - `no_probe_recipe` — КАК пробовать этот CLI, не задокументировано: заглушке
 *   нужно ответить его диалектом и назвать его инструменты теми именами, под
 *   которыми он их знает, а выдуманное имя дало бы красный про пробу, а не про
 *   перенос. Список рецептов сокращается правкой кода, а не молчанием;
 * - `no_one_shot` — неинтерактивный запуск этого CLI не задокументирован
 *   (правило 3: форматы и способы запуска — только из документации);
 * - `no_stub_endpoint` — подставить заглушку вместо модели нечем: у цели нет ни
 *   переменной окружения с адресом, ни куска конфигурации, в который его пишет
 *   панель (`continue` — второй такой формат, и рецепта пробы у него пока нет).
 *   Гнать пробу в настоящую модель нельзя ни при каких обстоятельствах: это
 *   чужие деньги и чужой трафик;
 * - `needs_panel_runtime` — обещан уровень «эмуляция»: он держится запуском CLI
 *   через панель, и надзиратель рантайма — отдельная волна (П3);
 * - `needs_wire` — обещан уровень «провод»: нужен контур в пути запроса (П4);
 * - `target_defers_tools` — цель ЗАБРАЛА запись, но модели заранее её не
 *   называет: инструменты MCP она объявляет по запросу, а не списком в запросе.
 *   Живой прогон 22.09.2026 (`codex-cli 0.155.1`): его MCP-клиент пробный сервер
 *   поднял и список инструментов у него взял (`Service initialized as client`),
 *   а в запросе к модели имени инструмента нет вовсе. Красный здесь обвинил бы
 *   перенос в дефекте, которого нет, — но и зелёного тут взять неоткуда;
 * - `emit_failed` — пробная среда для этой цели не собралась: писать было
 *   нечем, и измерять нечего;
 * - `run_failed` — цель запустилась и завершилась ошибкой;
 * - `timed_out` — цель не ответила за отведённое время.
 */
export const probeSkipReasons = [
  'cli_not_installed',
  'no_probe_recipe',
  'no_one_shot',
  'no_stub_endpoint',
  'needs_panel_runtime',
  'needs_wire',
  'target_defers_tools',
  'emit_failed',
  'run_failed',
  'timed_out',
] as const;

export type ProbeSkipReason = (typeof probeSkipReasons)[number];

/**
 * Приговор строки. `mismatch` — красный, и он про ПЕРЕНОС: панель обещала
 * уровень, цель повела себя иначе.
 */
export const probeVerdicts = ['match', 'mismatch', 'not_checked'] as const;

export type ProbeVerdict = (typeof probeVerdicts)[number];

/**
 * Одна строка отчёта пробы: обещание, ожидание, наблюдение, приговор.
 *
 * `expected` стоит отдельным полем, а не выводится экраном из `promised`, по той
 * же причине, по которой `fallback` живёт в приговоре верности: связь «уровень →
 * что обязано наблюдаться» зависит ещё и от слоя (хук обязан ОСТАНОВИТЬ, а
 * переменная окружения — просто доехать), и вторая её реализация на экране
 * разошлась бы с первой молча.
 */
export interface ProbeRow {
  readonly layer: ProbeLayer;
  /** Идентификатор пробной записи канона — та самая, что поехала в дом цели. */
  readonly itemId: string;
  /** ОБЕЩАНО: уровень, посчитанный матрицей (П1) для этой записи у этой цели. */
  readonly promised: FidelityLevel;
  /** Что обязано наблюдаться, если обещание верно. */
  readonly expected: ProbeObservation;
  /** ПРОВЕРЕНО: что произошло. */
  readonly observed: ProbeObservation;
  readonly verdict: ProbeVerdict;
  /** Причина, по которой прогона не было. `null` — прогон был. */
  readonly skip: ProbeSkipReason | null;
  /**
   * Что именно видели — одной строкой, для раскрытия строки на экране. Пусто
   * допустимо; выдуманное значение — нет.
   */
  readonly detail: string;
}

/** Сводка отчёта. Считается из строк, а не копится по ходу. */
export interface ProbeSummary {
  readonly match: number;
  readonly mismatch: number;
  readonly notChecked: number;
}

/**
 * Отчёт приёмочной пробы.
 *
 * `cliCommand` и `cliInstalled` лежат в отчёте, а не подразумеваются: отчёт, в
 * котором шесть строк «не проверено», обязан уметь сказать, что цели попросту
 * нет на машине, — иначе он читается как поломка панели.
 */
export interface ProbeReport {
  readonly target: string;
  readonly scope: EnvScope;
  readonly ranAt: string;
  /** Имя бинаря, которым пробовали запустить цель. */
  readonly cliCommand: string;
  readonly cliInstalled: boolean;
  readonly rows: readonly ProbeRow[];
  readonly summary: ProbeSummary;
}

/**
 * Ожидание по уровню и слою.
 *
 * Блокирующие слои (хук, право) на уровне «нативно» обязаны ОСТАНОВИТЬ действие:
 * инвариант 6 партии — запрет не имеет права молча стать наблюдением, и проба
 * обязана ловить ровно это. Остальные слои на том же уровне обязаны лишь
 * доехать. «Текстом» у любого слоя — это `present`: текст доехал до модели, но
 * ничего не принуждает. «Невозможно» — `absent`, и это ВЕРНЫЙ исход, а не провал.
 *
 * `emulated` и `wired` сюда не попадают: их измеряет не проба, а надзиратель
 * рантайма (П3) и провод (П4), и до них строка честно «не проверена».
 */
export function expectedObservation(
  layer: ProbeLayer,
  level: FidelityLevel,
): ProbeObservation | null {
  if (level === 'emulated' || level === 'wired') return null;
  if (level === 'impossible') return 'absent';
  if (level === 'text') return 'present';
  return layer === 'hook' || layer === 'permission' ? 'enforced' : 'present';
}

/** Сводка по строкам отчёта. Ровно одна реализация — и у сервера, и у экрана. */
export function summarizeProbe(rows: readonly ProbeRow[]): ProbeSummary {
  let match = 0;
  let mismatch = 0;
  let notChecked = 0;
  for (const row of rows) {
    if (row.verdict === 'match') match += 1;
    else if (row.verdict === 'mismatch') mismatch += 1;
    else notChecked += 1;
  }
  return { match, mismatch, notChecked };
}

/**
 * Ответ маршрута пробы. Конверт живёт в контрактах, а не двумя объявлениями по
 * сторонам: у П1.2 переименованное на сервере поле собиралось на обеих сторонах
 * и показывало человеку `undefined`.
 */
export interface ProbeAnswer {
  readonly report: ProbeReport;
}

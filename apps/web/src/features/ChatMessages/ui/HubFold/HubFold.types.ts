import type { ReactNode } from 'react';

export interface HubFoldProps {
  /** Заголовок раздела с числом строк — виден и в свёрнутом виде. */
  title: string;
  /** Подсказка по наведению на заголовок. */
  hint?: string;
  /** Открыт ли раздел при первом показе; по умолчанию свёрнут. */
  defaultExpanded?: boolean;
  /** Тон заголовка: `warning` — раздел держит работу (пробелы доставки). */
  tone?: 'warning';
  /**
   * Кнопки раздела справа от заголовка — видны и в свёрнутом виде: действие над
   * всем списком («Разобрать…») не должно прятаться за раскрытием.
   */
  actions?: ReactNode;
  children: ReactNode;
}

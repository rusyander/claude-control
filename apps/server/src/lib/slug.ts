/**
 * Слаг из человеческого имени: заголовка правила, имени скилла.
 *
 * Кириллица транслитерируется, а не отбрасывается. Отбрасывание давало пустую
 * строку на любом русском имени, а слаг тут становится идентификатором и даже
 * именем папки: пустой id молча уводил запись не туда (см. `saveSkill`).
 *
 * Живёт в lib/, потому что нужен двум доменам сразу (правила и скиллы), и
 * алгоритм обязан быть у них ОДИН: id правил уже записаны в state.json
 * пользователя, и любое расхождение осиротило бы их отметки. По той же причине
 * шаги ниже менять нельзя — только дополнять новыми символами в таблице.
 */
const TRANSLIT: Record<string, string> = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'g',
  д: 'd',
  е: 'e',
  ё: 'e',
  ж: 'zh',
  з: 'z',
  и: 'i',
  й: 'y',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'h',
  ц: 'c',
  ч: 'ch',
  ш: 'sh',
  щ: 'sch',
  ъ: '',
  ы: 'y',
  ь: '',
  э: 'e',
  ю: 'yu',
  я: 'ya',
};

/**
 * Длина по умолчанию. Слаг уходит в имя папки и в адрес страницы, поэтому
 * длинное имя обрезаем: полное имя хранится отдельно и показывается как есть.
 */
const MAX_LENGTH = 60;

export function slugify(text: string, maxLength: number = MAX_LENGTH): string {
  return text
    .toLowerCase()
    .split('')
    .map((char) => TRANSLIT[char] ?? char)
    .join('')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, maxLength);
}

/**
 * Факты ЗАПУСКА одного CLI — то, что нужно, чтобы его запустить и направить его модель:
 * имя и бинарь, каналы адреса модели, ключи вендора, лестница моделей, глубина, пределы
 * локальной модели, событие окна подписки.
 *
 * Один источник на двоих: каталог провайдеров панели (`apps/server/src/providers/catalog`)
 * берёт отсюда значения, а не объявляет свои, и переходники ядра (`apps/core/src/adapters/<cli>/`)
 * собирают из них `CliAdapter.caps` (спецификация 03, 11 R:PR-05). Пути к конфигам, разделы,
 * форматы, установка и детект — забота панели, сюда не входят.
 *
 * Правило спецификации 11: возможность, которую не доказывают ни код, ни документация,
 * здесь ОТСУТСТВУЕТ (или `unknown`), а не угадывается. Отсутствие — тоже факт.
 *
 * Идентификаторы CLI — непрозрачные строки, сверяемые с реестром в рантайме (P108):
 * перечисления имён в типах здесь нет намеренно.
 */

/** Насколько CLI проверен в панели; значения — словарь контрактов (`ProviderStatus`). */
export type RunStatus = 'verified' | 'experimental';

/** Имена исполняемого файла CLI: обычное и windows-обёртка (`.cmd`). */
export interface CliBinary {
  command: string;
  windowsCommand: string;
}

/**
 * Диалект провода, которым CLI идёт по адресу модели (спецификация 11 R:PR-03): по нему
 * маршрут решает, нужен ли перевод на шлюзе.
 */
export type Dialect = 'anthropic-messages' | 'openai-chat' | 'openai-responses' | 'google-genai';

/**
 * Вид API своего эндпоинта в словаре панели (`EndpointApiKind` контрактов): для чужого
 * адреса `openai` и `openai-compat` — одно и то же. Выводится из диалекта (`channels.ts`).
 */
export type EndpointApiKind = 'anthropic' | 'google' | 'openai-compat';

/**
 * Тип модельного API вендора для прямого вызова ключом (маршрут `api-key`); `none` — своего
 * API у CLI нет, прямой вызов невозможен.
 */
export type VendorApiKind = 'anthropic' | 'openai' | 'google' | 'openai-compat' | 'none';

/** Модельное API вендора: вид, стандартные переменные ключа, задокументированный адрес. */
export interface VendorApi {
  kind: VendorApiKind;
  /** Переменные окружения, из которых CLI сам берёт ключ. Только задокументированные имена. */
  keyVars: string[];
  /**
   * Адрес собственного API вендора — только из документации вендора. Вид `openai`/`openai-compat`
   * — вместе с версией (`<baseUrl>/chat/completions`); `anthropic` и `google` — корень хоста
   * (путь диалекта `/v1/messages`, `/v1beta/...` дописывает вызывающий). Нет — прямой вызов
   * обязан отказать, а не угадывать адрес; маршрута `api-key:<cli>` в ядре тоже нет.
   */
  baseUrl?: string;
}

/**
 * Как CLI входит в модель сам, без панели (маршрут `cli-login`, спецификация 11 R:PR-01):
 * - `account` — вход в учётную запись вендора (подписка, OAuth);
 * - `cli-config` — провайдер и ключ настраиваются внутри самого CLI (его конфиг, связка ключей);
 * - `unknown` — ни код, ни документация не говорят.
 */
export type LoginKind = 'account' | 'cli-config' | 'unknown';

/**
 * Настройка конфига человека, при которой канал НЕ сработает (CLI прочтёт не наш адрес).
 * Здесь — только имя настройки (и значение, которого она требует); прочитать конфиг и решить —
 * дело того, кто знает путь к файлу (панель), это не факт запуска.
 */
export interface ChannelBypass {
  /** Имя настройки, как его назовёт отказ. */
  setting: string;
  /** Значение, при котором канал работает; не задано — мешает само наличие настройки. */
  requires?: string;
}

/**
 * Канал адреса тройкой ЗАДОКУМЕНТИРОВАННЫХ переменных окружения: адрес, модель, ключ. Та же
 * тройка годится и для окружения одного прогона, и для собственного файла переменных CLI.
 */
export interface EnvVarsChannel {
  via: 'env';
  form: 'vars';
  dialect: Dialect;
  /** Переменная базового адреса — обязательна, иначе канал бессмыслен. */
  baseUrlVar: string;
  /** Переменная модели. Нет — модель этим каналом не переносится. */
  modelVar?: string;
  /** Приставка, без которой CLI имя модели не примет (Aider: litellm требует `openai/`). */
  modelPrefix?: string;
  /** Переменная, в которой CLI ждёт ключ к этому адресу (только имя). */
  keyVar?: string;
  bypass?: ChannelBypass;
}

/** Адрес шлюза, модель и заглушка ключа — то, из чего собирается окружение прогона. */
export interface RunEndpointInput {
  /** Адрес шлюза под этот прогон, с `/v1` на конце. */
  baseUrl: string;
  /** Модель маршрута; пусто — маршрут модель не назвал. */
  model: string;
  /** Заглушка: настоящий ключ подставляет шлюз. */
  key: string;
}

/**
 * Канал адреса окружением ОДНОГО прогона, у CLI без своего файла переменных и без тройки
 * «адрес · модель · ключ» (Kimi Code, Goose, OpenCode): окружение собирается целиком.
 */
export interface EnvRunChannel {
  via: 'env';
  form: 'run';
  dialect: Dialect;
  /** Переменная ключа внутри собранного окружения, если ключ едет отдельной переменной. */
  keyVar?: string;
  /** Окружение прогона — чистая функция входа, без чтения диска. */
  build: (input: RunEndpointInput) => Record<string, string>;
  bypass?: ChannelBypass;
}

/**
 * Канал адреса куском СОБСТВЕННОГО конфига CLI — там, где документация называет это место
 * сама (Codex: таблица `model_providers`, Continue: `apiBase` модели).
 *
 * Сегодня панель правит регион в файле человека. На один сеанс, файлом рядом с его конфигом,
 * такой канал не доказан (спецификация 11 R:PR-05) — поэтому `perSession: false`.
 */
export interface FileChannel {
  via: 'file';
  dialect: Dialect;
  /** Формат файла, по нему выбирается писатель. */
  format: 'codex-toml' | 'continue-yaml';
  /** Задокументированное место адреса внутри файла. */
  place: string;
  perSession: false;
}

export type Channel = EnvVarsChannel | EnvRunChannel | FileChannel;

/** Глубина продумывания одним флагом: шаблон argv (`{effort}` — место значения) и допустимые значения. */
export interface EffortFact {
  argv: string[];
  /** От низкого к высокому: порядок и есть лестница усилия ядра (`tierLadderOf`). */
  values: string[];
}

/**
 * Ступень лестницы модели ядра (03 §Economy): `model` — имя, которое CLI принимает в выборе модели
 * (понижение ставит именно его), `ids` — приставки полных имён той же ступени (`claude-opus-5` —
 * та же ступень, что и алиас).
 */
export interface ModelRung {
  model: string;
  ids: string[];
}

/**
 * Канал, которым CLI узнаёт пределы локальной модели (окно, сроки — спецификация 11 R:PR-04):
 * - `env` — переменные окружения прогона (Claude Code);
 * - `settings-file` — ключи файла настроек, подложенного переменной окружения (Qwen Code).
 */
export type LimitsChannel =
  | { via: 'env'; vars: string[] }
  | {
      via: 'settings-file';
      /** Переменная окружения, которой CLI принимает путь файла настроек на прогон. */
      fileVar: string;
      /** Путь объекта с ключами внутри файла. */
      path: string[];
      keys: { window: string; timeout: string; idle: string };
    };

/** Событие потока CLI, в котором приходит состояние окна подписки (спецификация 11 R:PR-06). */
export interface WindowEvent {
  type: string;
}

export interface CliRunFacts {
  /** Непрозрачный id CLI — ключ реестра и настройка `provider` панели. */
  id: string;
  /** Человекочитаемое имя. */
  name: string;
  status: RunStatus;
  binary: CliBinary;
  login: LoginKind;
  vendorApi: VendorApi;
  /** Запускает ли панель через этот CLI ответ без ключа (у Cursor — нет). */
  cliRunnable: boolean;
  /** Каналы адреса модели в порядке предпочтения; пусто — только свой вход CLI. */
  channels: Channel[];
  effort?: EffortFact;
  /** Вендоры каталога моделей (models.dev), чьи модели относятся к этому CLI. */
  modelVendors?: string[];
  /** Семейства каталога от слабого к сильному — лестница подбора модели (Т12). */
  modelLadder?: string[];
  /**
   * Ступени модели от слабой к сильной — лестница уровня шага ядра (понижение механики, ревьюер
   * не слабее автора, потолок подагента). Не `modelLadder`: там семейства каталога для подбора
   * панели, здесь имена, которые CLI принимает сам. Нет — ранга модели у CLI не знаем.
   */
  modelRungs?: ModelRung[];
  /**
   * Потолок автоматики (этап 11, D7, P138): самая сильная ступень `modelRungs[].model`, до которой
   * ядро поднимает шаг само — эскалацией после неудачи и подъёмом по обучению. Выше — только явный
   * выбор человека (Fable у Claude). Нет — модель сама не поднимается, только усилие.
   */
  autoCeiling?: string;
  limitsChannel?: LimitsChannel;
  /** Нет — событие окна у CLI не задокументировано (`unknown`, отказ читается в потоке). */
  windowEvent?: WindowEvent;
}

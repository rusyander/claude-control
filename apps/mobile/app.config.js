/**
 * Конфигурация Expo поверх `app.json`.
 *
 * Единственное, что здесь добавляется, — адрес панели по умолчанию. Он нужен,
 * когда APK отдают другому человеку: тот ставит файл и видит адрес уже
 * заполненным, ему остаётся вписать токен.
 *
 * Адрес берётся из окружения СБОРКИ, а не из репозитория: тайлнет-имя машины —
 * личная вещь, а репозиторий публичный. Поэтому
 * `MOBILE_DEFAULT_URL=https://машина.ts.net:10000 pnpm mobile:apk`, а без
 * переменной поле остаётся пустым, как раньше.
 *
 * Токен сюда не кладётся никогда: APK распаковывается в одну команду, а за
 * токеном стоит доступ к учётным данным и запуск команд на машине.
 */
const base = require('./app.json');

module.exports = () => ({
  ...base.expo,
  extra: {
    ...base.expo.extra,
    defaultPanelUrl: process.env.MOBILE_DEFAULT_URL ?? '',
  },
});

/**
 * Имя вопроса в памяти отвеченных (`agent-runs`).
 *
 * У вопроса из транскрипта своего идентификатора нет — блоки сообщения его не
 * несут, — поэтому именем служит сообщение плюс номер блока. У живого вызова
 * есть `toolUseId`, и он точнее всего. Когда нет ни того, ни другого, остаётся
 * само тело вызова: два разных вопроса одного разговора обязаны получить разные
 * имена, иначе ответ на первый погасил бы второй, и человек не смог бы ответить
 * на вопрос, которого агент ещё ждёт.
 */
export function questionKey(scope: string, id?: string, input?: string): string {
  return `${scope}#${id || hash(input ?? '')}`;
}

/** Короткий и устойчивый отпечаток строки (djb2) — только чтобы различать. */
function hash(value: string): string {
  let acc = 5381;
  for (let i = 0; i < value.length; i += 1) acc = ((acc << 5) + acc + value.charCodeAt(i)) | 0;
  return (acc >>> 0).toString(36);
}

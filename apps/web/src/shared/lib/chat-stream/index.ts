/**
 * Состояние потокового ответа Claude.
 *
 * Тип живёт в shared, а не в entity Chat, намеренно: им пользуются и лента чата
 * (features/ChatMessages через стор agent-runs), и витрина (@shared/lib/mocks).
 * Держать определение в entity значило бы тянуть shared → entities, что ломает
 * границы слоёв. Поэтому определение здесь, а entity его переэкспортирует.
 */

import type { MessageUsage } from '@claude-control/contracts';

export interface StreamedTool {
  name: string;
  input: string;
  /** Идентификатор вызова — по нему к нему приходит расход шага. */
  id?: string;
  /**
   * Расход шага, породившего этот вызов. Общий на все вызовы одного шага:
   * раздельного счёта модель не даёт (см. ChatEvent.usage на сервере).
   */
  usage?: MessageUsage;
}

export interface StreamState {
  /** Текст ответа, который набирается на глазах. */
  text: string;
  /**
   * Расход шагов, закончившихся одним текстом, — цена самого ответа. Сложен по
   * шагам: в ленте они склеены в один блок, и разделить его обратно нечем.
   */
  textUsage?: MessageUsage;
  thinking: string;
  tools: StreamedTool[];
  isRunning: boolean;
  /**
   * Связь с потоком потеряна, идёт переподключение. Прогон при этом жив — он на
   * сервере, — но набранное в пузыре оборвано на полуслове и уже неполно.
   */
  stalled?: boolean;
  /**
   * Переподключения исчерпаны: поток не восстановился. Лента говорит об этом
   * вслух и даёт перечитать переписку — ответ агента, если он всё-таки
   * дописался, лежит в транскрипте.
   */
  dropped?: boolean;
  /**
   * Потока к прогону у этой вкладки нет: потоков не больше `MAX_STREAMS`, место
   * досталось более важным. Прогон жив на сервере, правда — в транскрипте.
   */
  parked?: boolean;
  error?: string;
  sessionId?: string;
  costUsd?: number;
  /** Момент сброса окна лимитов, unix-секунды. */
  limitResetsAt?: number;
}

/**
 * Рисует ли поток текущий ход прямо сейчас.
 *
 * Одно условие на двоих: по нему лента показывает потоковый пузырь, и по нему
 * же тот же ход прячется из истории (`pages/Chat/lib/liveTurn.ts`). Разойдись
 * они — и ход либо покажется дважды, либо исчезнет совсем.
 *
 * Потерянная связь гасит пузырь целиком, а не дорисовывает его: набранное в нём
 * оборвано на полуслове, а полный ответ агент тем временем пишет в транскрипт.
 * Уступая место истории, пузырь тем же движением её и раскрывает — ход, который
 * он прятал, снова виден, и вместо замершего текста человек получает настоящий.
 * Припаркованный прогон — тот же случай: потока нет, историю ведёт транскрипт.
 */
export function isStreamShown(
  stream: Pick<StreamState, 'isRunning' | 'text' | 'stalled' | 'parked'>,
): boolean {
  if (stream.stalled || stream.parked) return false;
  return stream.isRunning || Boolean(stream.text);
}

export interface Option {
  label?: string;
  description?: string;
}

export interface Question {
  question?: string;
  header?: string;
  multiSelect?: boolean;
  options?: Option[];
}

export interface QuestionCardProps {
  questions: Question[];
  /** Ответить (отправка в тот же разговор). Нет — вопрос только для чтения. */
  onPick?: (answer: string) => void;
  /**
   * Агент этого разговора сейчас работает. Отвечать это НЕ мешает: вызов
   * `AskUserQuestion` в пакетном режиме возвращается ошибкой сразу и никого не
   * ждёт, так что вопрос задан посреди хода. Признак нужен только карточке —
   * сказать правду о судьбе ответа: он встанет в очередь и уйдёт по концу хода,
   * а не «агент думает над ним прямо сейчас».
   */
  busy?: boolean;
  /**
   * Чей это вопрос, если не этого разговора. Родительский чат — пульт над
   * своими детьми, и вопросов от шести агентов в нём бывает шесть: подпись у
   * отправленного ответа говорит, КУДА он ушёл, иначе после клика человек видит
   * «ответ отправлен» и не знает, кому именно ответил.
   */
  target?: string;
  /**
   * На этот вопрос уже ответили — помнит стор, не карточка.
   *
   * Своё «отправлено» умирает вместе с перемонтажом: ушёл на другую вкладку и
   * вернулся — карточка снова выглядит неотвеченной, а источник вопроса всё
   * ещё его отдаёт. Второй ответ на тот же вопрос — это второй ход агента.
   */
  isAnswered?: boolean;
}

/** Что уже выбрано: индекс вопроса → выбранные подписи вариантов. */
export type PickedAnswers = Record<number, string[] | undefined>;

/** Состояние одного вопроса в карточке — оно же решает, как он выглядит. */
export type QuestionState = 'done' | 'current' | 'locked';

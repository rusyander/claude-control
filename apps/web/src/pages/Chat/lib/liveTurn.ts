import type { ChatMessage } from '@claude-control/contracts';

/**
 * История без хода, который прямо сейчас рисует поток.
 *
 * Пока прогон идёт, его ход живёт в памяти вкладки и виден сразу. Но CLI пишет
 * транскрипт по строке на каждый шаг, и любая перечитка ленты посреди прогона —
 * по опросу, по фокусу окна, после F5 — приносит те же вызовы ещё раз, уже из
 * истории: один Bash под другим, с двумя бейджами расхода. Поэтому, пока
 * потоковый пузырь на экране, из истории убираем ответы модели, записанные
 * после старта прогона. Реплики человека остаются: свою видно сразу и без
 * потока.
 *
 * Время старта — серверное, из события session: те же часы, что и у
 * транскрипта, а часам телефона доверять нельзя. Старта нет — прогон ещё не
 * дошёл до модели, и его хода в транскрипте быть не может. Допуска нет
 * НАРОЧНО: реестр ставит старт до запуска CLI, так что записи этого прогона
 * всегда строго позже; а запас назад прятал бы ответ предыдущего хода, когда
 * следующий уходит из очереди через доли секунды после него.
 */
export function withoutLiveTurn(
  history: ChatMessage[],
  startedAt: number | undefined,
  streamShown: boolean,
): ChatMessage[] {
  if (!streamShown || startedAt === undefined) return history;
  const kept = history.filter(
    (message) => message.role !== 'assistant' || Date.parse(message.timestamp) < startedAt,
  );
  // Тот же массив, когда убирать нечего: лента прокручивается к низу на смену
  // списка, и новый массив на каждый рендер дёргал бы её впустую.
  return kept.length === history.length ? history : kept;
}

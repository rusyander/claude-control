/**
 * Куда сейчас добавляется файл в дереве ресурса.
 *
 * Значений три, и два из них легко перепутать: путь папки — поле открыто в ней,
 * пустая строка — поле открыто в КОРНЕ ресурса, `undefined` — поля нет вовсе.
 * На этом и погорела отмена внутри папки: она отдавала пустую строку, то есть
 * не закрывала поле, а переносила его в корень, и Escape вместо отказа
 * открывал ввод имени наверху дерева (Enter там создал бы файл в корне).
 * Поэтому «закрыть» — не литерал по месту вызова, а одно правило здесь.
 */
export type CreateTarget = string | undefined;

/** Поле ввода в корне ресурса, а не в папке. */
export const CREATE_IN_ROOT = '';

/** Открыто ли поле именно в этой папке ('' — корень). */
export function isCreatingIn(state: CreateTarget, folder: string): boolean {
  return state === folder;
}

/** Отмена: поля больше нет. Никогда не корень — отказ ничего не открывает. */
export function cancelCreate(): CreateTarget {
  return undefined;
}

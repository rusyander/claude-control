import type { MediaDeck } from '@agentdeck/contracts';

/**
 * Правка готовой презентации: «поправь третий слайд» вместо новой колоды.
 *
 * Владелец 13.09.2026: «если пользователь попросит что-нибудь изменить, то будет
 * такая возможность, и агент не потеряется». Не потеряться ему помогает не память,
 * а панель: структура прежней колоды лежит у неё на диске и уезжает модели вместе
 * с просьбой (`deckReviseRequest`). Отсюда и этот тип — он связывает карточку
 * готовой колоды с композером, который отправит следующую просьбу.
 *
 * Тип живёт в сущности, а не в ленте: правку начинают ДВА разных места (правый
 * столбец у Claude и карточка в ленте у любого CLI), а состояние держит один хук
 * на оба чата.
 */
export interface MediaRevision {
  /**
   * Колода, которую заменит следующая сборка. Пусто — обычная сборка по теме.
   * Идентификатор, а не структура: структуру страница не получает вовсе — это
   * килобайты, которые экрану не нужны.
   */
  reviseOf?: string;
  /** Начать правку: композер перейдёт в режим презентации и скажет, что правит. */
  onStart: (deck: MediaDeck) => void;
  /** Правка собрана — состояние правки больше не нужно. */
  onDone?: () => void;
}

/**
 * Наблюдение за MR доставленной группы (WP1j; журнал 104, 114): ветки
 * ревьюеров, пришедшие после «готово», и исход конвейера. В хранилище, а не в
 * памяти: проверки идут часами, и перезапуск панели их не обрывает.
 */
export interface SplitMrWatch {
  /** `doneAt` группы, к которому относится расписание: новое «готово» — новый круг. */
  cycle: string;
  /** Сколько проверок круга сделано — номер следующей паузы в расписании. */
  checks: number;
  /** Что уже передано группе: `<ветка>:<последняя реплика>` — через все круги. */
  relayed?: string[];
  /** Исход конвейера, на который панель уже посмотрела: один взгляд на конвейер. */
  pipeline?: { id: string; status: string };
  /** Сколько раз наблюдатель продолжил группу — потолок против петли. */
  resumes?: number;
  /** Круг кончен: MR влит или закрыт, расписание исчерпано, потолок продолжений. */
  stopped?: 'merged' | 'closed' | 'exhausted' | 'limit';
}

/**
 * Память конвейера уровней одного разделения (Т1): что человек попросил, что
 * ответил разбор и в каком состоянии каждая группа. Живёт в хранилище, а не в
 * памяти, по той же причине, что и пауза дерева: разбор идёт минуты, группы с
 * `after` ждут часы, а стенд за это время перезапускается.
 */
export interface SplitPlanRecord {
  /** Разговор, в котором человек согласился на разделение, — ключ записи. */
  parentChatId: string;
  /**
   * Проект, как его назвал запрос разделения: по этому пути читаются настройки
   * (сколько групп разом, доставка, строки «Группы», правило подбора) — тем же
   * ключом, которым их пишет панель.
   */
  projectPath: string;
  /**
   * Верх репозитория, от которого заводятся копии, если он не совпадает с
   * `projectPath` (проект — подкаталог монорепозитория, m6). Нет — копии от
   * `projectPath`, как у записей до этого поля.
   */
  copyRoot?: string;
  createdAt: string;
  /** Чат разбора (уровень 1); нет — разбор не запускался (подбор выключен). */
  triageChatId?: string;
  /** Итог разбора: получен ли блок, что панель починила, конфликты и порядок. */
  triage?: {
    at: string;
    received: boolean;
    /** Разбор оборван перезапуском панели — группы стоят на вопросе, а не идут. */
    interrupted?: boolean;
    repairs: string[];
    conflicts: { paths: string[]; resolvedBy: number; why: string }[];
  };
  /** Порядок старта и слияния — индексы групп. */
  order: number[];
  /** Запрос разделения, которым заводятся группы после разбора. */
  request: {
    allowEdits?: boolean;
    model?: string;
    effort?: string;
    assignments?: Record<string, { model?: string; effort?: string }>;
  };
  /** Предложение агента после применения разбора (задачи, границы, заметки). */
  proposal: {
    shared?: string;
    groups: {
      title: string;
      branch: string;
      tasks: string[];
      brief?: string;
      kind?: string;
      model?: string;
      effort?: string;
      owns?: string[];
      notes?: string;
      /** Группа ревьюит MR по ссылке (Т7) — копия встанет на его ветку. */
      review?: { url: string; branch?: string };
    }[];
  };
  groups: SplitPlanGroupRecord[];
  /**
   * Группы прошлых разделений этого разговора, которым ещё есть что сказать
   * (F5.2): неубранная копия или приёмка человека. Запись ключуется родителем,
   * и новое разделение затирало их целиком — копии оставались сиротами без
   * кнопки уборки, а принятый чат терял метку «принято». Номера здесь — номера
   * СТАРОГО плана; группы ищутся по чату, не по номеру.
   */
  retiredGroups?: SplitPlanGroupRecord[];
  /**
   * Лимит подписки исчерпан до этого момента (ISO, журнал 81, 89): очередь новых
   * групп не заводит — они сожгли бы старт впустую, — а после сброса идёт дальше.
   */
  limitUntil?: string;
  /**
   * Срок `limitUntil` поставило предупреждение «лимит на исходе»
   * (`allowed_warning`, аудит 25.09, L63), а не отказ: идущие группы работают,
   * новые не стартуют до сброса.
   */
  limitWarning?: boolean;
  /**
   * План отменён человеком (ISO): незакрытые группы закрыты сбоем «план
   * отменён», их прогоны остановлены. Отметка держит конвейер от оживления
   * плана — итогом разбора, продолжением чата, наблюдателем MR.
   */
  cancelledAt?: string;
  /**
   * Пересечения веток после работы (Т6) и то, о чём человеку уже сказали.
   * `noticed` — отпечатки фактов («файл — эти группы»), по которым заметка в
   * ленту родителя уже уходила: без них пересчёт после каждой цепочки повторял
   * бы одно и то же сообщение.
   */
  overlap?: SplitOverlapView & { noticed: string[] };
}

/**
 * Память панели об одной ЦЕЛИ запуска: см. `AppState.runnerPrefs`.
 *
 * Ключ карты — нормализованный абсолютный каталог запуска. У проекта без
 * монорепы это сам корень, поэтому записи, сделанные до появления подпапок,
 * читаются как есть: `projectPath`/`dir` у них пусты и означают «корень».
 */
/** Итог одной проверки связи с MCP-сервером — то, что показывает карточка и считает обзор. */
export interface McpHealthRecord {
  health: McpHealth;
  /** Причина отказа, если health = failed. */
  detail?: string;
  /** Сколько инструментов отдал сервер при успешной проверке. */
  toolCount?: number;
  /** Когда проверка проводилась (ISO). */
  checkedAt: string;
}

/**
 * Итог последней живой проверки связи с внешней системой — зеркало
 * `McpHealthRecord`, и не случайно: вопрос тот же («отвечает ли и кем мы там
 * представились»), а ответ обязан переживать F5 и перезапуск сервера. Токена
 * здесь нет — ни целиком, ни куском: в записи только то, что можно показать.
 */
export interface IntegrationHealthRecord {
  state: IntegrationState;
  /** Человеческая причина отказа или короткое «кем вошли». */
  detail: string;
  checkedAt: string;
  /** Имя учётной записи, которым панель представилась. */
  account?: string;
  /** Что ответил Atlassian про себя: облако или своя установка. */
  deployment?: AtlassianDeployment;
}

export interface RunnerPrefs {
  /** Абсолютный каталог запуска (ключ карты — его нормализованный вид). */
  path: string;
  /** Корень проекта. Пусто у старых записей — тогда это сам `path`. */
  projectPath?: string;
  /** Подпапка относительно корня; пусто — сам корень. */
  dir?: string;
  /** Поднимать dev-сервер при старте сервера панели. */
  autostart?: boolean;
  /** Порт прошлого удачного запуска — подсказка в интерфейсе. */
  port?: number;
  /** Порт, закреплённый пользователем: уходит в `PORT` и ожидается именно он. */
  pinnedPort?: number;
  /** Оверрайд команды запуска. */
  command?: string;
}

/** Чем цель отличается от голого пути: корень проекта и подпапка внутри него. */
export interface RunnerTargetMeta {
  projectPath?: string;
  dir?: string;
}

/**
 * Данные, которых нет в конфигах Claude Code: группы, сценарии, отметки
 * «выключено» и настройки самого приложения. Живут отдельным файлом внутри
 * agentdeck/, чтобы не засорять конфиги тем, чего Claude Code не понимает.
 *
 * Выключение сущности хранится здесь, а не удалением из конфига: так текст
 * правила или команда хука не теряются и их можно вернуть одним переключателем.
 */
export interface AppState {
  groups: Group[];
  automations: Automation[];
  disabled: Record<EntityKind, string[]>;
  /**
   * Кто погашен группой: вид → id сущности → список групп, которые её гасят.
   *
   * Отдельно от `disabled` намеренно. Иначе включение группы «воскрешало» бы
   * то, что человек выключил вручную по отдельности, а сущность из двух групп
   * включалась бы первой же из них. Здесь сущность оживает, только когда её
   * отпустили все группы и она не выключена вручную.
   */
  disabledByGroup: Record<EntityKind, Record<string, string[]>>;
  /**
   * Команды выключенных хуков.
   *
   * Хук выключается удалением из settings.json — иначе Claude Code продолжал
   * бы его исполнять. Но тогда его текст в файле не остаётся, и вернуть его
   * было бы нечем: выключение оказалось бы удалением. Поэтому снимок хука
   * хранится здесь, пока он выключен, и подмешивается обратно в список.
   */
  disabledHooks: Record<string, Hook>;
  /**
   * Какие переменные окружения применила каждая группа: id группы → имена
   * ключей, записанных ею в settings.json. По этой отметке при выключении
   * снимаются только свои ключи (не задев ручные и чужие), а при пересечении
   * групп ключ остаётся, пока его держит хотя бы одна.
   */
  envByGroup: Record<string, string[]>;
  /**
   * Реестр проектов уровня конфигурации: запомненные пути к каталогам проектов,
   * чьи `CLAUDE.md`, `.claude/settings.json` и `.mcp.json` панель показывает и
   * правит. Хранится здесь, а не в конфигах Claude Code: это данные самой панели,
   * а сами файлы проекта остаются в его каталоге и не дублируются.
   */
  projects: Project[];
  /**
   * Оверрайд команды запуска dev-сервера на проект: нормализованный путь →
   * командная строка. Пусто/нет ключа — команда определяется автоматически по
   * package.json проекта (скрипт dev/start и пакетный менеджер по lock-файлу).
   */
  runnerCommands: Record<string, string>;
  /**
   * Что панель помнит о dev-сервере проекта между запусками: нормализованный
   * путь → {исходный путь, автозапуск, порт прошлого запуска}.
   *
   * Исходный путь хранится вместе с ключом намеренно: ключ нормализован (на
   * Windows ещё и в нижнем регистре), а запускать процесс надо в каталоге,
   * который написал пользователь. Порт помнится и без автозапуска — тогда
   * адрес проекта не скачет от запуска к запуску.
   */
  runnerPrefs: Record<string, RunnerPrefs>;
  settings: AppSettings;
  /**
   * Итоги проверки провайдеров: id провайдера → последний результат.
   *
   * Хранится здесь, а не в настройках: это не выбор пользователя, а факт о его
   * машине («здесь круг чтения-записи сошёлся, ассистент ответил»). Из него
   * берётся бейдж «проверен» вместо вечного «экспериментальный».
   */
  providerChecks: Record<string, ProviderCheckResult>;
  /**
   * Итог последней проверки связи MCP-сервера: имя сервера → статус, причина,
   * число инструментов и время проверки. Раньше жил только в состоянии карточки
   * в браузере: обновление страницы возвращало «не проверялся», а обзор считал
   * отвечающие серверы по списку, где health всегда было `unknown`.
   */
  mcpHealth: Record<string, McpHealthRecord>;
  /**
   * Что открыто в окне кода у таба проекта: нормализованный путь → снимок
   * (дерево, файл, режимы показа).
   *
   * На сервере, а не в браузере, по просьбе владельца: localStorage уходит
   * вместе с чисткой кэша, а вкладка кода — рабочее место, которое обидно
   * терять. Запись живёт, пока открыт таб; закрытие таба её стирает.
   */
  projectCodeViews: Record<string, ProjectCodeView>;
  /**
   * Раскладка окна кода — одна на панель. Ширина списка файлов не свойство
   * проекта, а привычка человека: настроил один раз — ждёт её везде.
   */
  projectCodeLayout?: ProjectCodeLayout;
  /**
   * Где ВЫКЛЮЧЕН подбор модели под задачу: нормализованный путь проекта → false.
   *
   * Только отклонение от умолчания: правило включено везде, где его не трогали.
   * Выключенное значит «дети разделения едут на модели, которую выбрал человек»
   * — то самое поведение, что было до партии подбора.
   */
  projectCascade: Record<string, boolean>;
  /**
   * Откуда взялся чат: ключ разговора → его родитель. Заполняется разделением
   * задач и больше ничем.
   *
   * Вывести это из транскриптов нельзя — у Claude Code нет понятия «разговор
   * порождён разговором», а для человека это главное, что о таком чате нужно
   * знать: в списке он видит дерево, а не пять безымянных чатов подряд.
   */
  chatLinks?: Record<string, ChatLink>;
  /**
   * Деревья разговоров, поставленные на паузу целиком: корень → запись. В
   * записи — чем перезапустить каждый остановленный прогон (его параметры и
   * сессия) и очередь автостартов, отложенных до продолжения. Переживает
   * перезапуск панели намеренно: пауза нажимается на ночь, а стенд за ночь
   * может перезагрузиться — и продолжить утром должно быть чем.
   */
  treePause?: Record<string, TreePauseRecord>;
  /**
   * Конвейер уровней разделения (Т1): родительский разговор → запись. Разбор и
   * ожидание предшественников длятся дольше одного процесса сервера.
   */
  splitPlans?: Record<string, SplitPlanRecord>;
  /**
   * Телефоны, которым уходят уведомления о прогонах. Не настройка, а реестр
   * устройств: токен выдаёт сервис Expo конкретной УСТАНОВКЕ приложения, при
   * переустановке он меняется, а прежний перестаёт принимать молча — поэтому
   * список чистится по ответу сервиса, а не руками.
   */
  pushDevices?: PushDevice[];
  /**
   * Verifier парольной фразы шифрования копий секретов. Не сама фраза, а её
   * производная (scrypt-хэш с солью): по нему проверяется, та ли фраза введена,
   * восстановить фразу по нему нельзя. Пусто — шифрование ещё не настраивали.
   * Хранится тут, а не в settings: это не пользовательская настройка, а
   * технический артефакт, и в схему настроек (contracts) ему попадать незачем.
   */
  secretBackupVerifier?: string;
  /**
   * Итог последней проверки связи с внешними системами: id интеграции →
   * запись. Ровно то же место и та же причина, что у `mcpHealth`: без него
   * страница настроек после перезагрузки показывала бы «не проверялось» по
   * работающей связи, а карточка — пустой статус.
   */
  integrationHealth?: Record<string, IntegrationHealthRecord>;
  /**
   * Итог последней пробы контура: id контура → что панель у него нашла. То же
   * место и та же причина, что у `mcpHealth`: матрица возможностей, живущая
   * только в состоянии страницы, умирает на F5, и раздел показывает «не
   * проверялся» по контуру, который отвечает. Ключа в записи нет — в ней только
   * то, что панель и так рисует на карточке.
   */
  platformHealth?: Record<string, PlatformHealthRecord>;
  /**
   * Что панель записала в чужие конфиги, применяя контур, и что было там до
   * неё (Т3). Здесь, а не в настройках: настройки уезжают экспортом на другую
   * машину, а откат по чужим следам — худшее, что можно предложить человеку.
   */
  platformApplied?: Record<string, PlatformAppliedRecord>;
  /**
   * ОТТИСК последнего отчёта верности переноса: «источник→цель:уровень» →
   * сводка, дата и версия канона (П1.2). Здесь, а не в настройках: отчёт
   * описывает CLI и файлы ЭТОЙ машины, и на другой означал бы чужую среду под
   * своим именем. Версия канона и дата лежат внутри записи — прочитанный завтра
   * оттиск обязан уметь сказать, что он посчитан по другому словарю.
   *
   * СТРОК ЗДЕСЬ НЕТ: они считаются заново на каждом запросе, а хранение их копий
   * растило бы файл состояния на 55 КБ с каждой парой CLI.
   */
  portabilityFidelity?: Record<string, FidelityMark>;
  /**
   * След последнего применённого переноса: «источник→цель:уровень» → файлы и
   * имена их резервных копий (П2.3). Без него «отменить перенос» невозможно:
   * какие копии сделал один перенос, каталог копий не помнит.
   */
  portabilityTransfers?: Record<string, TransferRecord>;
  /**
   * Подписки целей на канон панели: «цель:уровень» → подписанные слои плюс
   * память о спроецированном, запись за записью (П5.1). Память пофайловая не
   * годится: у цели записи сливаются в один файл, и хеш файла не умеет сказать,
   * КАКАЯ запись разошлась, — пересборка по нему переписывала бы файл целиком.
   */
  portabilitySubscriptions?: Record<string, EnvSubscription>;
  /**
   * Расход через контур по дням (Т8): id контура → запись. Здесь, а не в
   * счётчике шлюза: тот считает от запуска процесса, и перезапуск панели
   * показывал бы человеку с почти исчерпанным ключом честный ноль.
   */
  platformSpend?: Record<string, PlatformSpendRecord>;
  /**
   * Итог последнего пробного запроса через шлюз (Т2): id контура → ответ, модель,
   * задержка. Здесь, а не в настройках: задержка и ответ — свойство этого стенда,
   * а не настройки, которую человек переносит на другую машину.
   */
  platformSmoke?: Record<string, PlatformSmokeResult>;
  /**
   * Разовый рассказ о переносе старых настроек: включённых контуров могло быть
   * несколько, активным стал первый. Гасится маршрутом после прочтения —
   * повторно показанный, он читается как новое событие.
   */
  platformActivationNotice?: PlatformActivationNotice;
  /**
   * Порт, который шлюз контуров занял НА САМОМ ДЕЛЕ. Ноль или отсутствие —
   * шлюз не поднят.
   *
   * Отличается от `settings.platformGateway.port`, и в этом весь смысл записи:
   * задуманный порт совпадает с портом прокси защиты данных, занятый порт шлюз
   * берёт соседним, и сторож (`tools/keepalive.mjs`), следящий за задуманным,
   * либо принимает за шлюз чужой слушатель, либо перезапускает здоровый стенд
   * из-за молчания порта, который шлюзу никогда и не принадлежал.
   */
  platformGatewayPort?: number;
  /**
   * Модели, замеченные с голым `</think>` в тексте ответа (L9): id контура →
   * имена моделей. Факт, а не настройка: шлюз держит их ответы до тега, у
   * остальных — только ответ, начатый с `<think>`. Уходит с контуром.
   */
  platformThinkTail?: Record<string, string[]>;
  /**
   * Что человек привязал к проверяемому проекту: абсолютный путь проекта →
   * задачи Jira, страницы Confluence и репозиторий форджа (у самого проекта и
   * у каждой его группы тестов).
   *
   * Живёт в состоянии панели, а не в `.agent/tests/` проекта, намеренно: это
   * знание О ЧЕЛОВЕКЕ и его трекере, а не о наборе тестов, и в чужой репозиторий
   * такому знанию попадать незачем — оно уехало бы в git вместе с кейсами.
   */
  integrationLinks?: Record<string, IntegrationLinks>;
  /**
   * Шаблоны зеркала копий сверх встроенного списка: нормализованный путь
   * основной копии → что зеркалить ещё и что не зеркалить. Только отклонение
   * от умолчания — ключа нет, значит копия получает встроенный список.
   */
  worktreeMirror?: Record<string, WorktreeMirrorSettings>;
  /**
   * Разделение на проекте (доставка до MR, групп разом): нормализованный путь
   * основной копии → отклонение от `SPLIT_SETTINGS_DEFAULT`.
   */
  splitSettings?: Record<string, StoredSplitSettings>;
  /**
   * Общие правила групп разделения (вкладка «Группы»): разрешения, потолки
   * лёгкого и тяжёлого проекта, правило тяжести. Только отклонение от коробки.
   */
  splitDefaults?: StoredSplitDefaults;
  /**
   * Где РАЗРЕШЕНО принимать черновик генерации тестов без просмотра:
   * нормализованный путь проекта → true. Только отклонение от умолчания —
   * ключа нет, значит предложения генерации принимает человек. Подробности,
   * почему это память панели, а не файл проекта, — в `tests-drafts.ts`.
   */
  testsAutoAccept?: Record<string, boolean>;
}

/**
 * Сверка форматов чужих CLI с их официальными схемами (IDEA-3).
 *
 * Панель пишет конфигурации девяти чужих CLI по их документации, а документация
 * уезжает вместе с релизами. Сверка отвечает на один вопрос: те ключи, которые
 * панель РЕАЛЬНО правит, всё ещё есть в официально опубликованной схеме этого
 * CLI? Расхождение ничего не блокирует — это предупреждение «посмотрите глазами,
 * формат разъехался».
 *
 * Проверка возможна только там, где схема ОПУБЛИКОВАНА по задокументированному
 * адресу. У кого её нет — так и сказано (`no-schema`), а не «всё хорошо»:
 * выдуманный адрес схемы был бы хуже отсутствующего.
 */

/** Итог по одному ключу, который панель правит. */
export interface FormatCheckKey {
  /** Путь ключа в конфигурации, через точку: `experimental.hook`. */
  path: string;
  /** Раздел панели, который этот ключ ведёт. */
  section: string;
  /** Ключ найден в опубликованной схеме. */
  present: boolean;
}

/**
 * - `ok` — все ведомые ключи нашлись в схеме;
 * - `drift` — какого-то ключа в схеме нет: документация и схема разошлись;
 * - `no-schema` — официальной схемы у CLI не опубликовано, сверять не с чем;
 * - `unavailable` — схема есть, но получить или разобрать её не удалось.
 */
export type FormatCheckState = 'ok' | 'drift' | 'no-schema' | 'unavailable';

export interface FormatCheckProvider {
  providerId: string;
  state: FormatCheckState;
  /** Адрес официальной схемы, если он задокументирован. */
  schemaUrl?: string;
  /** Ключи и их наличие в схеме (пусто при `no-schema` и `unavailable`). */
  keys: FormatCheckKey[];
  /** Почему сверки нет или она не вышла. */
  note?: string;
}

export interface FormatCheckReport {
  /** Когда сверка выполнялась (ISO). */
  checkedAt: string;
  providers: FormatCheckProvider[];
}

export interface FormatCheckResponse {
  /** Отчёт из кэша. Пусто — сверка ещё ни разу не выполнялась. */
  report?: FormatCheckReport;
  /** Результат устарел (или его нет) и будет обновлён. */
  stale: boolean;
}

import type { MediaDeck, MediaImage } from '@agentdeck/contracts';
import type { Deck } from '@agentdeck/contracts/media-deck';

/**
 * Что карточка показывает. Ровно одно из трёх: языки блоков разные, и один блок —
 * это либо колода, либо рисунок, а готовая запись приходит вместо блока, а не
 * вместе с ним.
 */
export interface MediaFeedCardProps {
  /** Колода, разобранная из блока `agentdeck:deck`. */
  deck?: Deck;
  /** Рисунок из блока `agentdeck:svg` — уже проверенный разбором. */
  svg?: string;
  /**
   * Готовая картинка, которую панель нарисовала САМА (дороги контура и
   * эндпоинта). Приходит сюда там, где правого столбца нет вовсе — в чате чужого
   * CLI: обещать в меню «нарисует контур» и не показать результат нельзя.
   */
  picture?: MediaImage;
  /**
   * Разговор, к которому привязать файл. Пусто — запись останется без разговора:
   * файл от этого не пропадает, но в списке своего чата у него не будет.
   */
  chatId?: string;
  /** Модель разговора: карточка назовёт, кто диктовал или рисовал. */
  model?: string;
  /** О чём просили. Станет подписью записи — иначе через день колода безымянна. */
  prompt?: string;
  /**
   * Ответ ещё печатается. Смотреть можно (рисунок уже виден), собирать файлы —
   * нет: блок в идущем ответе панель показывает сразу, но он ещё не реплика, и
   * запись на диск по нему была бы записью по черновику.
   */
  disabled?: boolean;
  /** Убрать карточку с экрана. Есть только у готовой записи панели. */
  onClose?: () => void;
  /**
   * Колода, которую этот блок ЗАМЕНЯЕТ: человек попросил правку, и агент ответил
   * новой структурой. Без этого поля сборка потеряла бы картинки прежней колоды —
   * панель принимает их имена только из ЕЁ набора, а каждая стоила запроса.
   */
  reviseOf?: string;
  /**
   * Начать правку собранной колоды. Пусто — правка отсюда не начинается (правого
   * столбца в этом месте нет или композер её не ждёт).
   */
  onRevise?: (deck: MediaDeck) => void;
  /** Файлы собраны: состояние правки в композере больше не нужно. */
  onDeckSaved?: () => void;
}

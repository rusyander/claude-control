import { object, string, type infer as Infer } from 'zod';

/**
 * Зарегистрированный проект уровня конфигурации. Панель ведёт не только
 * пользовательский `~/.claude`, но и конфиги конкретных проектов: их `CLAUDE.md`,
 * `.claude/settings.json` (права и хуки) и корневой `.mcp.json` (MCP-серверы).
 *
 * Реестр проектов хранится в состоянии панели (`state.json`) — это просто список
 * запомненных путей. Сами файлы проекта живут в его каталоге и правятся теми же
 * доменными функциями, что и пользовательский уровень, только по проектным путям.
 */
export const projectSchema = object({
  /** Стабильный идентификатор записи реестра — по нему адресуются маршруты. */
  id: string(),
  /** Короткое имя для интерфейса — обычно имя каталога. */
  name: string(),
  /** Абсолютный путь к корню проекта. */
  path: string(),
});

export type Project = Infer<typeof projectSchema>;

/** Тело запроса на добавление проекта в реестр. */
export const projectDraftSchema = object({
  /** Абсолютный путь к корню проекта. Должен существовать и быть каталогом. */
  path: string().min(1),
  /** Необязательное имя; если не задано — берётся из последнего сегмента пути. */
  name: string().optional(),
});

export type ProjectDraft = Infer<typeof projectDraftSchema>;

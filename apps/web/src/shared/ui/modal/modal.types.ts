import type { ReactNode } from 'react';

export interface ModalProps {
  isOpen: boolean;
  onOpenChange: (isOpen: boolean) => void;
  title: string;
  description?: string;
  children: ReactNode;
  /**
   * Действия над тем, что показывает окно, — строкой под заголовком: у окна
   * записи (группы, шага) это «Редактировать», «Удалить» и т. п. Не путать с
   * `footer`: там кнопки завершения формы.
   */
  headerActions?: ReactNode;
  /** Кнопки внизу окна: сохранить, отменить, удалить. */
  footer?: ReactNode;
  /**
   * Размер задаёт и ширину, и высоту — окно не растёт и не сжимается от
   * содержимого, лишнее прокручивает тело. sm (420×320) — подтверждения,
   * md (620×560) — короткие формы и списки, lg (880×720) — окна записи и формы
   * подлиннее, xl (1380×880) — формы с помощником: поля и чат в две колонки,
   * full — рабочее окно почти во весь экран: дерево файлов и редактор. Экран
   * ограничивает размер сверху; на телефоне окно — лист во всю ширину.
   * fit — ширина md, высота по содержимому до потолка md: только для короткого
   * неизменного содержимого (выбор из пары вариантов, подтверждение с фактами).
   */
  size?: 'sm' | 'md' | 'lg' | 'xl' | 'full' | 'fit';
  /**
   * Отдать телу окна всю высоту и запретить ему прокрутку.
   *
   * Нужно окнам, внутри которых прокручиваются собственные области: без этого
   * прокрутка получается двойной — сначала едет всё окно вместе с шапкой, и
   * только потом содержимое колонки, до которой добрались.
   */
  bodyFill?: boolean;
  /**
   * Можно ли закрыть окно самому: крестик, Escape, клик по затемнению.
   *
   * false — для окон, из которых есть только один осмысленный выход (например,
   * «сервер не ответил» с единственной кнопкой «Повторить»): крестик, который
   * ничего не делает, хуже отсутствующего.
   */
  dismissible?: boolean;
}

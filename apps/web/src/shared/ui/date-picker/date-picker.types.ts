/**
 * Границы выбора в формате `YYYY-MM-DD` — местные календарные сутки.
 *
 * Строка, а не `Date`: аналитика на сервере считает периоды местными сутками,
 * а `new Date('2026-08-30')` — это полночь по Гринвичу, в поясе +3 уже вчерашний
 * вечер. Пока значение живёт строкой, часовой пояс не может её сдвинуть.
 */
export interface DateRangeValue {
  from?: string;
  to?: string;
}

/**
 * Режим выбора. `range` вырождается в одну дату сам: первый клик по календарю
 * даёт готовый диапазон из одних суток, второй — растягивает его. Отдельный
 * `single` нужен там, где вторая дата не имеет смысла в принципе.
 */
export type DatePickerMode = 'single' | 'range';

export interface DatePickerProps {
  mode?: DatePickerMode;
  value: DateRangeValue;
  /** Пустой объект — выбор сброшен: пользователь снял отметку с даты. */
  onChange: (value: DateRangeValue) => void;
  /** Верхняя граница выбора, `YYYY-MM-DD`. Обычно сегодня: будущего в отчётах нет. */
  max?: string;
  min?: string;
  /** Текст на кнопке, пока ничего не выбрано. */
  placeholder: string;
  ariaLabel: string;
  /** К какому краю кнопки прижимать всплывающий календарь. */
  align?: 'start' | 'center' | 'end';
  /** Подсветить кнопку как активный фильтр. */
  isActive?: boolean;
}

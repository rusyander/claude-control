import type { RunInputRecord } from '@agentdeck/contracts/run-input';
import type { LocalLayerCarry, SessionHooks } from '@agentdeck/contracts/core/session-carry';
import {
  BRIEF_OUTPUT_ENV,
  TESTS_CLI_ENV,
  TESTS_PROJECT_ENV,
} from '@agentdeck/contracts/chat-group-settings';
import { safeEffort, safeModel } from '../../../lib/cli-args/cli-args.ts';

/**
 * Параметры прогона чата и то, что из них видит агент. Жили в `ChatRunner.ts`
 * вместе с запуском CLI панелью; запуск ушёл в ядро (этап 10, G14 — прогон
 * чата ведёт `CoreChatRun`), а параметры, вход прогона (U8) и снятие
 * унаследованных меток ребёнка остались общими для реестра и ядра.
 */

export interface RunOptions {
  prompt: string;
  /** Продолжение существующей сессии. */
  sessionId?: string;
  /** Рабочая папка: артефакты Claude окажутся здесь. */
  cwd: string;
  /** Имя чата — CLI сохранит его в транскрипт, и список чатов его покажет. */
  name?: string;
  /** Модель: алиас (opus/sonnet/haiku/fable) или полное имя; пусто = по умолчанию. */
  model?: string;
  /** Глубина продумывания (--effort): low/medium/high/xhigh/max; пусто = по умолчанию. */
  effort?: string;
  /**
   * Ветвление вместо продолжения: нужно, когда пользователь правит своё
   * сообщение — исходная ветка диалога при этом остаётся нетронутой.
   */
  fork?: boolean;
  /**
   * Разовый ход без следа (`--no-session-persistence`): CLI не пишет транскрипт,
   * и процесс после хода закрывается, а не ждёт следующего в пуле. Так ходит
   * пинг тёплого кэша (`keep-warm`): с `fork` он читает префикс сессии группы,
   * а её транскрипт и список чатов остаются нетронутыми (замер 22.10).
   */
  ephemeral?: boolean;
  /**
   * Каждый вызов инструмента отклоняется хуком `PreToolUse` ДО исполнения
   * (`deny-tools-hook.mjs` в том же файле `--settings`). Пинг тёплого кэша —
   * ответвление сессии группы с её правами: правка без вопроса (acceptEdits,
   * правило «разрешить») успела бы исполниться раньше, чем обрыв по событию
   * `tool` снимет процесс. Хуки в системный промпт не попадают — префикс тот же.
   */
  denyTools?: boolean;
  /**
   * Каталог конфигурации Claude Code. Обычный чат работает с настоящим, а
   * песочница подсовывает временный — так тестируемое правило или хук
   * действует, а всё остальное из реальной конфигурации не подключается.
   */
  configDir?: string;
  /**
   * `--setting-sources` прогона. Просит его песочница (`user`): её рабочая папка
   * лежит под домом, и без сужения CLI находил бы поиском вверх личный
   * `~/.claude/CLAUDE.md`. Не выводится из `configDir`: свой каталог конфигурации
   * сам по себе не значит «без слоёв проекта» — иначе прогон со своим каталогом
   * терял бы `CLAUDE.md`, скиллы и MCP репозитория (`check-run-layers.mjs`).
   */
  settingSources?: string;
  /**
   * Дополнительные переменные окружения. Нужны песочнице: доступ к аккаунту
   * может быть не файлом, а ключом API — его передают именно так.
   */
  env?: Record<string, string>;
  /**
   * Адрес шлюза контура для ЭТОГО прогона (Т3) — то, чем «чат через контур,
   * тесты своим ключом» отличается от одной записи в общем конфиге CLI.
   *
   * Заполняет реестр прогонов на КАЖДОМ старте, руками задавать нечего:
   * решение зависит от активного контура и отмеченных потребителей, а они
   * меняются между прогонами. Отдельным полем от `env` именно поэтому —
   * значение, оставшееся в параметрах остановленного прогона, не должно
   * пережить снятую галочку при продолжении.
   */
  platformEnv?: Record<string, string>;
  /**
   * Системный промпт контура ВМЕСТО промпта CLI (Т5.4а). Пустая строка —
   * «работать обычным промптом»: реестр обязан уметь снять его так же, как
   * ставит, иначе продолжение прогона переживало бы выключенную галочку.
   *
   * Уходит ФАЙЛОМ (`--system-prompt-file`), и не только на Windows: текст
   * многострочный, с примерами JSON внутри, и в командной строке ему делать
   * нечего ни на одной системе.
   */
  platformSystemPrompt?: string;
  /**
   * Флаги снятия НАШИХ слоёв для прогона через контур (Т8): `--setting-sources`,
   * `--disable-slash-commands`, `--strict-mcp-config`.
   *
   * Отдельным полем от общих аргументов, и по той же причине, что у
   * `platformEnv`: состав решается на каждом старте, и флаг, оставшийся в
   * параметрах остановленного прогона, пережил бы возвращённую галочку. Значения
   * сюда кладёт домен контура, из запроса они не приходят ни в каком виде.
   */
  platformArgs?: string[];
  /**
   * Снята ли НАША дописка к системному промпту слоем `systemPrompt` (Т8).
   *
   * Именно отдельным флагом, а не затиранием `appendSystemPrompt` пустой строкой:
   * дописку собирает маршрут чата, а снятый слой — состояние контура, и затёртый
   * текст уже не вернуть. Прогон, поставленный на паузу со снятым слоем и
   * продолженный после того, как галочку вернули, уходил БЕЗ инициатив,
   * разделения и продолжения сессии — в сохранённых параметрах лежала пустая
   * строка, а восстановить её было неоткуда (ревью Т8, MAJOR-4). Флаг реестр
   * ставит на КАЖДОМ старте, поэтому прошлая жизнь прогона его не переживает.
   */
  platformDropAppend?: boolean;
  /**
   * Блок набора панели к системному промпту, когда флага плагина нет: сейчас —
   * дисциплина локальной модели при режиме «глобальные». Реестр ставит его на
   * КАЖДОМ старте, по той же причине, что и остальные `platform*`: прошлая жизнь
   * прогона его не переживает.
   */
  platformAppend?: string;
  /**
   * MCP-серверы, взятые человеком в локальный прогон (L4): записи из его файлов
   * настроек. Прогон идёт с `--strict-mcp-config`, который унёс бы все серверы, и
   * эти приезжают своим `--mcp-config` — так же, как брокер прав. Реестр ставит поле на
   * КАЖДОМ старте: выбор человека меняется между ходами.
   */
  platformMcp?: { ids: string[]; config: unknown };
  /**
   * Строка лёгкого профиля группы разделения (1.2): какие MCP-серверы в прогоне,
   * какие сняты и как попросить снятый. Реестр ставит её на КАЖДОМ старте вместе
   * с профилем — состав меняется, когда группа попросила сервер.
   */
  profileNote?: string;
  /**
   * Настройки профиля чата поверх личных: хуки (список задач трекера без описаний, 5.2). В сеанс
   * ядра едут полем `session.hooks` — его `--settings` единственный (s12, `core-run/session-carry.ts`).
   */
  platformSettings?: { hooks?: SessionHooks };
  /**
   * Локальный слой проекта (`domains/local-layer`) на этот старт: уезжает в ядро полем
   * `session.localLayer`, а источники настроек без `project` — в `platformArgs`. Реестр ставит
   * или снимает его на КАЖДОМ старте: режим карточки меняется между ходами (s10 G14 p6).
   */
  localLayer?: LocalLayerCarry;
  /**
   * Права на действия с файлами. В песочнице — acceptEdits: там файлы Claude
   * и есть результат. В настоящем проекте по умолчанию `default`: чтение
   * работает, а правки без подтверждения не проходят, и панель ничего в
   * рабочем коде молча не меняет.
   */
  permissionMode?: string;
  /**
   * Интерактивные права: когда задано, к агенту подключается мини-MCP-сервер, и
   * каждый запрос на разрешение инструмента (вне авторазрешённого режимом)
   * уходит человеку кнопкой в чате. `runId` связывает запрос с разговором,
   * `baseUrl` — адрес приложения, куда MCP-сервер стучится за решением. При
   * полном доступе (bypassPermissions) не нужно — там всё и так разрешено.
   * `tokenFile` — ПУТЬ к ключу доступа: при включённом удалённом доступе гейт
   * требует ключ и от собственного MCP-сервера (по HTTP тот — такой же клиент,
   * как телефон), а без ключа каждый запрос прав получал 401 и превращался в
   * отказ. Именно путь, а не значение: файл читается на каждый запрос, поэтому
   * смена ключа посреди прогона не ломает права до конца работы, а на машине,
   * где удалённый доступ не включали, ключ и не заводится.
   */
  permissionPrompt?: { runId: string; baseUrl: string; tokenFile?: string };
  /**
   * Дописка к системному промпту: правда про вопрос человеку, разделение задач
   * по чатам и продолжение в чистой сессии — тем составом, который включён.
   *
   * Переводы строки сохраняются: на Windows значение уходит ФАЙЛОМ
   * (`--append-system-prompt-file`) — ни перевод строки, ни кавычки через
   * cmd.exe не проходят, а файл оболочка не разбирает вовсе (разбор в `run()`);
   * в остальных ОС процесс запускается без оболочки, и аргумент доезжает как
   * есть. Сценарий из 80 шагов одной строкой модель читала бы сплошной стеной.
   */
  appendSystemPrompt?: string;
  /**
   * Правда о рабочем каталоге — сейчас это тесты проекта (папка e2e, как тест
   * становится кейсом). Отдельным полем, а не внутри `appendSystemPrompt`: её
   * реестр пересчитывает на КАЖДОМ старте, а дописка переживает продолжение, и
   * склейка там задвоила бы строку на втором ходу.
   */
  workspaceNote?: string;
  /**
   * Команда запуска CLI активного провайдера. Задаётся маршрутом чата через
   * реестр провайдеров; по умолчанию — команда провайдера Claude. Имя больше не
   * хардкодится здесь, но значение то же (claude / claude.cmd).
   */
  command?: string;
  /**
   * Ход, начатый самим CLI живой сессии (см. `live-session.ts`): прогон не
   * отправляет сообщения, а забирает уже идущий ход — фоновая задача агента
   * кончилась, и CLI продолжил работу сам.
   */
  wake?: boolean;
  /**
   * С `wake`: хода CLI ещё нет — прогон держит сессию и ждёт его
   * (`LiveSession.awaitTurn`). Заводит реестр, когда фоновому субагенту между
   * ходами нужно решение человека (`ChatRunRegistry.hostBackgroundAsk`).
   */
  hold?: boolean;
  /**
   * Инструменты, снятые настройкой панели `chatLeanTools` (`UNUSED_HEAVY_TOOLS`).
   * Решает реестр на каждом старте: выключенная настройка возвращает их уже
   * следующему ходу, а не новому разговору.
   */
  deniedTools?: readonly string[];
}

/**
 * Дописка к системному промпту ровно в том виде, в каком её получит процесс:
 * текст панели (ребёнку — с его правилами) и строка о тестах проекта. Её же
 * берёт подпись живой сессии — иначе процесс из пула держал бы старый промпт.
 */
function appendedOf(options: RunOptions): string {
  // Блок набора (`platformAppend`) — не наша дописка и слоем «системный промпт»
  // не снимается: он выбран на странице набора, а не расчётом контура.
  const kit = options.platformAppend?.trim() ?? '';
  const ours = options.platformDropAppend
    ? ''
    : [options.appendSystemPrompt ?? '', options.workspaceNote ?? '', options.profileNote ?? '']
        .filter((part) => part.trim())
        .join('\n\n')
        .trim();
  return [ours, kit].filter(Boolean).join('\n\n');
}

/**
 * Вход прогона ровно в том виде, в каком его получит CLI (U8): та же дописка,
 * что уедет `--append-system-prompt`, те же модель и глубина, что пройдут
 * проверку грамматики, и промпт контура. Собирается здесь, рядом со сборкой
 * флагов, — чтобы «что получил агент» не разошлось с тем, что он получил.
 */
export function receivedInputOf(options: RunOptions, startedAt: number): RunInputRecord {
  const model = safeModel(options.model);
  const effort = safeEffort(options.effort);
  const appended = appendedOf(options);
  const contour = options.platformSystemPrompt?.trim();
  return {
    startedAt,
    ...(model ? { model } : {}),
    ...(effort ? { effort } : {}),
    permissionMode: options.permissionMode ?? 'acceptEdits',
    prompt: options.prompt,
    ...(appended ? { appendSystemPrompt: appended } : {}),
    ...(contour ? { systemPrompt: contour } : {}),
    ...(options.platformArgs?.length ? { platformArgs: [...options.platformArgs] } : {}),
  };
}

/** Метка автономии чата, снятой 02.11.2026 (см. `forgetInheritedChildMarks`). */
const RETIRED_AUTONOMY_ENV = 'AGENTDECK_AUTONOMOUS';

/**
 * Снять с окружения панели метки ребёнка, унаследованные от запустившего её
 * процесса. Панель, перезапущенная агентом группы, иначе метила бы ребёнком
 * каждый свой запуск — чаты человека (хуки молчали бы ему о «/clear»), чужие
 * CLI, прогоны проверок с коротким выводом. Число мест очереди остаётся: его
 * человек задаёт в окружении панели сам. Вызывается один раз, при старте.
 */
export function forgetInheritedChildMarks(env: NodeJS.ProcessEnv): void {
  delete env[BRIEF_OUTPUT_ENV];
  // Проект группы (X1): унаследованный, он увёл бы tests-cli без `--project`
  // в любом чате панели к копии, из которой её перезапустили.
  delete env[TESTS_PROJECT_ENV];
  // Путь к tests-cli: унаследованный от копии вёл бы к её checkout, а не к этой панели.
  delete env[TESTS_CLI_ENV];
  // Метка автономии прежних версий: панель её больше не ставит, а личный двойник
  // хука автовыбора в `~/.claude` её читает — унаследованная, она отвечала бы за
  // человека в каждом чате панели, перезапущенной из такого прогона.
  delete env[RETIRED_AUTONOMY_ENV];
}

/**
 * Создать одноразовый каталог конфигурации.
 *
 * `onboardingDone` ставится сразу: мастер первого запуска — отдельный экран, и
 * в кадрах этой пачки ему делать нечего. Светлая тема выбрана явно, чтобы
 * кадры не зависели от темы машины, на которой идёт съёмка.
 */
export function makeHome(home, { claudeMd = RULES_CLAUDE_MD, projects = [] } = {}) {
  mkdirSync(join(home, 'agentdeck'), { recursive: true });
  writeFileSync(join(home, 'settings.json'), '{}\n', 'utf8');
  writeFileSync(join(home, 'CLAUDE.md'), claudeMd, 'utf8');
  writeFileSync(
    join(home, 'agentdeck', 'state.json'),
    `${JSON.stringify({ projects, settings: { onboardingDone: true, theme: 'light', language: 'ru' } }, null, 2)}\n`,
    'utf8',
  );
}

/** Переписать личный CLAUDE.md между кадрами — сценарию нужно другое состояние файла. */
export function setClaudeMd(home, text) {
  writeFileSync(join(home, 'CLAUDE.md'), text, 'utf8');
}

/**
 * Выдуманный проект на диске: свой `CLAUDE.md` и свой `.claude/rules`.
 *
 * Настоящий каталог, а не подмена ответа: слои инструкций — это как раз про то,
 * какие файлы лежат на диске, и подменённый ответ доказывал бы только разметку.
 */
export function makeProject(dir = PROJECT_DIR) {
  if (existsSync(dir) && !existsSync(join(dir, MARK))) {
    throw new Error(`${dir} уже существует и создан не съёмкой — выберите другой путь`);
  }
  mkdirSync(join(dir, '.claude', 'rules'), { recursive: true });
  writeFileSync(join(dir, MARK), 'создан tools/help-shots/rules-panel.mjs\n', 'utf8');
  writeFileSync(join(dir, 'CLAUDE.md'), PROJECT_CLAUDE_MD, 'utf8');
  writeFileSync(join(dir, '.claude', 'rules', 'exports.md'), PROJECT_RULE, 'utf8');
  writeFileSync(join(dir, '.claude', 'rules', 'code-style.md'), PROJECT_RULE_2, 'utf8');
  return dir;
}

/** Снести выдуманный проект — но только тот, который создали мы. */
export function dropProject(dir = PROJECT_DIR) {
  if (existsSync(join(dir, MARK))) rmSync(dir, { recursive: true, force: true });
}

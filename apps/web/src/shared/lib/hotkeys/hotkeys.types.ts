/**
 * Один шаг аккорда: клавиша плюс признак «главного» модификатора. Под `mod`
 * понимаем Ctrl или Cmd вместе — так одно сочетание работает и на Windows, и на
 * macOS. Shift и Alt намеренно не учитываем: символ уже приходит в `key`
 * (например, `?` вместо Shift+`/`), а буквы приводим к нижнему регистру.
 */
export interface KeyStep {
  /** Нормализованная клавиша: буквы в нижнем регистре, символы как есть. */
  key: string;
  /** Нажат Ctrl или Cmd. */
  mod: boolean;
}

/** Привязка: последовательность шагов и что делать, когда она набрана. */
export interface HotkeyBinding {
  /**
   * Аккорд строкой. Пробел разделяет шаги последовательности, `+` — модификатор
   * внутри шага. Примеры: `mod+k`, `g o`, `/`, `?`.
   */
  chord: string;
  /** Действие при совпадении. */
  handler: () => void;
  /**
   * Разрешить срабатывание, когда фокус в поле ввода. По умолчанию простые
   * аккорды (без `mod`) в полях не срабатывают, чтобы не мешать набору текста.
   */
  allowInInput?: boolean;
}

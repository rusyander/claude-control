import type { FastifyInstance } from 'fastify';

/**
 * Пустое тело запроса — это `{}`, а не отсутствие объекта.
 *
 * Fastify отдаёт обработчику `undefined`, когда тела нет вовсе, и `null` на
 * литерал `null`. Обработчик, который читает `request.body.поле` напрямую, на
 * таком запросе падает с 500: снаружи это выглядит как сломанная панель, хотя
 * сломан ровно один запрос. К серверу ходит ещё и телефон через Tailscale, так
 * что обрезанное тело — не выдумка.
 *
 * Дефект механический и одинаковый в полутора десятках маршрутов, поэтому
 * чинится ОДНОЙ точкой, а не сорока правками по месту: так его нельзя ни забыть
 * в новом маршруте, ни расчинить обратно при следующей правке.
 *
 * Отдельной функцией, а не строкой в `index.ts`, ровно по одной причине: тест
 * поднимает свой экземпляр Fastify, и без общей точки он проверял бы не тот
 * сервер, который работает у человека.
 */
export function registerEmptyBodyGuard(app: FastifyInstance): void {
  // `preValidation` идёт ПОСЛЕ разбора тела, поэтому подмена не мешает ни
  // парсеру, ни схемам маршрутов. GET и HEAD не трогаем: тела у них нет по
  // определению, и заводить его пустым значило бы врать о запросе.
  app.addHook('preValidation', (request, _reply, done) => {
    const bodyless = request.method === 'GET' || request.method === 'HEAD';
    if (!bodyless && (request.body === undefined || request.body === null)) {
      request.body = {};
    }
    done();
  });
}

/** Коды отказов пакета: панель переводит их в свои тексты, ядро и хост — в факт `unknown` с причиной. */
export type KeysErrorCode =
  /** Блок без метки формата — не наша зашифрованная копия. */
  | 'not-encrypted'
  /** Тег GCM не сошёлся: не та парольная фраза или повреждённый блок. */
  | 'decrypt-failed'
  /** Файл ключей есть, а машинного секрета к нему нет — расшифровать нечем. */
  | 'master-missing'
  /** Расшифровано, но внутри не объект ключей. */
  | 'store-garbage';

export type KeysError = Error & { code: KeysErrorCode };

/** Расшифрованное хранилище: идентификатор хранилища → значение ключа. */
export type KeyStore = Record<string, string>;

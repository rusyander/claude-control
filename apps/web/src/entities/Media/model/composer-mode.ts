/**
 * Режим отправки в композере: обычное сообщение агенту, картинка (Т9) или
 * презентация (Т10).
 *
 * Тип живёт в сущности «Медиа», а не в фиче композера, хотя рисует его композер.
 * Причина в границах слоёв: состояние режимов считает один общий хук
 * (`useChatMedia`), нужный И чату Claude, И чату чужого CLI, а фича не вправе
 * тянуть другую фичу. Поэтому смысл («какие бывают режимы и что панель о них
 * знает») лежит здесь, а композер берёт его отсюда.
 */
export type ComposerMode = 'text' | 'image' | 'deck';

/**
 * Режим композера и его доступность. Приходит страницей, а не считается в
 * композере: решение «чем сделать и можно ли» принимает сервер один раз
 * (`planImage`/`planDeck`), а второй такой расчёт на клиенте разошёлся бы с
 * настоящим маршрутом.
 */
export interface ComposerModeState {
  mode: ComposerMode;
  onModeChange: (mode: ComposerMode) => void;
  /** Доступен ли режим картинки. Ложь — пункт заперт, и причина рядом. */
  imageAvailable: boolean;
  /** Причина недоступности словами. Пусто — режим доступен. */
  imageReason?: string;
  /** Чем нарисует: агент разговора, контур или профиль эндпоинта. */
  imageSource?: string;
  /**
   * Рисует АГЕНТ разговора, а не панель своей дорогой. Признак нужен подсказке в
   * пустом поле: «панель нарисует сама, без агента» на этой дороге — прямая
   * неправда, а человек читает именно её, а не подпись маршрута под полем.
   */
  imageByAgent?: boolean;
  /** Доступен ли режим презентации. */
  deckAvailable: boolean;
  deckReason?: string;
  /** Кто соберёт колоду и получится ли PDF на этой машине. */
  deckSource?: string;
  /** Идёт работа режима: поле и кнопки заняты, как и при прогоне агента. */
  isDrawing?: boolean;
  /**
   * Заголовок колоды, которую правит следующая отправка. Пусто — обычная сборка.
   * Композер говорит это словами: «поправь третий слайд» без напоминания о том,
   * ЧТО правится, легко отправить не в ту колоду.
   */
  reviseTitle?: string;
  /** Отменить правку и вернуться к обычной сборке по теме. */
  onReviseCancel?: () => void;
  /**
   * Меню открылось — перечитать план у сервера.
   *
   * План спрашивается один раз при монтировании, а разговор живёт открытым
   * часами: выключенный за это время контур, уехавший порт шлюза или правка
   * `imagesUrl` в соседней вкладке до меню не доходили, и оно продолжало обещать
   * дорогу, которой уже нет. Дальше человек описывал картинку и получал отказ —
   * ровно тот отказ, ради которого план и спрашивается ДО нажатия. Перечитывание
   * стоит одного запроса на открытие меню и не ходит в сеть дальше панели.
   */
  onMenuOpen?: () => void;
}

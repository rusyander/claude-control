import type { LimitShare } from '@agentdeck/contracts';
import type { CascadeStage } from '@agentdeck/contracts/model-cascade';
import type { ChatTreeView } from '@agentdeck/contracts/chat-handoff';
import type { ChildQuestion } from './ChildQuestion.types';
import type { ChildPermission } from './ChildPermission.types';

/**
 * Группа разделения глазами родителя: где она сейчас и чем ведётся.
 *
 * Одна группа — до пяти разговоров (план, работа, ревью, правки; разбор общий
 * на всё разделение), и все они живут в одной копии. Строка сводки описывает
 * ГРУППУ, а не разговор: `chatId` — это последнее её звено, то самое, которое
 * человек и хочет открыть.
 */
export interface ChildStageGroup {
  chatId: string;
  /**
   * Ключи ВСЕХ звеньев группы в списке чатов. Запрос прав и вопрос любого звена
   * — в карточке группы (владелец 23.10), а не только последнего.
   */
  chatIds?: string[];
  title: string;
  branch?: string;
  /** Пройденные звенья по порядку; последнее — нынешнее состояние группы. */
  stages: CascadeStage[];
  /** Чем ведётся последнее звено: из транскрипта, иначе из назначения панели. */
  model?: string;
  /** Глубина продумывания, назначенная звену панелью: транскрипт её не пишет. */
  effort?: string;
  /** От заведения звена работы до первой правки кода агентом (мс); нет — правок ещё не было. */
  firstEditAfterMs?: number;
  /** Сумма времени цепочки (мс): у каждого звена от заведения до последней записи. */
  workMs?: number;
  /**
   * Доля окон лимита подписки (0..1), потраченная звеньями группы, — сумма их
   * `ChatSummary.limitShare`. Нет замеров ни у одного звена — поля нет.
   */
  limitShare?: LimitShare;
  /**
   * Когда заведено первое звено цепочки и когда была последняя запись в ней
   * (ISO). По ним хаб считает, сколько идёт разбор и всё разделение: `workMs`
   * тут не годится — у молчащего прогона последняя запись стоит, а время идёт.
   */
  startedAt?: string;
  lastAt?: string;
  /** Старт идущего хода группы (ISO) — с него индикатор считает «работает». */
  runStartedAt?: string;
  isRunning: boolean;
  /** Прогон группы стоит на запросе прав — ждёт решения человека. */
  awaitingPermission?: boolean;
  /**
   * Чат группы, отброшенной перезапуском разделения (L20): связь с родителем
   * сохранена, но работа не продолжается. Строкой группы не считается — хаб
   * показывает такие чаты внизу, под «Неактивно».
   */
  retired?: boolean;
  /**
   * Снятая группа оставила неубранную копию (F5.2): родитель, которому
   * адресуется её уборка. Нет — убирать нечего.
   */
  retiredCopy?: { parentChatId: string };
  /** Снятую группу человек принял (TK-accepted) — отметка переживает новое разделение. */
  retiredAccepted?: boolean;
  /** Дерево стоит на паузе — группа остановлена и ждёт «Продолжить всё». */
  isPaused?: boolean;
  /**
   * Звено спросило человека инструментом и стоит (Д16) — из транскрипта. Без
   * этого такая группа в хабе выглядела просто остановившейся.
   */
  waitingFor?: 'question';
}

export interface ChildStagesProps {
  groups: ChildStageGroup[];
  /** Открыть звено в этом же окне — вкладка копии для этого не нужна. */
  onOpen: (chatId: string) => void;
  /**
   * Дерево с сервера: сколько прогонов идёт и стоит ли всё. Без него кнопок
   * паузы нет — считать их по списку чатов нельзя, очередь автостартов знает
   * только сервер.
   */
  tree?: ChatTreeView;
  /** Остановить / продолжить всё дерево разом. */
  onPauseAll?: () => void;
  onResumeAll?: () => void;
  /** Запрос паузы или продолжения в пути — кнопка крутится, второй клик не уходит. */
  treeBusy?: boolean;
  /**
   * Дерево ведёт чужой CLI: сессии у него нет, и продолжение — не «с того же
   * места», а тот же вопрос заново. Меняет только подпись кнопки: обещать
   * человеку продолжение сессии там, где её не существует, нельзя.
   */
  foreign?: boolean;
  /**
   * Провайдер чужого CLI: карточка собирает из него ключ разговора звена для
   * «Что получил агент» (U8) — связи чужих чатов живут под `<провайдер>:<id>`.
   */
  providerId?: string;
  /**
   * Разделы под карточками групп (пересечения, шаги человеку, тикеты,
   * «Неактивно») открыты при первом показе. В панели они свёрнуты; открытыми их
   * рисуют проверки содержимого.
   */
  sectionsOpen?: boolean;
  /** Вопросы агентов по ключу чата карточки (карточка 27) — каждый в своей карточке. */
  questions?: ReadonlyMap<string, ChildQuestion[]>;
  /** Ответ на вопрос группы — уходит в её чат. */
  onAnswer?: (chatId: string, answer: string) => void;
  /**
   * Запросы прав по ключу чата карточки (владелец 23.10) — каждый в карточке
   * своей группы, а не плашкой над хабом.
   */
  permissions?: ReadonlyMap<string, ChildPermission[]>;
  /** Решение по правам — уходит в прогон ребёнка, под ключом которого он спросил. */
  onPermissionDecide?: (chatId: string, toolUseId: string, behavior: 'allow' | 'deny') => void;
}

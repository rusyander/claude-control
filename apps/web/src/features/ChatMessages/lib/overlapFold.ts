/**
 * Сколько строк пересечений веток видно без сворачивания.
 *
 * Живой прогон 24.09.2026: сверка насчитала 215 файлов (потом 389), и раздел
 * выталкивал за экран и строки групп над ним, и карточки прав агентов — всё,
 * ради чего на хаб вообще смотрят. Три строки читаются с одного взгляда и
 * ничего не выталкивают; больше — это уже список, который открывают, когда
 * решают про слияние, а не каждый раз.
 */
export const OVERLAP_OPEN_LIMIT = 3;

/**
 * Свёрнут ли раздел пересечений и есть ли у него переключатель.
 *
 * `expanded` — выбор человека; пока он не нажимал, короткий список открыт, а
 * длинный свёрнут. Число файлов при этом видно всегда — в заголовке раздела.
 */
export function overlapFold(
  count: number,
  expanded: boolean,
): { foldable: boolean; showRows: boolean } {
  const foldable = count > OVERLAP_OPEN_LIMIT;
  return { foldable, showRows: !foldable || expanded };
}

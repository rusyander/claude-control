/**
 * Каталог моделей активного провайдера.
 *
 * Панель сама узнаёт, какие модели у провайдера сейчас есть, а не хранит
 * список, зашитый в код: модели выходят чаще, чем обновляется панель, и
 * зашитый список устаревает молча — пользователь просто не видит новую модель
 * в выборе. Источник — открытый каталог models.dev (тот же, которым живёт
 * OpenCode): один запрос отдаёт модели всех вендоров с идентификаторами,
 * семействами, датами выхода и лимитами.
 *
 * Провайдер, для которого вендор не задан (Continue, Goose, Aider, Cursor —
 * это оболочки поверх любых моделей), каталога не получает: угадывать, чей
 * список ему показать, панель не будет (fail-closed).
 */

/** Одна модель в каталоге. */
export interface ModelInfo {
  /** Идентификатор, который принимает CLI/API провайдера (`claude-opus-5`). */
  id: string;
  /** Человеческое имя (`Claude Opus 5`). */
  name: string;
  /**
   * Семейство (`claude-opus`, `gpt-mini`, `gemini-flash`). По нему считается
   * «вышла модель НОВЕЕ той, что стоит по умолчанию»: сравнивать поколения
   * внутри одного семейства осмысленно, между семействами — нет.
   */
  family: string;
  /** Вендор в каталоге (`anthropic`, `openai`, `google`, …). */
  vendor: string;
  /** Дата выхода `YYYY-MM-DD` или `YYYY-MM`; пусто — источник её не знает. */
  releaseDate?: string;
  /** Окно контекста в токенах. */
  contextLimit?: number;
  /** Потолок вывода в токенах. */
  outputLimit?: number;
  /** Умеет рассуждать (reasoning/thinking). */
  reasoning?: boolean;

  // --- Поля, которые заполняет только источник «контур». У models.dev их нет,
  // и придумывать их за контур панель не станет: пусто значит «не объявлено».

  /** Объявленный контуром вид модели (`chat`, `embedding`, …). */
  kind?: string;
  /** Контур объявил: модель принимает изображения. */
  vision?: boolean;
  /** Контур объявил: модель умеет вызывать функции. */
  functionCalling?: boolean;
  /** Контур объявил: модель умеет отвечать строгим JSON. */
  jsonMode?: boolean;
  /**
   * Модель пропала из списка контура. Остаётся в каталоге с пометкой, но
   * выбрать её нельзя: контур такой запрос уже не примет.
   */
  retired?: boolean;
  /** Когда модель видели у контура в последний раз. Только у пропавших. */
  lastSeenAt?: string;
}

/** Откуда берётся каталог моделей. */
export const modelSources = ['models.dev', 'platform'] as const;
export type ModelSource = (typeof modelSources)[number];

/**
 * Почему выбранный источник «контур» не сработал и ответ пришёл с models.dev.
 *
 * Отдельными причинами, а не одним «не вышло»: выключенный контур чинится
 * тумблером, непроверенный — кнопкой «Проверить связь», а несуществующий —
 * выбором другого в списке. Одна общая строка отправила бы человека искать
 * поломку не там.
 */
export const modelSourceFallbacks = [
  /** Источником выбран контур, но ни один не назван. */
  'no-platform',
  /** Названный контур из настроек пропал. */
  'platform-gone',
  /** Контур выключен или ключ не сохранён. */
  'platform-off',
  /** Контур ни разу не проверяли — списка моделей у панели нет. */
  'never-checked',
  /** Последняя проба неудачна и удачной не было ни одной. */
  'never-answered',
  /**
   * «Обновить» не смогло даже сходить: настройка контура не даёт составить
   * запрос (нечитаемый файл корневого сертификата). Отдельная причина, потому
   * что чинится она в карточке контура, а не кнопкой и не выбором другого.
   */
  'check-failed',
] as const;
export type ModelSourceFallback = (typeof modelSourceFallbacks)[number];

/** Ответ `GET /api/models`. */
export interface ModelCatalogResponse {
  /** Провайдер, для которого собран каталог. */
  provider: string;
  /** Вендоры каталога, относящиеся к этому провайдеру. */
  vendors: string[];
  /** Модели, свежие сверху. */
  models: ModelInfo[];
  /**
   * `models.dev` — данные из сети или из кэша этого источника;
   * `platform` — список ключа, полученный пробой контура;
   * `none` — источник ни разу не отвечал, показывать нечего.
   */
  source: 'models.dev' | 'platform' | 'none';
  /** Что человек ВЫБРАЛ в настройках. С `source` расходится при откате. */
  requestedSource: ModelSource;
  /**
   * Почему выбранный источник не сработал. Пусто — сработал: молчаливого отката
   * не бывает, иначе список моделей меняется под человеком без объяснения.
   */
  fallback?: ModelSourceFallback;
  /** Контур, из которого собран каталог (или из которого не вышло его собрать). */
  platformId?: string;
  /** Имя контура для строки на экране: идентификатор человек не выбирал. */
  platformTitle?: string;
  /** Когда каталог был скачан. Пусто — ни разу не скачивался. */
  fetchedAt?: string;
  /** Данные старше суток — панель покажет, что список может быть неполным. */
  stale: boolean;
  /** Адрес источника — чтобы было видно, откуда цифры. */
  url: string;
  /** Провайдер не объявил вендора: каталог для него не поддерживается. */
  unsupported: boolean;
  /** Идентификаторы моделей, появившихся с прошлого обновления. */
  newIds: string[];
  /** Автозамена модели по умолчанию, если она произошла именно сейчас. */
  promoted?: ModelPromotion;
}

/**
 * Замена модели по умолчанию на более новую того же семейства.
 *
 * Панель делает это сама, когда включено `autoUpdateModels` и в настройках
 * стоит КОНКРЕТНАЯ модель (не алиас и не «как выберет CLI»): алиас `opus` и
 * так означает «последняя», а вот пришпиленный `claude-opus-4-8` остаётся
 * прошлым поколением навсегда, пока его не переставят руками.
 */
export interface ModelPromotion {
  /** Что стояло. */
  from: string;
  /** Что стало. */
  to: string;
  /** Подпись новой модели для сообщения пользователю. */
  toName: string;
  /** Когда заменили, ISO. */
  at: string;
}

/** Сообщение, по которому лента запомнила место: его id и сдвиг от верха видимой части. */
export interface FeedAnchor {
  id: string;
  /** Где верх сообщения стоял относительно верха видимой части ленты, px (выше — меньше нуля). */
  offset: number;
}

/** Место в ленте, с которого человек ушёл в другой разговор. */
export interface FeedSnapshot {
  anchor?: FeedAnchor;
  /** Сырая прокрутка — запасной путь, когда якоря в ленте уже нет. */
  scrollTop: number;
  /** Последнее сообщение в момент снимка: по нему видно, что на экране та же переписка. */
  lastId?: string;
}

/** Сообщение ленты в момент снимка: верх и низ относительно верха видимой части, px. */
export interface FeedRow {
  id: string;
  top: number;
  bottom: number;
}

/** Что лента показывает сейчас — то, по чему решается, куда вернуть прокрутку. */
export interface FeedProbe {
  /** Где сейчас верх якорного сообщения относительно верха видимой части; нет — его не нарисовали. */
  anchorTop?: number;
  /** Нарисовано ли последнее сообщение снимка. */
  hasLast: boolean;
  scrollTop: number;
  /** Наибольшая возможная прокрутка (`scrollHeight − clientHeight`). */
  maxScroll: number;
}

/**
 * Как контур ведёт цикл вызовов своих инструментов. `loop` — ходит по кругу сам
 * и отдаёт готовый ответ; `single_turn` — возвращает вызов и ждёт результата от
 * клиента.
 */
export const platformToolModes = ['loop', 'single_turn'] as const;
export type PlatformToolMode = (typeof platformToolModes)[number];

/**
 * Размышления модели — три состояния, а не выключатель: «не отправлять» и
 * «отправить выключенным» у контуров различаются. Reasoning-модель на vLLM
 * (Qwen3) думает, если поле не пришло, и выключить её можно только явным
 * `false` — булева настройка этого сказать не могла (аудит MD-02).
 */
export const platformThinkingModes = ['default', 'on', 'off'] as const;
export type PlatformThinkingMode = (typeof platformThinkingModes)[number];

/**
 * Настройка, записанная до трёх состояний, была булевой: `true` значило
 * «включить», `false` — «поле не отправлять». Строку не трогаем: незнакомое
 * значение пусть назовёт перечисление, а не превратит в умолчание молча.
 */
export function thinkingModeInput(value: unknown): unknown {
  if (value === true) return 'on';
  if (value === false || value === undefined) return 'default';
  return value;
}

/** Та же схема и в настройках сервера — поле в поле, иначе разойдутся молча. */
export const platformThinkingSchema = preprocess(thinkingModeInput, zodEnum(platformThinkingModes));

/**
 * Правила КОНТУРА, которыми панель распоряжается из запроса (Т7, решение Р5).
 *
 * Здесь лежат только значения. Список того, что вообще можно задать, объявляет
 * драйвер (`DriverControl` с `kind: 'request'`), и правило, которого драйвер не
 * объявил, в запрос не попадает НИКОГДА — даже если значение в настройке
 * осталось от другого контура. Это та же линия, что и у остальной платформенной
 * ветки: ни одного `if (platform.id === …)` вне драйвера.
 */
export const platformRulesSchema = object({
  /**
   * Инструменты САМОГО контура: их имена из его реестра.
   *
   * Список, а не выключатель, потому что поле контура принимает имена, и узнать
   * их панели неоткуда — реестр закрыт ключом другого рода (`no-mcp-catalog`,
   * та же причина, по которой человек сам ведёт список агентов). Пусто —
   * инструменты платформы не запрашиваются вовсе, и наверх уходит
   * `tool_choice: "none"` (Т5.4).
   */
  platformTools: array(string()).default([]),
  /** Имеет смысл только при непустом `platformTools`. */
  toolMode: zodEnum(platformToolModes).default('loop'),
  /**
   * Именованный набор параметров генерации на стороне контура. Пусто — поле не
   * отправляется, и контур подставляет своё умолчание сам: «не отправить» и
   * «отправить пустую строку» — разные вещи, вторая была бы отказом 400.
   */
  generationPreset: string().default(''),
  /** Размышления модели: `default` — поле не отправляется, решает шаблон модели. */
  enableThinking: platformThinkingSchema,
});

export type PlatformRules = Infer<typeof platformRulesSchema>;

/**
 * НАШИ слои в прогоне через контур (Т8, решения Р5/Р6).
 *
 * Зачем выключатель вообще. Через контур ходят модели среднего класса, и H1
 * замерила, чем это кончается: 108 546 знаков инструкций, написанных под Claude,
 * топят такую модель — она объявляет файл созданным, не сделав ни одного вызова.
 * Короткий промпт контура (Т5.4а) снимает промпт CLI, а личный `~/.claude`
 * человека — правила, скиллы, хуки — остаётся, и на живой машине это ещё
 * десятки тысяч знаков на КАЖДЫЙ ход (кэша промпта у контура нет,
 * `shim-no-cache`).
 *
 * ПОЧЕМУ СОСТАВ ИМЕННО ТАКОЙ, А НЕ ПО СЛОЮ НА ГАЛОЧКУ. Слой снимается тем, что
 * умеет CLI, а не тем, что удобно нарисовать. Замерено пробой на настоящем
 * `claude` 2.1.263 (`.agent/tmp/t8-layers-probe.mjs`, стаб вместо модели, в
 * запросе ищутся метки каждого слоя):
 *   `--setting-sources project,local` — снимает СРАЗУ личные правила, хуки,
 *      права, личные скиллы и личные MCP-серверы: в CLI это один источник
 *      «user», и разделить его нечем. Проектный слой этот флаг не трогает
 *      (проверено);
 *   `--disable-slash-commands` — скиллы, и ВСЕ: личные и репозитория;
 *   `--strict-mcp-config` — MCP-серверы, и ВСЕ: личные, проектный `.mcp.json` и
 *      переходник панели к контуру. Переживает его только брокер прав панели,
 *      который приезжает своим `--mcp-config` (проверено — иначе каждый запрос
 *      прав стал бы молчаливым отказом).
 * Поэтому `settings` — одна галочка на три слоя, и на карточке это сказано
 * словами (подпись `rules-partial`), а не спрятано. По той же причине у скиллов
 * и MCP подписи говорят, что уезжает и проектное: раздельных флагов нет, а
 * человек, снявший «MCP-серверы» ради экономии промпта, иначе терял бы
 * инструменты задачи молча (ревью Т8).
 *
 * ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Защита данных (`dlp`): выключать маску ради экономии
 * промпта — обмен, которого панель не предлагает, и её выключатель остаётся там,
 * где был. Гейт промпта отдельной строки не имеет, потому что физически он —
 * НАШ ХУК в `~/.claude/settings.json`: он уходит вместе с `settings` и приходит
 * вместе с ним. Подбор модели под задачу выключается на проект в правах чата, и
 * второй его выключатель здесь означал бы две правды об одном.
 */
export const ourRulesSchema = object({
  /** Общий выключатель: снят — ни одного нашего слоя в прогоне через контур. */
  enabled: boolean().default(true),
  /** Личные правила, хуки, права, скиллы и MCP из `~/.claude` (источник `user`). */
  settings: boolean().default(true),
  /** Скиллы отдельно: их снимает свой флаг, не трогая правил и хуков. */
  skills: boolean().default(true),
  /** MCP-серверы отдельно; брокер прав панели остаётся при любом значении. */
  mcp: boolean().default(true),
  /** Дописка панели к системному промпту: инициативы, разделение, продолжение. */
  systemPrompt: boolean().default(true),
});

export type OurRules = Infer<typeof ourRulesSchema>;


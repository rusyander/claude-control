import type { ReactNode } from 'react';

export interface VirtualListProps<TItem> {
  items: TItem[];
  /**
   * Высота строки в пикселях: нужна для расчёта окна прокрутки. Функция —
   * когда строки разной высоты, например заголовки групп между записями.
   */
  rowHeight: number | ((item: TItem, index: number) => number);
  /**
   * Высота собственного окна прокрутки. Задаётся только там, где список живёт
   * в своей колонке (список разговоров чата). Без неё список прокручивается
   * вместе со страницей — одна прокрутка на раздел, без коробки фиксированной
   * высоты с пустотой под ней.
   */
  height?: number;
  renderRow: (item: TItem, index: number) => ReactNode;
  getKey: (item: TItem, index: number) => string;
  /**
   * Ниже этого количества строк виртуализация не включается: она усложняет
   * поиск по странице и выделение текста, а выигрыша на коротком списке нет.
   */
  threshold?: number;
  /**
   * Ключ строки, до которой докрутить список (агент панели показывает право):
   * невидимой строки нет в DOM, и найти её там нечем. Один раз на ключ.
   */
  scrollToKey?: string;
  /**
   * Метка просьбы докрутить: сменилась при том же ключе — докрутить снова
   * (агент показал ту же строку повторно, а человек успел уйти от неё).
   */
  scrollNonce?: string | number;
}

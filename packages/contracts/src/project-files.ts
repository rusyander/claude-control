/**
 * Файлы проекта, открытого в чате: дерево, содержимое, запись и «что здесь
 * поменял агент».
 *
 * Раздел отвечает на вопрос, ради которого он и заведён: разговор закончился —
 * что именно изменилось в коде. База сравнения берётся НЕ из git, а из самого
 * транскрипта: `Edit`/`MultiEdit`/`Write` несут `old_string` и `new_string`,
 * поэтому «до» восстанавливается обратной прокруткой правок по текущему тексту.
 * Так дифф показывает работу ЭТОГО разговора, а не всё, что накопилось в
 * рабочем дереве, и работает в каталоге без git.
 *
 * Старого текста в файле уже нет — он удалён, — поэтому клиент правит текущее
 * содержимое, а «было» показывает поверх него декорациями.
 */

/** Одна запись дерева проекта: каталог или файл. */
export interface ProjectFileNode {
  name: string;
  /** Путь от корня проекта; разделитель всегда `/`, даже на Windows. */
  path: string;
  isDir: boolean;
  /** Только у файлов. */
  sizeBytes?: number;
}

/** Содержимое одного каталога: дерево грузится по уровню, а не целиком. */
export interface ProjectFileTree {
  /** Каталог, чьё содержимое перечислено; пусто — корень проекта. */
  dir: string;
  entries: ProjectFileNode[];
  /** Записей больше потолка: показан не весь каталог. */
  truncated: boolean;
}

/** Сводка правок агента по одному файлу — для отметок в дереве. */
export interface ProjectFileChange {
  path: string;
  added: number;
  removed: number;
  /** Файла нет на диске: агент его правил, а потом файл удалили или переименовали. */
  missing: boolean;
}

export interface ProjectFileChanges {
  files: ProjectFileChange[];
  /**
   * Правки, которые не удалось привязать к файлу проекта: путь вне каталога
   * или инструмент, чей формат панель не разбирает (например, блокноты).
   */
  skipped: number;
}

/** Насколько можно верить восстановленному «до». */
export type ProjectFileBaselineKind =
  /** Прежний текст восстановлен по правкам целиком. */
  | 'exact'
  /** Файл перезаписан целиком (`Write`): прежнего текста в транскрипте нет. */
  | 'whole-file'
  /** Правок агента по этому файлу нет — сравнивать не с чем. */
  | 'none';

/**
 * Чем файл показывать вместо текста (или вместе с ним).
 *
 * Решает расширение, а не содержимое: панель не угадывает формат по байтам —
 * ошибиться здесь значит выдать за картинку то, что ею не является. Пусто —
 * обычный текст, показывать нечем, кроме редактора.
 */
export type ProjectFilePreview =
  /** Растровая картинка — тянется браузером по адресу `project-files/raw`. */
  | 'image'
  /** SVG: рисунок собирается из текста файла, поэтому правится тут же. */
  | 'svg'
  /** PDF — встроенный просмотрщик браузера. */
  | 'pdf'
  /** Markdown: текст и его разметка — две вкладки одного файла. */
  | 'markdown';

/** Файл, открытый в редакторе: текущий текст плюс всё, что нужно для диффа. */
export interface ProjectFileContent {
  path: string;
  /** Текущее содержимое — именно оно правится и сохраняется. */
  content: string;
  /** Содержимое до правок агента в этом разговоре. Нет — при `kind: 'none'`. */
  baseline?: string;
  kind: ProjectFileBaselineKind;
  added: number;
  removed: number;
  /**
   * Правки агента, которых не нашлось в текущем тексте: файл меняли и мимо
   * этого разговора. Дифф от этого неполон, и клиент обязан сказать об этом.
   */
  unmatched: number;
  /** Двоичный файл: показываем факт, но не текст и не дифф. */
  isBinary: boolean;
  /**
   * Формат, который показывается не текстом. У картинки и PDF при этом
   * `isBinary: true` и пустой `content` — сами байты клиент берёт отдельным
   * запросом, чтобы не гонять их через JSON в base64.
   */
  preview?: ProjectFilePreview;
  sizeBytes: number;
  /** Время последней записи на диске — с ним же файл уходит обратно. */
  mtimeMs: number;
  /** Слишком велик для сравнения: текст отдан, дифф не строился. */
  tooBig: boolean;
  /** Файл только для чтения (права ОС) — правку клиент не предлагает. */
  isReadOnly: boolean;
}

/** Запрос на запись. `mtimeMs` — тот, что пришёл с содержимым. */
export interface ProjectFileSaveRequest {
  path: string;
  file: string;
  content: string;
  mtimeMs: number;
}

export interface ProjectFileSaveResult {
  mtimeMs: number;
  sizeBytes: number;
  /** Куда легла копия прежней версии; пусто — копии отключены в настройках. */
  backupPath?: string;
}

/**
 * Что открыто в окне кода у одного таба проекта.
 *
 * Живёт на сервере, в `state.json`, а не в браузере: у панели уже есть
 * собственный файл состояния, и класть туда же — значит пережить и чистку
 * кэша, и другой браузер. Ключ — тот же нормализованный путь проекта, что
 * служит идентификатором таба, поэтому у каждого таба своё дерево и свой
 * открытый файл, а закрытие таба эту запись стирает.
 */
export interface ProjectCodeView {
  /** Открытый файл — путь от корня проекта. Пусто — не открыт ни один. */
  file?: string;
  /** Раскрытые каталоги дерева — пути от корня проекта. */
  openDirs: string[];
  /** Показывать правки агента поверх текста. */
  showDiff: boolean;
  /** Активен список «Изменённые», а не всё дерево. */
  onlyChanged: boolean;
}

/**
 * Раскладка окна кода — ОДНА на панель, а не на проект.
 *
 * Ширина колонки с файлами — привычка человека, а не свойство репозитория:
 * настроив её один раз, он ждёт ту же ширину в любом проекте. Поэтому она
 * лежит рядом со снимками табов, но отдельным полем без ключа проекта.
 */
export interface ProjectCodeLayout {
  /** Ширина списка файлов в пикселях. Границы — `contracts/project-code`. */
  treeWidth: number;
}

import type { ArchiveManifest } from './archive.types.ts';

/**
 * README внутри архива. Его читают двое: человек, который развернёт архив на
 * новой машине, и модель, которой скажут «разбери и подхвати». Поэтому он на
 * русском (человеческий документ) и одновременно строго перечисляет, что где
 * лежит — модели этого достаточно, чтобы разложить файлы без панели.
 *
 * Здесь же честно сказано, чего в архиве НЕТ: секретов, истории диалогов и
 * настроек самой панели. Иначе на новой машине это выглядело бы как потеря.
 */
export function buildArchiveReadme(manifest: ArchiveManifest): string {
  const { provider, exportedAt, source } = manifest;
  const totalBytes = manifest.entries.reduce((sum, entry) => sum + entry.bytes, 0);

  const locations = manifest.locations
    .map(
      (location) =>
        `- \`files/loc-${location.index}/\` → ${location.kind === 'dir' ? 'каталог' : 'файл'} ` +
        `\`${location.sourcePath}\` (раздел: ${location.role})`,
    )
    .join('\n');

  const checklist =
    manifest.checklist.length === 0
      ? '- ничего: секретов в конфигурации не нашлось'
      : manifest.checklist
          .map((item) => {
            const keys = item.keys.length > 0 ? `: ${item.keys.join(', ')}` : '';
            return `- ${describeChecklistReason(item.reason)} — \`${item.source}\`${keys}`;
          })
          .join('\n');

  return `# Окружение ${provider.name} — перенос на другую машину

Собрано панелью claude-control ${exportedAt} на платформе \`${source.platform}\`.
Файлов: ${manifest.entries.length}, размер до сжатия: ${formatBytes(totalBytes)}.

## Что внутри

- \`MANIFEST.json\` — полная опись: откуда каждый файл, его размер и контрольная сумма.
- \`README.md\` — этот файл.
- \`files/loc-<номер>/…\` — сама конфигурация. Номер соответствует месту:

${locations}

## Как развернуть

**Через панель (рекомендуется):** Настройки → «Перенос окружения» → «Импорт» у нужного
провайдера → выбрать этот архив. Панель покажет, какие файлы новые, какие отличаются от
уже имеющихся, и запишет только отмеченные — каждый перезаписываемый файл уходит в
резервную копию.

**Руками:** содержимое \`files/loc-<номер>/\` положить в каталог, указанный выше для этого
номера, но по путям НОВОЙ машины (домашняя папка и разделители там другие).

**Через саму модель:** распакуйте архив и скажите ассистенту примерно так:

> Я пользовался тобой на другой машине. В папке <путь к распакованному архиву> лежит
> экспорт моего окружения: прочитай MANIFEST.json и README.md, посмотри, какие там
> инструкции, правила, скиллы, хуки и MCP-серверы, и разложи их в мою конфигурацию —
> сначала покажи, что именно собираешься записать.

## Чего в архиве нет

- **Секретов.** Токены, ключи API, файлы доступа и \`.env\` не переносятся. Что придётся
  ввести на новой машине:

${checklist}

- **Истории диалогов, логов и кэшей** — это не настройка, а хвост работы прежней машины.
- **Настроек самой панели** (группы, связи, оформление) — они переносятся отдельной
  кнопкой снимка настроек в том же разделе.
- Файлы, которые не поместились или оказались нечитаемыми, перечислены в \`MANIFEST.json\`
  в поле \`skipped\`.

Значения секретных ключей внутри конфигов заменены меткой \`__REDACTED__\` — найдите её
поиском после разворота. Скрипты хуков скопированы как есть: если в них зашит токен,
уберите его перед тем, как передавать архив кому-то ещё.
`;
}

function describeChecklistReason(reason: string): string {
  if (reason === 'env-file') return 'переменные окружения';
  if (reason === 'secret-file') return 'файл с секретами не переносился';
  return 'значения заменены меткой';
}

function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} Б`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} КБ`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} МБ`;
}

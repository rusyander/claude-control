import type { EmitEntry } from '@agentdeck/contracts/portable-emit';
import type { AgentEnvironment, EnvItemKind, EnvScope } from '@agentdeck/contracts/portable-env';
import type { ConfigProvider } from '../../../providers/types.ts';

/**
 * Договор эмиссии: что эмиттеру дают и что он возвращает.
 *
 * Эмиттер НИЧЕГО не знает об импортёрах — общего у половин ровно два, канон и
 * каталог возможностей (§5.3 плана). Пары «источник → приёмник» в коде нет:
 * эмиттер видит записи канона и факты ЦЕЛИ, и откуда записи приехали, его не
 * касается.
 */

/** Что нужно эмиттеру, чтобы разложить канон по файлам одной цели на одном уровне. */
export interface EmitDeps {
  /** Провайдер-ЦЕЛЬ: его каталог возможностей решает всё. */
  target: ConfigProvider;
  scope: EnvScope;
  /** Пользовательский каталог конфигурации; уважает его только Claude. */
  override?: string;
  /**
   * Корень проекта — обязателен при `scope: 'project'` и не значит ничего при
   * глобальном (П2.5). Уровень выбирает ПУТИ, а не набор слоёв записи.
   */
  projectRoot?: string;
}

/**
 * Одна запись в ОДИН файл цели.
 *
 * Запись не исполняется при построении плана: П2.3 сначала показывает человеку
 * дифф каждого файла (песочница `provider-preview.runPreview`), и только потом
 * применяет. Поэтому здесь ОПИСАНИЕ действия с двумя способами его выполнить —
 * по настоящему пути и по подставленному.
 *
 * `itemIds` — множественное число не от щедрости: инструкции всех записей
 * сливаются у цели в ОДИН файл, и строка плана обязана назвать все записи,
 * которые в него вошли, иначе дифф одного файла выглядел бы правкой одной
 * записи.
 */
export interface EmitWrite {
  readonly kind: EnvItemKind;
  readonly itemIds: readonly string[];
  /** Файл цели, который изменится. */
  readonly filePath: string;
  /** Выполнить запись по настоящему пути. `backupDir` уходит в адаптер формата. */
  apply(backupDir?: string): void;
  /**
   * Сколько КОНЦЕВЫХ отрезков пути обязана сохранить песочница предпросмотра.
   *
   * По умолчанию один — адаптеру важен сам файл. Просит о большем та запись,
   * чей адаптер выводит из пути больше, чем имя файла: у скилла имя папки
   * обязано совпадать с именем скилла, а `SKILL.md` у всех скиллов один. С
   * плоской копией такой адаптер либо отказывает, либо пишет МИМО песочницы, и
   * предпросмотр показывает пустой дифф вместо нового файла.
   */
  readonly sandboxSegments?: number;
  /**
   * Та же запись по ПОДСТАВЛЕННОМУ пути — копия файла в песочнице предпросмотра.
   * Резервная копия при этом не делается: её делает настоящая запись, а
   * предпросмотр не должен вытеснять историю из ротации (то же решение, что в
   * `provider-preview.ts`).
   */
  applyTo(filePath: string): void;
}

/**
 * План эмиссии: строка на каждую запись паспорта плюс список файловых правок.
 *
 * Два списка, а не один, потому что отвечают они на разные вопросы: `entries` —
 * что будет с каждой записью канона (включая те, что никуда не лягут), `writes`
 * — какие файлы цели изменятся. Одна запись канона может не дать ни одной
 * правки, а одна правка — собрать несколько записей.
 */
export interface EmitPlan {
  /** Идентификатор провайдера-цели. */
  readonly target: string;
  readonly scope: EnvScope;
  /** Корень цели: дом провайдера или каталог проекта. */
  readonly root: string;
  readonly entries: readonly EmitEntry[];
  readonly writes: readonly EmitWrite[];
}

export type Emitter = (env: AgentEnvironment, deps: EmitDeps) => EmitPlan;

/** Эмиттера для этого id в каталоге нет — одиннадцатый CLI без своего файла (§5.4). */
export class UnknownEmitProviderError extends Error {
  readonly providerId: string;

  constructor(providerId: string) {
    super(`Эмиттер среды для провайдера «${providerId}» не заведён.`);
    this.name = 'UnknownEmitProviderError';
    this.providerId = providerId;
  }
}

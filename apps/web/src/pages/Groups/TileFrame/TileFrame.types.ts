import type { ReactNode } from 'react';

export interface TileFrameProps {
  name: string;
  onOpen: () => void;
  badges: ReactNode;
  /**
   * Строка «Когда» как есть; пусто — карточка пишет `whenEmpty` приглушённо.
   * Запасной текст подставляет рамка, а не вызывающий: подставленный заранее,
   * он делал строку непустой, и приглушение не срабатывало никогда.
   */
  when: string;
  /** Что сказать вместо пустого «Когда». */
  whenEmpty: string;
  whenLabel: string;
  /** Тело карточки между «Когда» и числами: превью шагов, состав по видам, проекты. */
  children?: ReactNode;
  /** Нижняя строка чисел: «4 шага · 2 участника». */
  counts: string;
  /**
   * «В проекте изменилось: …», «Нет файла у участника: …» — видно и на карточке:
   * это просьба о действии. Каждое — своей строкой: склеенные через точку, они
   * читались одной фразой.
   */
  warnings?: readonly string[];
  /** Справа от имени: «Копировать» и тумблер группы. */
  aside?: ReactNode;
  /** Якорь для агента панели: по нему он показывает карточку. */
  anchor?: string;
  /** Второй якорь той же карточки — проектная половина связанной пары. */
  anchorAlias?: string;
}

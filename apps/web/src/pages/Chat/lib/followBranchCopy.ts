import { projectShortName, workspace } from '@shared/lib/workspace';

/**
 * Разговор переехал в копию, заведённую из карточки ворот ветки, — человек
 * переезжает за ним (Ф-6), как после «Открыть» в окне «Параллельные ветки».
 *
 * Сервер поднимает тот же разговор с рабочей папкой копии, и дальше чат сам
 * считает копию своим домом: во вкладке основной копии он больше не свой.
 * Оставить человека там — значит показать разговор не своего проекта, а
 * копию, где теперь идёт работа, заставить искать самому. Вкладка копии
 * запоминает этот разговор ДО того, как эффект смены вкладки его спросит:
 * иначе там встал бы пустой черновик. Каталог, уже видный в открытой вкладке,
 * второй вкладки не получает — тот же `reveal`, что у продолжения.
 */
export function followBranchCopy(path: string, viewId: string | undefined): string {
  const tabId = workspace.reveal(path, projectShortName(path));
  if (viewId) workspace.rememberView(tabId, viewId);
  return tabId;
}

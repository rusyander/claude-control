/** Карточка «Ждёт вас» задачи ядра во «Вопросах» телефона. */
export interface CoreWaitingCard {
  taskId: string;
  /** Заголовок задачи; `null` — без заголовка (экран подставит «Задача без заголовка»). */
  title: string | null;
  /** Сколько блокирующих вопросов держат задачу. */
  count: number;
  /** Текст первого блокирующего вопроса из вида задачи; пусто — ядро его не прислало. */
  question: string;
}

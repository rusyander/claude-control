/** Сколько последних меток помнить: сообщений человека за часы работы — сотни, не тысячи. */
const SENT_ONCE_CAP = 2000;

/**
 * Метки сообщений, уже отданных агенту (`clientId` тела отправки).
 *
 * Слово на ходу доходит до агента, а ответ на запрос клиент может потерять:
 * обрыв связи, телефон ушёл в фон, запрос дольше срока ожидания. Клиент тогда
 * ставит слово в свою очередь и досылает его по концу хода новым запуском —
 * агент получал ответ человека дважды, а группа на паузе просыпалась от
 * второго (карточка 33 прогона 20.10). Повтор метки сервер узнаёт здесь.
 *
 * Только память процесса и только последние `SENT_ONCE_CAP`: перезапуск
 * панели между словом и досылкой метку теряет — тогда держит пауза группы
 * (`automatic`), а не эта страховка.
 */
export class SentOnce {
  private readonly ids = new Set<string>();

  has(id: string): boolean {
    return this.ids.has(id);
  }

  remember(id: string): void {
    this.ids.delete(id);
    this.ids.add(id);
    // Set держит порядок вставки — первая метка и есть самая старая.
    while (this.ids.size > SENT_ONCE_CAP) {
      const oldest = this.ids.values().next().value;
      if (oldest === undefined) break;
      this.ids.delete(oldest);
    }
  }
}

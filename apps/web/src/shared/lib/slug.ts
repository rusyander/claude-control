/**
 * Слаг имени — тот же алгоритм, что у сервера (`apps/server/src/lib/slug.ts`).
 *
 * Идентификатор скиллу выдаёт сервер (это имя папки), фронту он нужен ровно для
 * одного: сразу после создания открыть дерево файлов нового скилла, не дожидаясь
 * перечитывания списка. Своя урезанная версия (латиница без транслитерации и без
 * ограничения длины) на русском имени давала ПУСТУЮ строку — дерево и заготовка
 * структуры молча не применялись к только что созданному скиллу.
 *
 * Расхождение с сервером ловится тестом: таблица случаев в `slug.test.ts`
 * повторяет ожидания серверных тестов.
 */
const TRANSLIT: Record<string, string> = {
  а: 'a',
  б: 'b',
  в: 'v',
  г: 'g',
  д: 'd',
  е: 'e',
  ё: 'e',
  ж: 'zh',
  з: 'z',
  и: 'i',
  й: 'y',
  к: 'k',
  л: 'l',
  м: 'm',
  н: 'n',
  о: 'o',
  п: 'p',
  р: 'r',
  с: 's',
  т: 't',
  у: 'u',
  ф: 'f',
  х: 'h',
  ц: 'c',
  ч: 'ch',
  ш: 'sh',
  щ: 'sch',
  ъ: '',
  ы: 'y',
  ь: '',
  э: 'e',
  ю: 'yu',
  я: 'ya',
};

/** Длина, после которой сервер режет слаг: id уходит в имя папки. */
const MAX_LENGTH = 60;

export function slugify(text: string, maxLength: number = MAX_LENGTH): string {
  return text
    .toLowerCase()
    .split('')
    .map((char) => TRANSLIT[char] ?? char)
    .join('')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, maxLength);
}

/**
 * Чем провайдер ЗАПУСКАЕТСЯ: имя бинаря CLI и метаданные модельного API, по
 * которым панель резолвит раннер ассистента (`api` / `cli` / `none`).
 */
import type { ProviderEditsControl } from '@agentdeck/contracts';

/** Имена исполняемого файла CLI: обычное и windows-обёртка (`.cmd`). */
export interface ProviderCli {
  command: string;
  windowsCommand: string;
}

/**
 * Тип модельного API провайдера — какой ключ и какого рода ему нужен, чтобы
 * ассистент панели ходил в модель напрямую (режим `api`). `none` — у провайдера
 * нет собственного модельного API (Cursor): прямой вызов невозможен.
 */
export type AssistantApiKind = 'anthropic' | 'openai' | 'google' | 'openai-compat' | 'none';

/**
 * Вид API СВОЕГО эндпоинта. Уже, чем `AssistantApiKind`: для чужого адреса
 * `openai` и `openai-compat` — одно и то же, а `none` эндпоинтом не бывает.
 * Значение то же, что в контракте (`packages/contracts/src/endpoints.ts`);
 * вторая копия здесь потому, что contracts входит в сервер только типом.
 */
export type ProviderEndpointApiKind = 'anthropic' | 'google' | 'openai-compat';

/**
 * ЗАДОКУМЕНТИРОВАННЫЕ имена переменных окружения, которыми CLI переводится на
 * свой адрес модели. Ключ — вид API; CLI, понимающий два протокола (Qwen),
 * объявляет оба.
 *
 * ПРАВИЛО 3 (форматы только из документации) действует здесь буквально: имя
 * переменной либо названо в документации CLI, либо этого CLI тут нет. Молча не
 * сработавшая переменная хуже честного отказа — человек будет уверен, что
 * трафик уходит на его сервер, а он уходит в облако.
 *
 * Кого тут НЕТ и почему:
 * - Codex: `base_url` задаётся только в `config.toml` (таблица
 *   `model_providers`), переменной окружения для него не задокументировано;
 *   `env_key` называет лишь имя переменной С КЛЮЧОМ, а не адрес.
 * - Continue: адрес — поле `apiBase` у модели в `config.yaml`; глобальной
 *   переменной окружения нет, `~/.continue/.env` хранит только секреты.
 * - Goose, Kimi, OpenCode, Cursor: своего файла переменных окружения нет вовсе
 *   (`env = unsupported`), писать некуда.
 */
export interface ProviderEndpointVars {
  /** Имя переменной базового адреса — обязательно, иначе профиль бессмыслен. */
  baseUrlEnv: string;
  /** Имя переменной модели. Нет — панель модель не переносит. */
  modelEnv?: string;
  /**
   * Имя переменной, в которой CLI ждёт токен доступа к эндпоинту. Здесь лежит
   * ТОЛЬКО имя; само значение — в зашифрованном хранилище панели и пишется в
   * конфиг лишь по явной галочке пользователя.
   */
  credentialEnv?: string;
  /**
   * Настройка конфига человека, при которой CLI переменную адреса НЕ прочтёт
   * (Gemini: способ входа не ключом API), — её имя. Тогда контур не пишет адрес
   * ни в файл, ни в окружение прогона: настройка, которая молча не действует,
   * хуже названного отказа. Смысл тот же, что у `ProviderRunEndpoint.bypass`.
   */
  bypass?: () => string | undefined;
}

export type ProviderEndpointConfig = Partial<Record<ProviderEndpointApiKind, ProviderEndpointVars>>;

/**
 * Адрес эндпоинта, задаваемый НЕ переменной окружения, а куском конфигурации.
 *
 * Заведено для двух CLI, у которых документация прямо говорит: адрес живёт в
 * файле. Codex — таблица `model_providers` в `config.toml`, Continue — поле
 * `apiBase` у модели в `config.yaml`. Через окружение эти двое адрес не берут,
 * поэтому у них нет `endpointConfig`, — но и прочерком в списке они стоять не
 * должны: способ задокументирован, просто он другой.
 *
 * Правка — всегда хирургическая, регионом: остальной файл обязан остаться
 * байт-в-байт (`lib/codex-toml/codex-toml.ts`, `lib/continue-yaml.ts`).
 */
export interface ProviderEndpointFile {
  /** Какой из двух форматов правится — по нему выбирается писатель. */
  format: 'codex-toml' | 'continue-yaml';
  /** Путь к файлу; `override` уважает только claude, у остальных он не при чём. */
  path: (override?: string) => string;
  /** Диалект, на котором CLI пойдёт по этому адресу. */
  apiKind: ProviderEndpointApiKind;
  /**
   * КАКОЙ ручкой CLI пойдёт по этому адресу — и это не то же самое, что `apiKind`.
   *
   * Оба здешних CLI «OpenAI-совместимы», но ручки у них разные: Continue идёт в
   * `/chat/completions`, а Codex с версии, снявшей `wire_api = "chat"`
   * (`openai/codex#7782`), умеет только `/responses`. Шлюз панели обслуживает
   * четыре маршрута, и `responses` среди них нет
   * (`platform/gateway/pipeline.ts`, `GATEWAY_ROUTES`).
   *
   * Поле заведено живой пробой 22.09.2026 на настоящем `codex-cli 0.155.1`:
   * конфиг, написанный панелью с `wire_api = "chat"`, этот CLI не загружает
   * ЦЕЛИКОМ — падает любой его запуск, а не только запрос через контур. Пока
   * шлюз не знает ручку, цель обязана быть прочерком с причиной, а не записью,
   * которая ломает человеку CLI.
   */
  wireApi: 'chat' | 'responses';
}

/** Адрес шлюза, модель и заглушка ключа — то, из чего собирается окружение прогона. */
export interface RunEndpointInput {
  /** Адрес шлюза под этот прогон, с `/v1` на конце (диалект `openai-compat`). */
  baseUrl: string;
  /** Модель контура; пусто — контур модель не назвал. */
  model: string;
  /** Заглушка: настоящий ключ подставляет шлюз. */
  key: string;
}

/**
 * Адрес эндпоинта ОДНОГО прогона, собранный окружением, у которого нет ни
 * раздела переменных в файлах CLI, ни тройки «адрес · модель · ключ».
 *
 * Заведено для Kimi Code (`KIMI_MODEL_*`), Goose (`GOOSE_PROVIDER` +
 * `OPENAI_HOST`/`OPENAI_BASE_PATH`) и OpenCode (`OPENCODE_CONFIG_CONTENT`): все
 * три задокументированы как переменные, перебивающие конфиг человека, но
 * писать их в его файлы некуда — поэтому только прогон панели, без «Терминала».
 * Модель едет в окружении, и флагом модели прогон её НЕ получает: имя модели
 * контура для этих CLI — не псевдоним их конфига.
 */
export interface ProviderRunEndpoint {
  /** Диалект, которым CLI пойдёт по адресу. */
  apiKind: 'openai-compat';
  env: (input: RunEndpointInput) => Record<string, string>;
  /**
   * Настройка в конфиге человека, которая увела бы ЧАСТЬ прогона мимо контура
   * (своя модель субагентов, ведущая модель другого провайдера), — её имя.
   * Переменной, перебивающей её, документация не называет, поэтому прогон
   * отказывает, а не уходит наполовину в облако вендора.
   */
  bypass?: () => string | undefined;
}

/**
 * Метаданные ассистента провайдера (мульти-модельность, Ф6a).
 *
 * Гибрид выбора раннера: есть API-ключ (сохранён в панели или в стандартной
 * env-переменной) → режим `api`; ключа нет, но CLI провайдера установлен →
 * режим `cli`; иначе → `none` (панель просит ключ). Реальных вызовов моделей на
 * этой фазе НЕТ — только резолвинг раннера и хранение ключей.
 *
 * - `apiKind` — тип модельного API (по нему панель понимает, ключ какого рода
 *   нужен); `none` означает, что прямого модельного API у CLI нет.
 * - `apiKeyEnvVars` — стандартные переменные окружения, из которых ключ
 *   подхватывается автоматически. ТОЛЬКО заявленные имена — форматы чужих
 *   конфигов не угадываем.
 * - `cliRunnable` — можно ли запустить ассистента через CLI провайдера (когда
 *   ключа нет, но бинарь найден в PATH). У Cursor — false (ассистент unsupported).
 * - `oneShotArgs` — argv для НЕинтерактивного one-shot запуска CLI (Ф6b): промпт
 *   передаётся ОТДЕЛЬНЫМ элементом массива (без интерполяции в shell). Задаётся
 *   ТОЛЬКО там, где print-флаг задокументирован (gemini `-p`, codex `exec`); у
 *   остальных не задан → программный запуск через CLI невозможен (падаем в
 *   api/none). Claude сюда НЕ входит — он делегирует своему существующему пути.
 */
/**
 * Чем вести ЭТОТ прогон, если панель подобрала модель под класс работы
 * (`domains/provider-cascade/provider-cascade.ts`). Пусто — панель ничего не подбирала, и CLI
 * работает своей настроенной моделью: подставлять её вместо человека нельзя,
 * панель не знает ни его подписки, ни доступных ему моделей.
 */
export interface OneShotRun {
  /** Конкретное имя модели из каталога models.dev — в том виде, что ждёт CLI. */
  model?: string;
  /** Аналог глубины (`low`/`medium`/`high`). Есть только у Codex. */
  effort?: string;
  /**
   * «Разрешить правки» разговора. Флаг под него ставят только CLI, у которых он
   * проверен по `--help` (codex `--sandbox`, qwen `--approval-mode`); не задан —
   * argv как до переключателя. Спросить человека одиночный запуск не может,
   * поэтому `false` — запрет правок, а не вопрос.
   */
  allowEdits?: boolean;
  /**
   * Каталог, в котором запустится CLI (каталог разговора, временная папка
   * ассистента). Не задан — CLI стартует в каталоге сервера панели. Читает его
   * тот, чьё поведение от каталога зависит: Aider вне репозитория сам делает
   * `git init`, если не передать `--no-git`.
   */
  workdir?: string;
}

export interface ProviderAssistant {
  apiKind: AssistantApiKind;
  apiKeyEnvVars: string[];
  cliRunnable: boolean;
  /**
   * Второй аргумент — подбор модели под задачу (Т12). Каждый CLI собирает argv
   * САМ: место флага в командной строке у них разное (`codex exec -m … <промпт>`
   * против `gemini -m … -p <промпт>`), и общей склейки, которая была бы верна
   * для всех, не существует. CLI, у которого способ передать модель не
   * задокументирован, второй аргумент просто игнорирует — и тогда у него не
   * должно быть `modelLadder` (см. `ConfigProvider`).
   */
  oneShotArgs?: (prompt: string, run?: OneShotRun) => string[];
  /**
   * Добавка к окружению ТОГО ЖЕ одиночного запуска — для CLI, которому режим
   * прогона задокументирован переменной, а флага у него нет (Goose: `GOOSE_MODE`;
   * у `goose run` флага режима нет). Читает тот же `run`, что и `oneShotArgs`;
   * `undefined` — окружение как было. Ложится поверх окружения контура и слоя
   * группы: переключатель разговора — решение человека на этот прогон.
   */
  oneShotEnv?: (run?: OneShotRun) => Record<string, string> | undefined;
  /**
   * ПРОТОКОЛ локального сервера CLI, дающего СЕССИОННЫЙ (богатый) режим ассистента
   * вместо one-shot: диалог держит сам CLI, панель шлёт только новое сообщение.
   *
   * Значение называет протокол, а не просто «умеет сервер»: реализация под него
   * лежит в отдельном домене (`domains/opencode-serve/opencode-serve.ts`). Не задан → сессионного
   * режима у провайдера нет, и панель его не выдумывает (fail-closed). Сейчас
   * задокументирован ровно один — `opencode serve`.
   */
  sessionServer?: 'opencode';
  /**
   * Серверный режим CLI, в котором у ОДНОГО ответа есть вход посреди хода (В1):
   * ход запускается через него, и сообщение, написанное пока CLI отвечает,
   * уходит в этот же ход, а не в очередь. Реализации — `domains/provider-chat/live/`.
   * Не поднялся — ответ идёт обычным `oneShotArgs`, а сообщение ждёт в очереди.
   */
  liveServer?: 'codex-app-server' | 'qwen-serve' | 'goose-acp' | 'kimi-server';
  /**
   * Базовый адрес СОБСТВЕННОГО модельного API вендора для прямого вызова
   * (`<apiBaseUrl>/chat/completions`), например `https://api.example.com/v1`.
   * Нужен виду `openai-compat`: «совместимый» не говорит, ЧЕЙ это сервер, и
   * подставлять адрес OpenAI значило бы отдать ключ одного вендора другому.
   * Не задан — прямой вызов обязан отказать (`assistant-api-base-unknown`),
   * а не угадывать. Значение — только из документации вендора (правило 3).
   */
  apiBaseUrl?: string;
  /**
   * Чем CLI слушается переключателя «Разрешить правки» в чате (`flag` / `live` /
   * `none`, смысл — `ProviderEditsControl` в контракте). Не задан = `none`.
   * Объявление должно совпадать с кодом: `flag` — `oneShotArgs` (или
   * `oneShotEnv`) читает `run.allowEdits`; `live` — есть `liveServer`, отвечающий через
   * `decidePermission`, а одиночный запуск флага не ставит.
   */
  editsControl?: ProviderEditsControl;
  /**
   * Разбор stdout одиночного запуска в текст ответа — для CLI, которые печатают
   * вокруг ответа служебный вывод или отвечают потоком JSON. Вызывается один раз
   * на прогон и отдаёт свежий разборщик: у потокового формата есть состояние
   * (недочитанная строка). Не задан — stdout и есть ответ, как было.
   */
  parseStdout?: () => ProviderStdoutParser;
}

/**
 * Разборщик stdout одного прогона. `push` получает очередной декодированный кусок
 * и возвращает текст, который пора показать (может быть пустым); `end` — остаток
 * после закрытия потока. Склейка всех возвратов = ответ.
 */
export interface ProviderStdoutParser {
  push(chunk: string): string;
  end(): string;
  /**
   * CLI сам сообщил в потоке, что ход кончился удачно (у Gemini — событие
   * `result` со `status: "success"`). Тогда ненулевой код выхода после него —
   * сбой на выходе процесса, а не ответа: ответ принимается. Не задан — решает
   * только код выхода.
   */
  settled?(): boolean;
}

export interface ProjectGitControlsProps {
  /** Абсолютный путь каталога проекта. Нет `.git` — пульт не рисуется вовсе. */
  path: string;
  /**
   * Как показать сам пульт: `button` — кнопка в плотном ряду (вкладка проекта),
   * `strip` — полоса над лентой чата, где к ветке добавлены числа правок.
   * Поповер у обоих один и тот же.
   */
  variant?: 'button' | 'strip';
  /**
   * Идёт ли прогон в этом каталоге. Пока агент работает, состояние
   * перечитывается чаще: ветку он меняет за секунды.
   */
  isRunning?: boolean;
}

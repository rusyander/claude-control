/**
 * Контур — корпоративная платформа, к которой панель ходит по одному ключу:
 * её модели, эмбеддинги и агенты вместо облака вендора.
 *
 * Сущность уровня панели, а не провайдера: ключ один на всю машину, и держать
 * его копию в разделе каждого CLI значило бы вернуть ровно тот ручной ввод
 * адреса и токена, ради отмены которого контур и заводится. Токена здесь НЕТ и
 * быть не может: он лежит в зашифрованном хранилище панели (`platform:<id>`), а
 * `state.json` — открытый текст, который уезжает с машины на машину экспортом.
 *
 * ВЕТВЛЕНИЕ ТОЛЬКО ПО ВОЗМОЖНОСТЯМ. Ни одного `if (platform.id === 'enterprise-platform')`
 * вне драйвера: платформа отвечает, что умеет, панель спрашивает возможность.
 * Иначе второй контур в другой компании потребует переписать половину панели.
 */

/**
 * Драйвер — единственное место, где знают о конкретной платформе. Какие драйверы
 * есть, решают данные пресетов (`platform-presets.ts`, аудит DRV-03), а не
 * перечень здесь: второй перечень разошёлся бы с первым на первом же новом шлюзе.
 */
/**
 * Чем инструменты клиента доходят до модели этого контура — решение шлюза
 * (`chooseToolRoute`), присланное сервером, а не пересобранное экраном:
 * - `shim` — текстом протокола, прослойкой;
 * - `native` — полем `tools`, платформа его принимает;
 * - `none` — не доходят: тип их не принимает и прослойка выключена, либо ход
 *   заняли инструменты самой платформы. CLI через такой контур — собеседник.
 */
export type PlatformToolRoute = 'shim' | 'native' | 'none';

/**
 * Что делать, когда контур не отвечает. `required` — не работать: отказ контура
 * есть отказ, тихого возврата на прежний апстрим не бывает. `best-effort` —
 * предупредить человека и оставить решение ему.
 */
export const platformModes = ['required', 'best-effort'] as const;
export type PlatformMode = (typeof platformModes)[number];

/**
 * Из идентификатора собирается адрес локального шлюза, поэтому в нём нет ни
 * пробелов, ни слэшей, ни процентов — всего, что в адресе значит другое.
 */
export const platformIdPattern = /^[a-zA-Z0-9][a-zA-Z0-9._-]*$/;

/**
 * День учёта: `YYYY-MM-DD` либо пусто. Дни расхода сравниваются посимвольно, и
 * любая другая запись даты не отказала бы, а тихо исказила период бюджета.
 */
export const platformDayPattern = /^(\d{4}-\d{2}-\d{2})?$/;

/**
 * Настоящий ли это календарный день (или пусто).
 *
 * Одной формы мало: `2026-13-45` и `2026-02-31` проходят по виду, а дней таких
 * нет — и сравнение строк молча не находило бы ни одного дня расхода. Человек
 * при этом видел бы «расход ≈ 0.00 из 100 $» и полосу в нуле ровно там, где
 * тратится, — то есть ошибку ввода в виде спокойного отчёта.
 */
export function isPlatformDay(value: string): boolean {
  if (value === '') return true;
  if (!platformDayPattern.test(value)) return false;
  const date = new Date(`${value}T00:00:00.000Z`);
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value;
}

